/**
 * Resolve a vertex label to its table name.
 */
export function resolveVertexTable(label: string): string {
  const table = VERTEX_TABLE_MAP[label];
  if (!table) {
    throw new Error(`Unknown vertex label: ${label}`);
  }
  return table;
}

/**
 * Resolve an edge type to its table name.
 */
export function resolveEdgeTable(type: string): string {
  const table = EDGE_TABLE_MAP[type];
  if (!table) {
    throw new Error(`Unknown edge type: ${type}`);
  }
  return table;
}

/**
 * Get all vertex table names.
 */
export function getAllVertexTables(): string[] {
  return Object.values(VERTEX_TABLE_MAP);
}

/**
 * Get all edge table names.
 */
export function getAllEdgeTables(): string[] {
  return Object.values(EDGE_TABLE_MAP);
}

#!/usr/bin/env node
// Generate `src/vertex-tier.gen.ts` from `30-graph/deps.toml [vertex_tier.*]`.
// Run after editing deps.toml. Idempotent.

import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, "..", "..", "..");
const depsTomlPath = path.resolve(repoRoot, "30-graph", "deps.toml");
const outPath = path.resolve(__dirname, "..", "src", "vertex-tier.gen.ts");

function loadTierMap() {
  const text = readFileSync(depsTomlPath, "utf8");
  const out = { A: [], B: [], C: [] };
  const sectionRe = /\[vertex_tier\.tier_([abc])\]\s*([\s\S]*?)(?=\n\[|$)/g;
  let m;
  while ((m = sectionRe.exec(text)) !== null) {
    const tier = m[1].toUpperCase();
    const body = m[2];
    const tablesMatch = body.match(/tables\s*=\s*\[([\s\S]*?)\]/);
    if (!tablesMatch) continue;
    out[tier] = [...tablesMatch[1].matchAll(/"(vertex_[a-z0-9_]+)"/g)].map(
      (x) => x[1]
    );
  }
  return out;
}

function emit(map) {
  const total = map.A.length + map.B.length + map.C.length;
  const banner = `/* eslint-disable */
// GENERATED by scripts/gen-vertex-tier.mjs from 30-graph/deps.toml.
// ADR-0040 vertex DID tier policy. Do not edit by hand.
//   Tier A = first-class actor DID (DNS handle, ADR-0019 + ADR-0029 root)
//   Tier B = sub-path did:etzhayyim  (parent authority 継承, no handle)
//   Tier C = no DID             (reference / classification / crawl / infra)

export type VertexTier = 'A' | 'B' | 'C';

export const VERTEX_TIER_TOTAL = ${total};
`;

  const arr = (tier) =>
    `export const VERTEX_TIER_${tier}: readonly string[] = [\n` +
    map[tier].map((t) => `  '${t}',`).join("\n") +
    "\n] as const;\n";

  const mapEntries = [];
  for (const tier of ["A", "B", "C"]) {
    for (const t of map[tier]) mapEntries.push(`  ['${t}', '${tier}'],`);
  }

  const tierLookup = `
const VERTEX_TIER_MAP = new Map<string, VertexTier>([
${mapEntries.join("\n")}
]);

/** Return the ADR-0040 tier for a vertex_* table, or null if unclassified. */
export function getVertexTier(tableName: string): VertexTier | null {
  return VERTEX_TIER_MAP.get(tableName) ?? null;
}

/** List all vertex_* tables in the given tier. */
export function listVertexTier(tier: VertexTier): readonly string[] {
  if (tier === 'A') return VERTEX_TIER_A;
  if (tier === 'B') return VERTEX_TIER_B;
  return VERTEX_TIER_C;
}
`;

  return banner + "\n" + arr("A") + "\n" + arr("B") + "\n" + arr("C") + tierLookup;
}

const map = loadTierMap();
const text = emit(map);
writeFileSync(outPath, text);
console.log(
  `wrote ${outPath} (A=${map.A.length}, B=${map.B.length}, C=${map.C.length}, total=${
    map.A.length + map.B.length + map.C.length
  })`
);

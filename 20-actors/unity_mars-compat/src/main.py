from kotodama import Runtime
from kotoba import load_schema
from datomic import DatomicClient
import uuid
import datetime

schema = load_schema("../schema/unity_mars.kotoba")
db = DatomicClient.connect()
app = Runtime("unity_mars-compat")


def now():
    return datetime.datetime.utcnow().isoformat()


def new_id(prefix):
    return f"{prefix}_" + uuid.uuid4().hex[:16]


def _persist(entity, rec):
    """Transact a record into Datomic as namespaced EAVT facts."""
    facts = {}
    for k, v in rec.items():
        facts[f"unity_mars.{entity}/{k}"] = v
    db.transact([facts])
    return rec


def _query(entity, eid=None):
    """Read records of an entity from Datomic (optionally by id)."""
    pattern = {"entity": f"unity_mars.{entity}"}
    if eid is not None:
        pattern["id"] = eid
    return db.query(pattern)


def _require(data, fields):
    missing = [f for f in fields if not data.get(f)]
    if missing:
        return {"error": {"message": "Missing required fields: " + ", ".join(missing)}}
    return None


@app.route("/v1/anchors", methods=["POST"])
def create_anchor(request):
    """Create a Anchor."""
    data = request.json or request.form or {}
    err = _require(data, ['x', 'y'])
    if err:
        return err, 400
    rec = {"id": new_id("unitymar_anc")}
    rec["sceneId"] = data.get('sceneId')
    rec["x"] = float(data.get('x') or 0)
    rec["y"] = float(data.get('y') or 0)
    rec["z"] = float(data.get('z') or 0)
    rec["persistent"] = bool(data.get('persistent'))
    rec["createdAt"] = now()
    rec["updatedAt"] = rec["createdAt"]
    _persist("Anchor", rec)
    return rec, 201

@app.route("/v1/anchors", methods=["GET"])
def list_anchors(request):
    """List Anchors."""
    items = _query("Anchor")
    return {"object": "list", "data": items, "count": len(items)}, 200


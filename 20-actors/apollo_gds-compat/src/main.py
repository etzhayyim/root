from kotodama import Runtime
from kotoba import load_schema
from datomic import DatomicClient
import uuid
import datetime

schema = load_schema("../schema/apollo_gds.kotoba")
db = DatomicClient.connect()
app = Runtime("apollo_gds-compat")


def now():
    return datetime.datetime.utcnow().isoformat()


def new_id(prefix):
    return f"{prefix}_" + uuid.uuid4().hex[:16]


def _persist(entity, rec):
    """Transact a record into Datomic as namespaced EAVT facts."""
    facts = {}
    for k, v in rec.items():
        facts[f"apollo_gds.{entity}/{k}"] = v
    db.transact([facts])
    return rec


def _query(entity, eid=None):
    """Read records of an entity from Datomic (optionally by id)."""
    pattern = {"entity": f"apollo_gds.{entity}"}
    if eid is not None:
        pattern["id"] = eid
    return db.query(pattern)


def _require(data, fields):
    missing = [f for f in fields if not data.get(f)]
    if missing:
        return {"error": {"message": "Missing required fields: " + ", ".join(missing)}}
    return None


@app.route("/v1/flights", methods=["POST"])
def create_flight(request):
    """Create a Flight."""
    data = request.json or request.form or {}
    err = _require(data, ['carrier', 'number'])
    if err:
        return err, 400
    rec = {"id": new_id("apollogd_fli")}
    rec["carrier"] = data.get('carrier')
    rec["number"] = data.get('number')
    rec["origin"] = data.get('origin')
    rec["destination"] = data.get('destination')
    rec["status"] = data.get('status')
    rec["createdAt"] = now()
    rec["updatedAt"] = rec["createdAt"]
    _persist("Flight", rec)
    return rec, 201

@app.route("/v1/flights", methods=["GET"])
def list_flights(request):
    """List Flights."""
    items = _query("Flight")
    return {"object": "list", "data": items, "count": len(items)}, 200


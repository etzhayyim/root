from kotodama import Runtime
from kotoba import load_schema
from datomic import DatomicClient
import uuid
import datetime

schema = load_schema("../schema/typeform.kotoba")
db = DatomicClient.connect()
app = Runtime("typeform-compat")


def now():
    return datetime.datetime.utcnow().isoformat()


def new_id(prefix):
    return f"{prefix}_" + uuid.uuid4().hex[:16]


def _persist(entity, rec):
    """Transact a record into Datomic as namespaced EAVT facts."""
    facts = {}
    for k, v in rec.items():
        facts[f"typeform.{entity}/{k}"] = v
    db.transact([facts])
    return rec


def _query(entity, eid=None):
    """Read records of an entity from Datomic (optionally by id)."""
    pattern = {"entity": f"typeform.{entity}"}
    if eid is not None:
        pattern["id"] = eid
    return db.query(pattern)


def _require(data, fields):
    missing = [f for f in fields if not data.get(f)]
    if missing:
        return {"error": {"message": "Missing required fields: " + ", ".join(missing)}}
    return None


@app.route("/v1/forms", methods=["POST"])
def create_form(request):
    """Create a Form."""
    data = request.json or request.form or {}
    err = _require(data, ['title', 'language'])
    if err:
        return err, 400
    rec = {"id": new_id("typeform_for")}
    rec["title"] = data.get('title')
    rec["language"] = data.get('language')
    rec["createdAt"] = now()
    rec["updatedAt"] = rec["createdAt"]
    _persist("Form", rec)
    return rec, 201

@app.route("/v1/forms", methods=["GET"])
def list_forms(request):
    """List Forms."""
    items = _query("Form")
    return {"object": "list", "data": items, "count": len(items)}, 200

@app.route("/v1/forms/<eid>", methods=["GET"])
def get_form(request, eid):
    """Retrieve a Form by id."""
    rows = _query("Form", eid)
    if not rows:
        return {"error": {"message": "Not found"}}, 404
    return rows[0], 200

@app.route("/v1/forms/<eid>", methods=["POST", "PATCH"])
def update_form(request, eid):
    """Update a Form."""
    rows = _query("Form", eid)
    if not rows:
        return {"error": {"message": "Not found"}}, 404
    data = request.json or request.form or {}
    rec = rows[0]
    for k, v in data.items():
        if k in rec and k not in ("id", "createdAt"):
            rec[k] = v
    rec["updatedAt"] = now()
    _persist("Form", rec)
    return rec, 200

@app.route("/v1/forms/<eid>", methods=["DELETE"])
def delete_form(request, eid):
    """Delete a Form."""
    rows = _query("Form", eid)
    if not rows:
        return {"error": {"message": "Not found"}}, 404
    db.retract({"entity": f"typeform.Form", "id": eid})

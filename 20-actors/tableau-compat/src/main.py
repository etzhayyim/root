from kotodama import Runtime
from kotoba import load_schema
from datomic import DatomicClient
import uuid
import datetime

schema = load_schema("../schema/tableau.kotoba")
db = DatomicClient.connect()
app = Runtime("tableau-compat")


def now():
    return datetime.datetime.utcnow().isoformat()


def new_id(prefix):
    return f"{prefix}_" + uuid.uuid4().hex[:16]


def _persist(entity, rec):
    """Transact a record into Datomic as namespaced EAVT facts."""
    facts = {}
    for k, v in rec.items():
        facts[f"tableau.{entity}/{k}"] = v
    db.transact([facts])
    return rec


def _query(entity, eid=None):
    """Read records of an entity from Datomic (optionally by id)."""
    pattern = {"entity": f"tableau.{entity}"}
    if eid is not None:
        pattern["id"] = eid
    return db.query(pattern)


def _require(data, fields):
    missing = [f for f in fields if not data.get(f)]
    if missing:
        return {"error": {"message": "Missing required fields: " + ", ".join(missing)}}
    return None


@app.route("/v1/datasets", methods=["POST"])
def create_dataset(request):
    """Create a Dataset."""
    data = request.json or request.form or {}
    err = _require(data, ['name', 'source'])
    if err:
        return err, 400
    rec = {"id": new_id("tableau_dat")}
    rec["name"] = data.get('name')
    rec["source"] = data.get('source')
    rec["schemaRef"] = data.get('schemaRef')
    rec["rowCount"] = int(data.get('rowCount') or 0)
    rec["createdAt"] = now()
    rec["updatedAt"] = rec["createdAt"]
    _persist("Dataset", rec)
    return rec, 201

@app.route("/v1/datasets", methods=["GET"])
def list_datasets(request):
    """List Datasets."""
    items = _query("Dataset")
    return {"object": "list", "data": items, "count": len(items)}, 200

@app.route("/v1/datasets/<eid>", methods=["GET"])
def get_dataset(request, eid):
    """Retrieve a Dataset by id."""
    rows = _query("Dataset", eid)
    if not rows:
        return {"error": {"message": "Not found"}}, 404
    return rows[0], 200

@app.route("/v1/datasets/<eid>", methods=["POST", "PATCH"])
def update_dataset(request, eid):
    """Update a Dataset."""
    rows = _query("Dataset", eid)
    if not rows:
        return {"error": {"message": "Not found"}}, 404
    data = request.json or request.form or {}
    rec = rows[0]
    for k, v in data.items():
        if k in rec and k not in ("id", "createdAt"):
            rec[k] = v
    rec["updatedAt"] = now()
    _persist("Dataset", rec)
    return rec, 200

@app.route("/v1/datasets/<eid>", methods=["DELETE"])
def delete_dataset(request, eid):
    """Delete a Dataset."""
    rows = _query("Dataset", eid)
    if not rows:
        return {"error": {"message": "Not found"}}, 404
    db.retract({"entity": f"tableau.Dataset", "id": eid})
    return {"id": eid, "deleted": True}, 200


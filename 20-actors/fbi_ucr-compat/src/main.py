from kotodama import Runtime
from kotoba import load_schema
from datomic import DatomicClient
import uuid
import datetime

schema = load_schema("../schema/fbi_ucr.kotoba")
db = DatomicClient.connect()
app = Runtime("fbi_ucr-compat")


def now():
    return datetime.datetime.utcnow().isoformat()


def new_id(prefix):
    return f"{prefix}_" + uuid.uuid4().hex[:16]


def _persist(entity, rec):
    """Transact a record into Datomic as namespaced EAVT facts."""
    facts = {}
    for k, v in rec.items():
        facts[f"fbi_ucr.{entity}/{k}"] = v
    db.transact([facts])
    return rec


def _query(entity, eid=None):
    """Read records of an entity from Datomic (optionally by id)."""
    pattern = {"entity": f"fbi_ucr.{entity}"}
    if eid is not None:
        pattern["id"] = eid
    return db.query(pattern)


def _require(data, fields):
    missing = [f for f in fields if not data.get(f)]
    if missing:
        return {"error": {"message": "Missing required fields: " + ", ".join(missing)}}
    return None


@app.route("/v1/cases", methods=["POST"])
def create_case(request):
    """Create a Case."""
    data = request.json or request.form or {}
    err = _require(data, ['number', 'jurisdiction'])
    if err:
        return err, 400
    rec = {"id": new_id("fbiucr_cas")}
    rec["number"] = data.get('number')
    rec["jurisdiction"] = data.get('jurisdiction')
    rec["status"] = data.get('status')
    rec["filedAt"] = data.get('filedAt')
    rec["createdAt"] = now()
    rec["updatedAt"] = rec["createdAt"]
    _persist("Case", rec)
    return rec, 201

@app.route("/v1/cases", methods=["GET"])
def list_cases(request):
    """List Cases."""
    items = _query("Case")
    return {"object": "list", "data": items, "count": len(items)}, 200

@app.route("/v1/cases/<eid>", methods=["GET"])
def get_case(request, eid):
    """Retrieve a Case by id."""
    rows = _query("Case", eid)
    if not rows:
        return {"error": {"message": "Not found"}}, 404
    return rows[0], 200

@app.route("/v1/cases/<eid>", methods=["POST", "PATCH"])
def update_case(request, eid):
    """Update a Case."""
    rows = _query("Case", eid)
    if not rows:
        return {"error": {"message": "Not found"}}, 404
    data = request.json or request.form or {}
    rec = rows[0]
    for k, v in data.items():
        if k in rec and k not in ("id", "createdAt"):
            rec[k] = v
    rec["updatedAt"] = now()
    _persist("Case", rec)
    return rec, 200

@app.route("/v1/cases/<eid>", methods=["DELETE"])
def delete_case(request, eid):
    """Delete a Case."""
    rows = _query("Case", eid)
    if not rows:
        return {"error": {"message": "Not found"}}, 404
    db.retract({"entity": f"fbi_ucr.Case", "id": eid})
    return {"id": eid, "deleted": True}, 200


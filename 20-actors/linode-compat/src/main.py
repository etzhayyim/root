    """Create a Instance."""
    data = request.json or request.form or {}
    err = _reject_unknown(data, ['id', 'label', 'status', 'region', 'type', 'image', 'created', 'updated'])
    if err:
        return err, 400
    err = _require(data, ['id', 'label'])
    if err:
        return err, 400
    if data.get('status') and data['status'] not in ['running', 'offline', 'booting', 'busy', 'rebooting', 'shutting_down', 'provisioning', 'deleting', 'migrating', 'rebuilding', 'cloning', 'restoring', 'stopped', 'billing_suspension']:
        return {"error": {"message": "invalid status; allowed: " + ", ".join(['running', 'offline', 'booting', 'busy', 'rebooting', 'shutting_down', 'provisioning', 'deleting', 'migrating', 'rebuilding', 'cloning', 'restoring', 'stopped', 'billing_suspension']), "type": "invalid_request_error"}}, 400
    rec = {"id": new_id("linode_ins")}
    rec["id"] = _as_int(data.get('id'))
    rec["label"] = data.get('label')
    rec["status"] = data.get('status')
    rec["region"] = data.get('region')
    rec["type"] = data.get('type')
    rec["image"] = data.get('image')
    rec["created"] = data.get('created')
    rec["updated"] = data.get('updated')
    rec["createdAt"] = now()
    rec["updatedAt"] = rec["createdAt"]
    _persist("Instance", rec)
    return rec, 201


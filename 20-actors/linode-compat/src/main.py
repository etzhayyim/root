from kotodama import Runtime
from kotoba import load_schema
from datomic import DatomicClient
import uuid
import datetime

schema = load_schema("../schema/linode.kotoba")
db = DatomicClient.connect()
app = Runtime("linode-compat")


def now():
    return datetime.datetime.utcnow().isoformat()


def new_id(prefix):
    return f"{prefix}_" + uuid.uuid4().hex[:16]


def _persist(entity, rec):
    """Transact a record into Datomic as namespaced EAVT facts."""
    facts = {}
    for k, v in rec.items():
        facts[f"linode.{entity}/{k}"] = v
    db.transact([facts])
    return rec


def _query(entity, eid=None):
    """Read records of an entity from Datomic (optionally by id)."""
    pattern = {"entity": f"linode.{entity}"}
    if eid is not None:
        pattern["id"] = eid
    return db.query(pattern)


def _require(data, fields):
    missing = [f for f in fields if not data.get(f)]
    if missing:
        return {"error": {"message": "Missing required fields: " + ", ".join(missing)}}
    return None


@app.route("/v1/instances", methods=["POST"])
def create_instance(request):
    """Create a Instance."""
    data = request.json or request.form or {}
    err = _require(data, ['label', 'region'])
    if err:
        return err, 400
    rec = {"id": new_id("linode_ins")}
    rec["label"] = data.get('label')
    rec["region"] = data.get('region')
    rec["image"] = data.get('image')
    rec["group"] = data.get('group')
    rec["ipv6"] = data.get('ipv6')
    rec["type"] = data.get('type')
    rec["status"] = data.get('status')
    rec["hypervisor"] = data.get('hypervisor')
    rec["hostUuid"] = data.get('hostUuid')
    rec["watchdogEnabled"] = bool(data.get('watchdogEnabled'))
    rec["hasUserData"] = bool(data.get('hasUserData'))
    rec["lkeClusterId"] = int(data.get('lkeClusterId') or 0)
    rec["maintenancePolicy"] = data.get('maintenancePolicy')
    rec["createdAt"] = now()
    rec["updatedAt"] = rec["createdAt"]
    _persist("Instance", rec)
    return rec, 201

@app.route("/v1/instances", methods=["GET"])
def list_instances(request):
    """List Instances."""
    items = _query("Instance")
    return {"object": "list", "data": items, "count": len(items)}, 200


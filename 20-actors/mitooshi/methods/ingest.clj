#!/usr/bin/env bb
;; Working Clojure port of methods/ingest.py.
(ns mitooshi.methods.ingest
  "mitooshi 見通し — public time-series normalizer (R0, offline).

  ADR-2606051800. Normalizes a PUBLIC time-series batch (a watari/watatsuna chokepoint
  roll-up, an OpenSky-derived congestion series, a gov-open-data flow series, or a karakuri
  member-principal export) into kotoba-EDN `:series/*` + `:obs/*` datoms.

  CONSTITUTIONAL (mitooshi G4 + G10 + G11), the file-ingest mirror of the series_ingest cell:
    - G4 source membrane: a series is normalized ONLY if its source-class is in the
      primary-public set {public-broadcast, primary-disclosure, open-commons, gov-open-data,
      member-principal}. A proprietary-terminal source (Bloomberg/CapIQ/Refinitiv/四季報) or a
      scraped-Google-Trends series is REFUSED (counted + logged), never silently relabelled.
    - G11 honesty: everything is tagged :representative; observations are append-only and
      sorted by observed-at (latest = current value, the stream = the trail, 非終末論).
    - G10 outward-gated: LIVE fetch (network) requires BOTH MITOOSHI_OPERATOR_GATE=1
      (Council/operator attestation) AND an explicit --live flag; default is OFFLINE batch.

  Run:  bb --classpath 20-actors 20-actors/mitooshi/methods/ingest.clj --batch data/ingest/sample-batch.json [--out OUTDIR]
        bb --classpath 20-actors 20-actors/mitooshi/methods/ingest.clj --live  ; refused unless MITOOSHI_OPERATOR_GATE=1"
  (:require [cheshire.core :as json]
            [clojure.java.io :as io]
            [clojure.string :as str]))

;; G4 — the primary-public source classes; anything else is refused (kanjo §2(c)/(e)).
(def allowed-source-class
  #{"public-broadcast" "primary-disclosure" "open-commons" "gov-open-data" "member-principal"})

(defn- norm
  "Strip a leading colon from a string value, returning empty string for nil."
  [v]
  (str/replace (str (or v "")) #"^:" ""))

(defn normalize
  "Accepts {\"series\": [{id, kind, unit, source, sourceClass, obs:[{observedAt,value,class?}]}]}.

  Returns {\"series\" {id datom}, \"obs\" [datom], \"refused\" [{id, sourceClass, reason}]}.
  A series whose sourceClass is not primary-public is REFUSED (G4) — not normalized."
  [batch]
  (let [out-series (atom {})
        out-obs    (atom [])
        refused    (atom [])]
    (doseq [s (get batch "series" [])]
      (let [sid (get s "id")
            sc  (norm (get s "sourceClass"))]
        (if-not (contains? allowed-source-class sc)
          (swap! refused conj
                 {"id"          sid
                  "sourceClass" sc
                  "reason"      (str "G4: source-class " (pr-str sc) " not in primary-public set "
                                     (pr-str (vec (sort allowed-source-class)))
                                     "; proprietary terminals + scraped "
                                     "Google-Trends are unrepresentable (kanjo §2(c)/(e))")})
          (do
            (swap! out-series assoc sid
                   {":series/id"           sid
                    ":series/name"         (get s "name" sid)
                    ":series/kind"         (str ":" (norm (get s "kind" "transit-load")))
                    ":series/unit"         (get s "unit" "")
                    ":series/freq"         (str ":" (norm (get s "freq" "daily")))
                    ":series/source"       (get s "source" "")
                    ":series/source-class" (str ":" sc)
                    ":series/sourcing"     ":representative"})
            ;; append-only, sorted by observed-at (latest = current, 非終末論)
            (doseq [o (sort-by #(get % "observedAt" 0) (get s "obs" []))]
              (let [oid (str "obs." sid "." (get o "observedAt"))
                    d   {":obs/id"          oid
                         ":obs/series"      sid
                         ":obs/observed-at" (get o "observedAt")
                         ":obs/value"       (double (get o "value" 0.0))}
                    d   (if (contains? o "class")
                          (assoc d ":obs/class" (get o "class"))
                          d)]
                (swap! out-obs conj d)))))))
    {"series"  @out-series
     "obs"     @out-obs
     "refused" @refused}))

(defn- emit-edn
  "Render the normalize result to a kotoba EDN string."
  [norm-result]
  (str/join
   "\n"
   (concat
    [";; series-graph.merged.kotoba.edn — DERIVED from offline ingest (:representative)."
     ";; ADR-2606051800 · generated by methods/ingest.clj"
     ""
     "["]
    (for [d (vals (get norm-result "series"))]
      (str " {:series/id \"" (get d ":series/id") "\""
           " :series/kind " (get d ":series/kind")
           " :series/unit \"" (get d ":series/unit") "\""
           " :series/source-class " (get d ":series/source-class")
           " :series/sourcing :representative}"))
    (for [d (get norm-result "obs")]
      (let [cls (when (contains? d ":obs/class")
                  (str " :obs/class \"" (get d ":obs/class") "\""))]
        (str " {:obs/id \"" (get d ":obs/id") "\""
             " :obs/series \"" (get d ":obs/series") "\""
             " :obs/observed-at " (get d ":obs/observed-at")
             " :obs/value " (get d ":obs/value")
             (or cls "")
             "}")))
    ["]"])))

(defn live-refusal
  "G10 outward gate: returns the refusal message string if --live is set, else nil.
  Accepts env-gate as a string (or nil), mirroring watari/watatsuna pattern."
  [argv env-gate]
  (when (some #{"--live"} (or argv []))
    (if (not= (str env-gate) "1")
      (str "mitooshi G10: live public-series ingest is Council+operator gated. "
           "Set MITOOSHI_OPERATOR_GATE=1 with attestation to enable. "
           "Default offline mode: --batch <sample.json>.")
      (str "mitooshi R0: live fetch not implemented (design-only). "
           "Wire watari/watatsuna roll-up + gov-open-data + karakuri member-principal here once gated."))))

(defn main [& argv]
  (let [args (vec argv)]
    ;; G10: live gate check
    (when-let [msg (live-refusal args (System/getenv "MITOOSHI_OPERATOR_GATE"))]
      (println msg)
      (System/exit 2))
    (let [bi (.indexOf args "--batch")]
      (when (neg? bi)
        (println "usage: ingest.clj --batch <sample.json> [--out OUTDIR]")
        (System/exit 1))
      (let [batch-path (nth args (inc bi))
            batch      (json/parse-string (slurp (io/file batch-path)))
            norm-result (normalize batch)]
        (when-let [oi (.indexOf args "--out")]
          (when (>= oi 0)
            (let [outdir (io/file (nth args (inc oi)))]
              (.mkdirs outdir)
              (spit (io/file outdir "series-graph.merged.kotoba.edn")
                    (emit-edn norm-result)))))
        (println (format "mitooshi ingest (offline, :representative): %d series, %d obs from %s; %d refused (G4)"
                         (count (get norm-result "series"))
                         (count (get norm-result "obs"))
                         (.getName (io/file batch-path))
                         (count (get norm-result "refused"))))
        (doseq [r (get norm-result "refused")]
          (println (str "  REFUSED " (get r "id") ": " (get r "reason"))))))))

(when (= *file* (System/getProperty "babashka.file"))
  (apply main *command-line-args*))

#!/usr/bin/env python3
"""mitooshi 見通し — public time-series normalizer (R0, offline).

ADR-2606051800. Normalizes a PUBLIC time-series batch (a watari/watatsuna chokepoint
roll-up, an OpenSky-derived congestion series, a gov-open-data flow series, or a karakuri
member-principal export) into kotoba-EDN `:series/*` + `:obs/*` datoms.

CONSTITUTIONAL (mitooshi G4 + G10 + G11), the file-ingest mirror of the series_ingest cell:
  - G4 source membrane: a series is normalized ONLY if its source-class is in the
    primary-public set {public-broadcast, primary-disclosure, open-commons, gov-open-data,
    member-principal}. A proprietary-terminal source (Bloomberg/CapIQ/Refinitiv/四季報) or a
    scraped-Google-Trends series is REFUSED (counted + logged), never silently relabelled.
  - G11 honesty: everything is tagged :representative; observations are append-only and
    sorted by observed-at (latest = current value, the stream = the trail, 非終末論).
  - G10 outward-gated: LIVE fetch (network) requires BOTH MITOOSHI_OPERATOR_GATE=1
    (Council/operator attestation) AND an explicit --live flag; default is OFFLINE batch.

stdlib only. Usage:
    python3 ingest.py --batch data/ingest/sample-batch.json [--out OUTDIR]
    python3 ingest.py --live          # refused unless MITOOSHI_OPERATOR_GATE=1 (G10)
"""
from __future__ import annotations

import json
import os
import pathlib
import sys

# G4 — the primary-public source classes; anything else is refused (kanjo §2(c)/(e)).
ALLOWED_SOURCE_CLASS = (
    "public-broadcast", "primary-disclosure", "open-commons", "gov-open-data", "member-principal",
)


def _norm(v):
    return (v or "").lstrip(":")


def normalize(batch: dict) -> dict:
    """Accepts {"series": [{id, kind, unit, source, sourceClass, obs:[{observedAt,value,class?}]}]}.

    Returns {"series": {id: datom}, "obs": [datom], "refused": [{id, sourceClass, reason}]}.
    A series whose sourceClass is not primary-public is REFUSED (G4) — not normalized.
    """
    out_series: dict[str, dict] = {}
    out_obs: list[dict] = []
    refused: list[dict] = []

    for s in batch.get("series", []):
        sid = s.get("id")
        sc = _norm(s.get("sourceClass"))
        if sc not in ALLOWED_SOURCE_CLASS:
            refused.append({"id": sid, "sourceClass": sc,
                            "reason": f"G4: source-class {sc!r} not in primary-public set "
                                      f"{ALLOWED_SOURCE_CLASS}; proprietary terminals + scraped "
                                      f"Google-Trends are unrepresentable (kanjo §2(c)/(e))"})
            continue
        out_series[sid] = {
            ":series/id": sid,
            ":series/name": s.get("name", sid),
            ":series/kind": f":{_norm(s.get('kind', 'transit-load'))}",
            ":series/unit": s.get("unit", ""),
            ":series/freq": f":{_norm(s.get('freq', 'daily'))}",
            ":series/source": s.get("source", ""),
            ":series/source-class": f":{sc}",
            ":series/sourcing": ":representative",
        }
        # append-only, sorted by observed-at (latest = current, 非終末論)
        for o in sorted(s.get("obs", []), key=lambda r: r.get("observedAt", 0)):
            oid = f"obs.{sid}.{o.get('observedAt')}"
            d = {":obs/id": oid, ":obs/series": sid,
                 ":obs/observed-at": o.get("observedAt"), ":obs/value": o.get("value", 0.0)}
            if "class" in o:
                d[":obs/class"] = o["class"]
            out_obs.append(d)

    return {"series": out_series, "obs": out_obs, "refused": refused}


def _emit_edn(norm: dict) -> str:
    lines = [";; series-graph.merged.kotoba.edn — DERIVED from offline ingest (:representative).",
             ";; ADR-2606051800 · generated by methods/ingest.py", "", "["]
    for d in norm["series"].values():
        lines.append(f' {{:series/id "{d[":series/id"]}" :series/kind {d[":series/kind"]} '
                     f':series/unit "{d[":series/unit"]}" :series/source-class {d[":series/source-class"]} '
                     f':series/sourcing :representative}}')
    for d in norm["obs"]:
        cls = f' :obs/class "{d[":obs/class"]}"' if ":obs/class" in d else ""
        lines.append(f' {{:obs/id "{d[":obs/id"]}" :obs/series "{d[":obs/series"]}" '
                     f':obs/observed-at {d[":obs/observed-at"]} :obs/value {d[":obs/value"]}{cls}}}')
    lines.append("]")
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    if "--live" in argv:
        if os.environ.get("MITOOSHI_OPERATOR_GATE") != "1":
            sys.exit("mitooshi G10: live public-series ingest is Council+operator gated. "
                     "Set MITOOSHI_OPERATOR_GATE=1 with attestation to enable. "
                     "Default offline mode: --batch <sample.json>.")
        sys.exit("mitooshi R0: live fetch not implemented (design-only). "
                 "Wire watari/watatsuna roll-up + gov-open-data + karakuri member-principal here once gated.")

    if "--batch" not in argv:
        sys.exit(__doc__)
    batch_path = pathlib.Path(argv[argv.index("--batch") + 1])
    batch = json.loads(batch_path.read_text(encoding="utf-8"))
    norm = normalize(batch)
    if "--out" in argv:
        outdir = pathlib.Path(argv[argv.index("--out") + 1])
        outdir.mkdir(parents=True, exist_ok=True)
        (outdir / "series-graph.merged.kotoba.edn").write_text(_emit_edn(norm))
    print(f"mitooshi ingest (offline, :representative): {len(norm['series'])} series, "
          f"{len(norm['obs'])} obs from {batch_path.name}; {len(norm['refused'])} refused (G4)")
    for r in norm["refused"]:
        print(f"  REFUSED {r['id']}: {r['reason']}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))

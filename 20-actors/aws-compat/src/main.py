app = Runtime("aws-compat")


def now():
    return datetime.datetime.utcnow().isoformat()


def new_id(prefix):
    return f"{prefix}_" + uuid.uuid4().hex[:16]


def _persist(entity, rec):
    """Transact a record into Datomic as namespaced EAVT facts."""
    facts = {}
    for k, v in rec.items():
        facts[f"aws.{entity}/{k}"] = v
    db.transact([facts])
    return rec


def _query(entity, eid=None):
    """Read records of an entity from Datomic (optionally by id)."""
    pattern = {"entity": f"aws.{entity}"}
    if eid is not None:
        pattern["id"] = eid
    return db.query(pattern)


def _require(data, fields):
    missing = [f for f in fields if not data.get(f)]
    if missing:
        return {"error": {"message": "Missing required fields: " + ", ".join(missing)}}
    return None


@app.route("/v1/ec2instances", methods=["POST"])
def create_ec2_instance(request):
    """Create a Ec2Instance."""
    data = request.json or request.form or {}
    err = _require(data, ['instanceType', 'state'])
    if err:
        return err, 400
    rec = {"id": new_id("aws_ec2")}
    rec["instanceId"] = data.get('instanceId')
    rec["instanceType"] = data.get('instanceType')
    rec["state"] = data.get('state')
    rec["privateIp"] = data.get('privateIp')
    rec["region"] = data.get('region')
    rec["createdAt"] = now()
    rec["updatedAt"] = rec["createdAt"]
    _persist("Ec2Instance", rec)
    return rec, 201


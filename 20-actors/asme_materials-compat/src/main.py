from kotodama import Runtime
from kotoba import load_schema
from datomic import DatomicClient
import uuid
import datetime

schema = load_schema("../schema/asme_materials.kotoba")
db = DatomicClient.connect()
app = Runtime("asme_materials-compat")


def now():
    return datetime.datetime.utcnow().isoformat()


def new_id(prefix):
    return f"{prefix}_" + uuid.uuid4().hex[:16]


def _persist(entity, rec):
    """Transact a record into Datomic as namespaced EAVT facts."""
    facts = {}
    for k, v in rec.items():
        facts[f"asme_materials.{entity}/{k}"] = v
    db.transact([facts])
    return rec


def _query(entity, eid=None):
    """Read records of an entity from Datomic (optionally by id)."""
    pattern = {"entity": f"asme_materials.{entity}"}
    if eid is not None:
        pattern["id"] = eid
    return db.query(pattern)


def _require(data, fields):
    missing = [f for f in fields if not data.get(f)]
    if missing:
        return {"error": {"message": "Missing required fields: " + ", ".join(missing)}}
    return None


@app.route("/v1/substances", methods=["POST"])
def create_substance(request):
    """Create a Substance."""
    data = request.json or request.form or {}
    err = _require(data, ['casNumber', 'name'])
    if err:
        return err, 400
    rec = {"id": new_id("asmemate_sub")}
    rec["casNumber"] = data.get('casNumber')
    rec["name"] = data.get('name')
    rec["formula"] = data.get('formula')
    rec["molarMass"] = float(data.get('molarMass') or 0)
    rec["createdAt"] = now()
    rec["updatedAt"] = rec["createdAt"]
    _persist("Substance", rec)
    return rec, 201

@app.route("/v1/substances", methods=["GET"])
def list_substances(request):
    """List Substances."""
    items = _query("Substance")
    return {"object": "list", "data": items, "count": len(items)}, 200

@app.route("/v1/substances/<eid>", methods=["GET"])
def get_substance(request, eid):
    """Retrieve a Substance by id."""
    rows = _query("Substance", eid)
    if not rows:
        return {"error": {"message": "Not found"}}, 404
    return rows[0], 200

@app.route("/v1/substances/<eid>", methods=["POST", "PATCH"])
def update_substance(request, eid):
    """Update a Substance."""
    rows = _query("Substance", eid)
    if not rows:
        return {"error": {"message": "Not found"}}, 404

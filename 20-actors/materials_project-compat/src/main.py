from kotodama import Runtime
from kotoba import load_schema
from datomic import DatomicClient
import uuid
import datetime

schema = load_schema("../schema/materials_project.kotoba")
db = DatomicClient.connect()
app = Runtime("materials_project-compat")


def now():
    return datetime.datetime.utcnow().isoformat()


def new_id(prefix):
    return f"{prefix}_" + uuid.uuid4().hex[:16]


def _persist(entity, rec):
    """Transact a record into Datomic as namespaced EAVT facts."""
    facts = {}
    for k, v in rec.items():
        facts[f"materials_project.{entity}/{k}"] = v
    db.transact([facts])
    return rec


def _query(entity, eid=None):
    """Read records of an entity from Datomic (optionally by id)."""
    pattern = {"entity": f"materials_project.{entity}"}
    if eid is not None:
        pattern["id"] = eid
    return db.query(pattern)


def _require(data, fields):
    missing = [f for f in fields if not data.get(f)]
    if missing:
        return {"error": {"message": "Missing required fields: " + ", ".join(missing)}}
    return None


@app.route("/v1/summarydocs", methods=["POST"])
def create_summary_doc(request):
    """Create a SummaryDoc."""
    data = request.json or request.form or {}
    err = _require(data, ['material_id', 'formula_pretty'])
    if err:
        return err, 400
    rec = {"id": new_id("material_sum")}
    rec["material_id"] = data.get('material_id')
    rec["formula_pretty"] = data.get('formula_pretty')
    rec["formula_anonymous"] = data.get('formula_anonymous')
    rec["chemsys"] = data.get('chemsys')
    rec["volume"] = float(data.get('volume') or 0)
    rec["density"] = float(data.get('density') or 0)
    rec["density_atomic"] = float(data.get('density_atomic') or 0)
    rec["nsites"] = int(data.get('nsites') or 0)
    rec["nelements"] = int(data.get('nelements') or 0)
    rec["theoretical"] = bool(data.get('theoretical'))
    rec["deprecated"] = bool(data.get('deprecated'))
    rec["is_stable"] = bool(data.get('is_stable'))
    rec["is_magnetic"] = bool(data.get('is_magnetic'))
    rec["is_metal"] = bool(data.get('is_metal'))
    rec["is_gap_direct"] = bool(data.get('is_gap_direct'))
    rec["band_gap"] = float(data.get('band_gap') or 0)
    rec["efermi"] = float(data.get('efermi') or 0)
    rec["formation_energy_per_atom"] = float(data.get('formation_energy_per_atom') or 0)
    rec["energy_above_hull"] = float(data.get('energy_above_hull') or 0)
    rec["uncorrected_energy_per_atom"] = float(data.get('uncorrected_energy_per_atom') or 0)
    rec["energy_per_atom"] = float(data.get('energy_per_atom') or 0)
    rec["equilibrium_reaction_energy_per_atom"] = float(data.get('equilibrium_reaction_energy_per_atom') or 0)
    rec["total_magnetization"] = float(data.get('total_magnetization') or 0)
    rec["total_magnetization_normalized_vol"] = float(data.get('total_magnetization_normalized_vol') or 0)
    rec["createdAt"] = now()
    rec["updatedAt"] = rec["createdAt"]
    _persist("SummaryDoc", rec)
    return rec, 201


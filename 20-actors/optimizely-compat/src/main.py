from kotodama import Runtime
from kotoba import load_schema
from datomic import DatomicClient
import uuid
import datetime

schema = load_schema("../schema/optimizely.kotoba")
db = DatomicClient.connect()
app = Runtime("optimizely-compat")


def now():
    return datetime.datetime.utcnow().isoformat()


def new_id(prefix):
    return f"{prefix}_" + uuid.uuid4().hex[:16]


def _persist(entity, rec):
    """Transact a record into Datomic as namespaced EAVT facts."""
    facts = {}
    for k, v in rec.items():
        facts[f"optimizely.{entity}/{k}"] = v
    db.transact([facts])
    return rec


def _query(entity, eid=None):
    """Read records of an entity from Datomic (optionally by id)."""
    pattern = {"entity": f"optimizely.{entity}"}
    if eid is not None:
        pattern["id"] = eid
    return db.query(pattern)


def _require(data, fields):
    missing = [f for f in fields if not data.get(f)]
    if missing:
        return {"error": {"message": "Missing required fields: " + ", ".join(missing)}}
    return None


@app.route("/v1/assets", methods=["POST"])
def create_asset(request):
    """Create a Asset."""
    data = request.json or request.form or {}
    err = _require(data, ['title', 'type'])
    if err:
        return err, 400
    rec = {"id": new_id("optimize_ass")}
    rec["title"] = data.get('title')
    rec["type"] = data.get('type')
    rec["durationMs"] = int(data.get('durationMs') or 0)
    rec["contentRef"] = data.get('contentRef')
    rec["createdAt"] = now()
    rec["updatedAt"] = rec["createdAt"]
    _persist("Asset", rec)
    return rec, 201

@app.route("/v1/assets", methods=["GET"])
def list_assets(request):
    """List Assets."""
    items = _query("Asset")
    return {"object": "list", "data": items, "count": len(items)}, 200

@app.route("/v1/assets/<eid>", methods=["GET"])
def get_asset(request, eid):
    """Retrieve a Asset by id."""
    rows = _query("Asset", eid)
    if not rows:
        return {"error": {"message": "Not found"}}, 404
    return rows[0], 200

@app.route("/v1/assets/<eid>", methods=["POST", "PATCH"])
def update_asset(request, eid):
    """Update a Asset."""
    rows = _query("Asset", eid)
    if not rows:
        return {"error": {"message": "Not found"}}, 404
    data = request.json or request.form or {}
    rec = rows[0]
    for k, v in data.items():
        if k in rec and k not in ("id", "createdAt"):
            rec[k] = v
    rec["updatedAt"] = now()
    _persist("Asset", rec)
    return rec, 200

@app.route("/v1/assets/<eid>", methods=["DELETE"])
def delete_asset(request, eid):
    """Delete a Asset."""
    rows = _query("Asset", eid)
    if not rows:
        return {"error": {"message": "Not found"}}, 404
    db.retract({"entity": f"optimizely.Asset", "id": eid})
    return {"id": eid, "deleted": True}, 200


from kotodama import Runtime
from kotoba import load_schema
from datomic import DatomicClient
import uuid
import datetime

schema = load_schema("../schema/crowdstrike.kotoba")
db = DatomicClient.connect()
app = Runtime("crowdstrike-compat")


def now():
    return datetime.datetime.utcnow().isoformat()


def new_id(prefix):
    return f"{prefix}_" + uuid.uuid4().hex[:16]


def _persist(entity, rec):
    """Transact a record into Datomic as namespaced EAVT facts."""
    facts = {}
    for k, v in rec.items():
        facts[f"crowdstrike.{entity}/{k}"] = v
    db.transact([facts])
    return rec


def _query(entity, eid=None):
    """Read records of an entity from Datomic (optionally by id)."""
    pattern = {"entity": f"crowdstrike.{entity}"}
    if eid is not None:
        pattern["id"] = eid
    return db.query(pattern)


def _require(data, fields):
    missing = [f for f in fields if not data.get(f)]
    if missing:
        return {"error": {"message": "Missing required fields: " + ", ".join(missing)}}
    return None


@app.route("/v1/identities", methods=["POST"])
def create_identity(request):
    """Create a Identity."""
    data = request.json or request.form or {}
    err = _require(data, ['username', 'email'])
    if err:
        return err, 400
    rec = {"id": new_id("crowdstr_ide")}
    rec["username"] = data.get('username')
    rec["email"] = data.get('email')
    rec["status"] = data.get('status')
    rec["mfaEnabled"] = bool(data.get('mfaEnabled'))
    rec["createdAt"] = now()
    rec["updatedAt"] = rec["createdAt"]
    _persist("Identity", rec)
    return rec, 201

@app.route("/v1/identities", methods=["GET"])
def list_identities(request):
    """List Identities."""
    items = _query("Identity")
    return {"object": "list", "data": items, "count": len(items)}, 200

@app.route("/v1/identities/<eid>", methods=["GET"])
def get_identity(request, eid):
    """Retrieve a Identity by id."""
    rows = _query("Identity", eid)
    if not rows:
        return {"error": {"message": "Not found"}}, 404
    return rows[0], 200

@app.route("/v1/identities/<eid>", methods=["POST", "PATCH"])
def update_identity(request, eid):
    """Update a Identity."""
    rows = _query("Identity", eid)
    if not rows:
        return {"error": {"message": "Not found"}}, 404
    data = request.json or request.form or {}
    rec = rows[0]
    for k, v in data.items():
        if k in rec and k not in ("id", "createdAt"):
            rec[k] = v
    rec["updatedAt"] = now()
    _persist("Identity", rec)
    return rec, 200

@app.route("/v1/identities/<eid>", methods=["DELETE"])
def delete_identity(request, eid):
    """Delete a Identity."""
    rows = _query("Identity", eid)
    if not rows:
        return {"error": {"message": "Not found"}}, 404
    db.retract({"entity": f"crowdstrike.Identity", "id": eid})

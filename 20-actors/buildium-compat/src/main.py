from kotodama import Runtime
from kotoba import load_schema
from datomic import DatomicClient
import uuid
import datetime

schema = load_schema("../schema/buildium.kotoba")
db = DatomicClient.connect()
app = Runtime("buildium-compat")


def now():
    return datetime.datetime.utcnow().isoformat()


def new_id(prefix):
    return f"{prefix}_" + uuid.uuid4().hex[:16]


def _persist(entity, rec):
    """Transact a record into Datomic as namespaced EAVT facts."""
    facts = {}
    for k, v in rec.items():
        facts[f"buildium.{entity}/{k}"] = v
    db.transact([facts])
    return rec


def _query(entity, eid=None):
    """Read records of an entity from Datomic (optionally by id)."""
    pattern = {"entity": f"buildium.{entity}"}
    if eid is not None:
        pattern["id"] = eid
    return db.query(pattern)


def _require(data, fields):
    missing = [f for f in fields if not data.get(f)]
    if missing:
        return {"error": {"message": "Missing required fields: " + ", ".join(missing)}}
    return None


@app.route("/v1/listings", methods=["POST"])
def create_listing(request):
    """Create a Listing."""
    data = request.json or request.form or {}
    err = _require(data, ['price', 'status'])
    if err:
        return err, 400
    rec = {"id": new_id("buildium_lis")}
    rec["propertyId"] = data.get('propertyId')
    rec["price"] = float(data.get('price') or 0)
    rec["status"] = data.get('status')
    rec["listedAt"] = data.get('listedAt')
    rec["createdAt"] = now()
    rec["updatedAt"] = rec["createdAt"]
    _persist("Listing", rec)
    return rec, 201

@app.route("/v1/listings", methods=["GET"])
def list_listings(request):
    """List Listings."""
    items = _query("Listing")
    return {"object": "list", "data": items, "count": len(items)}, 200


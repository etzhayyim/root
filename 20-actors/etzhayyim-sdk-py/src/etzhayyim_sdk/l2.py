async def anchor(
    commit_cid: str,
    *,
    batch_size: int = 1,
    contract_address: str | None = None,
) -> str:
    """Anchor a commit CID on Base L2 and return the transaction hash.

    Calls ``EtzhayyimAnchor.anchor(rootHash, ipfsCid, batchSize)`` on the
    deployed contract.  Transaction is signed with ``ETZHAYYIM_L2_ANCHOR_KEY``
    and submitted via ``eth_sendRawTransaction``.

    The method is WIREABLE today but EXECUTABLE only after:
      1. EtzhayyimAnchor.sol is deployed (Step 8 cutover).
      2. ``ETZHAYYIM_L2_CONTRACT_ADDRESS`` is provisioned.
      3. ``ETZHAYYIM_L2_ANCHOR_KEY`` is provisioned (funded hot key).

    Args:
        commit_cid:       CIDv1 of the MST root (multibase-encoded string).
        batch_size:       Record count in this batch (informational, default 1).
        contract_address: Override env-var address for this call (tests/multi-deploy).

    Returns:
        0x-prefixed Base L2 transaction hash (32 bytes / 64 hex chars).

    Raises:
        L2ContractError: ``ETZHAYYIM_L2_CONTRACT_ADDRESS`` unset or placeholder.
        L2SigningError:  ``ETZHAYYIM_L2_ANCHOR_KEY`` missing or invalid.
        L2NetworkError:  RPC transport failure.
        L2ServerError:   RPC-level error (e.g. nonce too low, gas price too low).
    """
    from eth_account import Account  # type: ignore[import-untyped]

    contract = contract_address or _contract_address()
    private_key = _anchor_key()

    # --- Build transaction calldata ---
    root_hash = _cid_to_root_hash(commit_cid)
    ipfs_cid_bytes = commit_cid.encode("utf-8")
    calldata_bytes = _encode_anchor_calldata(root_hash, ipfs_cid_bytes, batch_size)
    calldata_hex = "0x" + calldata_bytes.hex()

    # --- Validate private key and load account BEFORE RPC calls ---
    # Done early so we surface key errors without making any network calls.
    key_hex = private_key if private_key.startswith("0x") else "0x" + private_key
    try:
        acct = Account.from_key(key_hex)
    except Exception as exc:
        raise L2SigningError(f"Invalid private key in ETZHAYYIM_L2_ANCHOR_KEY: {exc}") from exc

    sender = acct.address

    # --- Get nonce ---
    nonce_hex = await _rpc_call("eth_getTransactionCount", [sender, "latest"])
    nonce = int(nonce_hex, 16)

    # --- Get gas price (and enforce ceiling before burning further RPC calls) ---
    gas_price_hex = await _rpc_call("eth_gasPrice", [])
    gas_price = int(gas_price_hex, 16)

    max_gas = _max_gas_wei()
    if gas_price > max_gas:
        raise L2ServerError(
            f"Current gas price {gas_price // 10**9} Gwei exceeds ceiling "
            f"{max_gas // 10**9} Gwei (ETZHAYYIM_L2_MAX_GAS_GWEI). "
            "Raise the ceiling or retry when network is less congested."
        )

    # --- Determine chain ID from RPC ---
    chain_id_hex = await _rpc_call("eth_chainId", [])
    chain_id = int(chain_id_hex, 16)

    # --- Build and sign transaction ---
    tx: dict[str, Any] = {
        "to": contract,
        "data": calldata_hex,
        "gas": DEFAULT_GAS_LIMIT,
        "gasPrice": gas_price,
        "nonce": nonce,
        "chainId": chain_id,
        "value": 0,
    }

    signed_raw = _sign_transaction(tx, key_hex)

    # --- Submit ---
    tx_hash = await _rpc_call("eth_sendRawTransaction", [signed_raw])
    return tx_hash



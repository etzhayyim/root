async def verify(commit_cid: str, proof: dict[str, Any]) -> bool:
    """Verify a Merkle proof against an on-chain Base L2 anchor.

    This is a *simplified* L2 anchor proof verifier that implements the
    AT-Protocol-inspired MST path convention used by the EtzhayyimAnchor
    contract pipeline (ADR-2605171800 Stage 4).  It is NOT a full atproto
    MST proof verifier — full CBOR-encoded atproto MST proofs are deferred
    to a future milestone.  This verifier matches the JSON proof structure
    produced by the anchor-cron batch pipeline.

    Proof structure::

        {
            "record_uri":    str,        # AT URI of the record being proven
            "record_cid":    str,        # CID of the leaf record
            "mst_path":      list[dict], # ordered Merkle path, leaf → root
                                         # each step: {"side": "L"|"R", "hash": "0x..."}
            "mst_root_cid":  str,        # claimed MST root CID
            "l2_anchor_tx":  str,        # 0x-prefixed Base L2 tx hash
        }

    Merkle hash function: SHA-256 of (left_bytes || right_bytes).
    CID → 32-byte hash: SHA-256 of the CID string UTF-8 bytes (matches
    ``_cid_to_root_hash`` / ``rootHash`` convention in EtzhayyimAnchor.sol).

    Verification steps:
      1. Replay the Merkle path: starting from ``sha256(record_cid)``, apply
         each path step (concat with sibling, sha256) to compute
         ``computed_root``.
      2. Compare ``computed_root`` to ``sha256(mst_root_cid)``.  If they
         differ, return ``False``.
      3. Ensure ``commit_cid == mst_root_cid`` (caller's commit must match
         the proof's claimed root).  If not, return ``False``.
      4. Call ``read_anchor(l2_anchor_tx)`` and compare the on-chain
         ``root_hash`` field to ``computed_root``.  If they differ, return
         ``False``.

    Returns:
        ``True`` if all four checks pass; ``False`` if any check fails
        (invalid path, CID mismatch, on-chain mismatch).

    Raises:
        L2VerificationError: If the proof is structurally invalid (missing
            keys, unparseable hex, unrecognised side indicator).
        L2NetworkError: If the on-chain RPC call fails at the transport level.
        L2ServerError:  If the on-chain RPC endpoint returns an error.
        L2Error:        If the anchor tx is not found, reverted, or has no
            Anchored event.

    Note — caveats:
        - CBOR atproto MST proof support is deferred (not in scope here).
        - The verifier assumes a binary Merkle tree (each step has exactly
          one sibling).  Multi-arity trees are not supported.
    """
    # ── Step 0: validate proof structure ──────────────────────────────────────
    required_keys: frozenset[str] = frozenset(
        {"record_uri", "record_cid", "mst_path", "mst_root_cid", "l2_anchor_tx"}
    )
    missing = required_keys - set(proof.keys())
    if missing:
        raise L2VerificationError(f"proof missing keys: {missing}")

    record_cid: str = proof["record_cid"]
    mst_path: list[dict[str, Any]] = proof["mst_path"]
    claimed_root: str = proof["mst_root_cid"]

    # ── Step 1: replay Merkle path ────────────────────────────────────────────
    # Leaf hash: sha256 of record_cid UTF-8 bytes (matches _cid_to_root_hash).
    current: bytes = _cid_to_root_hash(record_cid)

    for step in mst_path:
        side: str = step.get("side", "")
        sibling_hex: str = step.get("hash", "")
        try:
            sibling: bytes = bytes.fromhex(sibling_hex.removeprefix("0x"))
        except ValueError:
            raise L2VerificationError(f"invalid sibling hash: {sibling_hex!r}")
        if len(sibling) != 32:
            raise L2VerificationError(
                f"sibling hash must be 32 bytes, got {len(sibling)}"
            )

        if side == "L":
            combined = sibling + current   # sibling is left child
        elif side == "R":
            combined = current + sibling   # sibling is right child
        else:
            raise L2VerificationError(
                f"invalid side {side!r} — must be 'L' or 'R'"
            )

        current = hashlib.sha256(combined).digest()

    # ── Step 2: compare computed root to claimed root ─────────────────────────
    claimed_root_bytes: bytes = _cid_to_root_hash(claimed_root)
    if current != claimed_root_bytes:
        return False

    # ── Step 3: commit_cid must match claimed root ────────────────────────────
    if commit_cid != claimed_root:
        return False

    # ── Step 4: on-chain anchor verification ──────────────────────────────────
    anchor_info = await read_anchor(proof["l2_anchor_tx"])
    on_chain_root_hash_hex: str = anchor_info.get("root_hash", "")
    try:
        on_chain_root_hash: bytes = bytes.fromhex(
            on_chain_root_hash_hex.removeprefix("0x")
        )
    except ValueError:
        raise L2VerificationError(
            f"on-chain rootHash is not valid hex: {on_chain_root_hash_hex!r}"
        )

    if on_chain_root_hash != claimed_root_bytes:
        return False

    return True

async def read_anchor(tx_hash: str) -> dict[str, Any]:
    """Read an anchor event from Base L2 by transaction hash.

    Fetches the transaction receipt and decodes the ``Anchored`` event log.

    Args:
        tx_hash: 0x-prefixed hex transaction hash (32 bytes / 64 hex chars).

    Returns:
        Dict with keys::

            {
              "tx_hash":       str,   # 0x-prefixed
              "block_number":  int,
              "status":        int,   # 1 = success, 0 = reverted
              "root_hash":     str,   # bytes32 hex (indexed topic)
              "anchorer":      str,   # address hex
              "ipfs_cid":      str,   # multibase CID string
              "batch_size":    int,
            }

    Raises:
        L2NetworkError: RPC transport failure.
        L2ServerError: RPC-level error.
        L2Error: If the receipt is not found, tx reverted, or Anchored log missing.
    """
    receipt = await _rpc_call("eth_getTransactionReceipt", [tx_hash])
    if receipt is None:
        raise L2Error(f"Transaction not found or not yet mined: {tx_hash}")

    status = int(receipt.get("status", "0x0"), 16)
    block_number = int(receipt.get("blockNumber", "0x0"), 16)

    if status == 0:
        raise L2Error(f"Transaction {tx_hash} reverted (status=0).")

    # Find the Anchored event log
    anchored_log: dict[str, Any] | None = None
    for log in receipt.get("logs", []):
        topics = log.get("topics", [])
        if topics and topics[0].lower() == ANCHORED_EVENT_TOPIC.lower():
            anchored_log = log
            break

    if anchored_log is None:
        raise L2Error(
            f"No Anchored event found in receipt for tx {tx_hash}. "
            f"Logs: {receipt.get('logs', [])}"
        )

    decoded = _decode_anchored_log(anchored_log)

    return {
        "tx_hash": tx_hash,
        "block_number": block_number,
        "status": status,
        **decoded,
    }


async def get_anchor(commit_cid: str) -> dict[str, Any] | None:
    """Query the contract for a CID's anchor record via eth_call.

    Uses the public ``anchors(bytes32)`` mapping getter.

    Args:
        commit_cid: CIDv1 string (multibase-encoded) to look up.

    Returns:
        Dict with anchor entry fields, or ``None`` if never anchored::

            {
              "root_hash":    str,   # bytes32 hex
              "ipfs_cid":     str,   # original CID bytes from contract
              "block_number": int,
              "anchorer":     str,   # address hex
              "batch_size":   int,
              "anchored_at":  int,   # unix timestamp
            }

    Raises:
        L2ContractError: Contract address unset/placeholder.
        L2NetworkError: RPC transport failure.
        L2ServerError: RPC-level error.
    """
    contract = _contract_address()
    root_hash = _cid_to_root_hash(commit_cid)
    calldata = "0x" + _encode_anchors_getter_calldata(root_hash).hex()

    result = await _rpc_call(
        "eth_call",
        [{"to": contract, "data": calldata}, "latest"],
    )

    return _decode_anchors_return(result)



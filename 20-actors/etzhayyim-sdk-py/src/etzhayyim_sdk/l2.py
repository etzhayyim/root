def _sign_transaction(tx: dict[str, Any], private_key_hex: str) -> str:
    """Sign a transaction dict with the given private key using eth_account.

    Returns the signed raw transaction as a 0x-prefixed hex string.

    Raises:
        L2SigningError: If the private key is malformed.
    """
    from eth_account import Account  # type: ignore[import-untyped]

    try:
        key = private_key_hex if private_key_hex.startswith("0x") else "0x" + private_key_hex
        signed = Account.sign_transaction(tx, key)
        # eth_account ≥0.7 uses raw_transaction; older versions used rawTransaction.
        raw = getattr(signed, "raw_transaction", None) or getattr(signed, "rawTransaction", None)
        if raw is None:
            raise AttributeError("eth_account SignedTransaction has neither raw_transaction nor rawTransaction")
        return "0x" + raw.hex()
    except Exception as exc:
        raise L2SigningError(f"Transaction signing failed: {exc}") from exc



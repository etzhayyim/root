def _cid_to_root_hash(commit_cid: str) -> bytes:
    """Convert a CID string to the 32-byte rootHash used by EtzhayyimAnchor.sol.

    Strategy: SHA-256 of the CID string bytes (UTF-8 encoded).
    This matches the contract docstring: "sha256 of the canonical MST root CID bytes."

    The CID is passed as its multibase string form (e.g. ``bafybeig5…``).
    The contract stores the raw bytes CID separately in ``ipfsCid`` so the
    rootHash is ONLY for deduplication / indexing.

    Note: This is SHA-256 (stdlib), NOT keccak256.  The contract uses sha256
    in its struct comment.  Confirm against deployed contract at Step 8.
    """
    return hashlib.sha256(commit_cid.encode("utf-8")).digest()


def _encode_anchor_calldata(
    root_hash: bytes,
    ipfs_cid_bytes: bytes,
    batch_size: int,
) -> bytes:
    """ABI-encode the call to anchor(bytes32 rootHash, bytes ipfsCid, uint64 batchSize).

    Solidity ABI encoding for (bytes32, bytes, uint64):
      - selector: 4 bytes
      - slot 0: rootHash (bytes32) — 32 bytes, right-padded (value is already 32)
      - slot 1: offset of bytes param — 32 bytes (= 0x60, since 3 head slots)
      - slot 2: batchSize (uint64)  — 32 bytes, left-zero-padded
      - slot 3: length of bytes    — 32 bytes
      - slot 4+: bytes data, right-padded to 32-byte boundary

    Returns raw calldata bytes (no 0x prefix).
    """
    selector = bytes.fromhex(ANCHOR_FUNCTION_SELECTOR[2:])

    # bytes32 rootHash — already 32 bytes
    slot_root_hash = root_hash.ljust(32, b"\x00")[:32]

    # Offset for the dynamic ``bytes`` param.
    # Head section = 3 slots × 32 bytes = 96 bytes = 0x60
    offset_bytes_param = (3 * 32).to_bytes(32, "big")

    # uint64 batchSize — right-aligned in 32-byte slot
    slot_batch_size = batch_size.to_bytes(32, "big")

    # bytes ipfsCid — length prefix + data
    cid_len = len(ipfs_cid_bytes)
    slot_cid_len = cid_len.to_bytes(32, "big")
    # Pad to 32-byte boundary
    padding = (32 - (cid_len % 32)) % 32
    cid_padded = ipfs_cid_bytes + b"\x00" * padding

    return (
        selector
        + slot_root_hash
        + offset_bytes_param
        + slot_batch_size
        + slot_cid_len
        + cid_padded
    )


def _encode_anchors_getter_calldata(root_hash: bytes) -> bytes:
    """ABI-encode call to the public anchors(bytes32) getter.

    selector (4 bytes) + bytes32 argument (32 bytes) = 36 bytes total.
    """
    selector = bytes.fromhex(ANCHORS_GETTER_SELECTOR[2:])
    slot = root_hash.ljust(32, b"\x00")[:32]
    return selector + slot


def _decode_anchors_return(raw_hex: str) -> dict[str, Any] | None:
    """Decode the ABI return value of the public anchors(bytes32) getter.

    Returns struct as dict, or None if the entry has never been anchored
    (blockNumber == 0 indicates empty/unanchored slot).

    ABI return layout for AnchorEntry (bytes32,bytes,uint256,address,uint64,uint64):
      slot 0:  rootHash  (bytes32)
      slot 1:  offset of bytes (dynamic)
      slot 2:  blockNumber (uint256)
      slot 3:  anchorer (address, 20 bytes, left-zero-padded)
      slot 4:  batchSize (uint64)
      slot 5:  anchoredAt (uint64)
      slot 6+: ipfsCid length + data
    """
    if not raw_hex or raw_hex == "0x":
        return None
    data = bytes.fromhex(raw_hex[2:] if raw_hex.startswith("0x") else raw_hex)
    if len(data) < 7 * 32:
        return None

    root_hash = data[0:32]
    # slot 1 = offset of bytes dynamic data
    block_number = int.from_bytes(data[64:96], "big")
    if block_number == 0:
        return None  # never anchored

    anchorer = "0x" + data[108:128].hex()  # last 20 bytes of slot 3
    batch_size = int.from_bytes(data[128:160], "big")
    anchored_at = int.from_bytes(data[160:192], "big")

    # Dynamic bytes at offset (always 224 = 0xE0 for this struct layout)
    offset = int.from_bytes(data[32:64], "big")
    cid_len = int.from_bytes(data[offset : offset + 32], "big")
    cid_bytes = data[offset + 32 : offset + 32 + cid_len]

    return {
        "root_hash": "0x" + root_hash.hex(),
        "ipfs_cid": cid_bytes.decode("utf-8", errors="replace"),
        "block_number": block_number,
        "anchorer": anchorer,
        "batch_size": batch_size,
        "anchored_at": anchored_at,
    }


def _decode_anchored_log(log: dict[str, Any]) -> dict[str, Any]:
    """Decode an Anchored(...) event log from eth_getTransactionReceipt.

    Event signature: Anchored(bytes32 indexed rootHash, address indexed anchorer,
                               bytes ipfsCid, uint256 blockNumber, uint64 batchSize)

    Topics[0] = ANCHORED_EVENT_TOPIC
    Topics[1] = rootHash (indexed bytes32)
    Topics[2] = anchorer  (indexed address, left-zero-padded to 32 bytes)
    Data = ABI-encoded (bytes ipfsCid, uint256 blockNumber, uint64 batchSize)
           = offset(32) + blockNumber(32) + batchSize(32) + cid_len(32) + cid_data
    """
    topics = log.get("topics", [])
    if len(topics) < 3:
        raise L2Error(f"Anchored log has fewer than 3 topics: {topics}")
    if topics[0].lower() != ANCHORED_EVENT_TOPIC.lower():
        raise L2Error(
            f"Log topic[0] {topics[0]} != ANCHORED_EVENT_TOPIC {ANCHORED_EVENT_TOPIC}"
        )

    root_hash = topics[1]
    anchorer = "0x" + topics[2][-40:]  # last 20 bytes (40 hex chars)

    raw_data = bytes.fromhex(log["data"][2:] if log["data"].startswith("0x") else log["data"])

    # Non-indexed data: (bytes ipfsCid, uint256 blockNumber, uint64 batchSize)
    # ABI layout: offset(32) + blockNumber(32) + batchSize(32) + cid_len(32) + cid_data
    offset = int.from_bytes(raw_data[0:32], "big")
    block_number_from_data = int.from_bytes(raw_data[32:64], "big")
    batch_size = int.from_bytes(raw_data[64:96], "big")
    cid_len = int.from_bytes(raw_data[offset : offset + 32], "big")
    cid_bytes = raw_data[offset + 32 : offset + 32 + cid_len]

    return {
        "root_hash": root_hash,
        "anchorer": anchorer,
        "ipfs_cid": cid_bytes.decode("utf-8", errors="replace"),
        "block_number_from_data": block_number_from_data,
        "batch_size": batch_size,
    }



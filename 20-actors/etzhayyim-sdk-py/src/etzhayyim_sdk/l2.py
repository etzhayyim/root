async def _rpc_call(method: str, params: list[Any]) -> Any:
    """Execute a JSON-RPC call and return the ``result`` field.

    Raises:
        L2NetworkError: HTTP transport failure.
        L2ServerError: Non-200 HTTP status or RPC-level error in response body.
    """
    global _request_id
    _request_id += 1
    client = _get_client()
    try:
        resp = await client.post(
            _rpc_url(),
            json={
                "jsonrpc": "2.0",
                "method": method,
                "params": params,
                "id": _request_id,
            },
        )
    except httpx.HTTPError as exc:
        raise L2NetworkError(f"RPC network error for {method}: {exc}") from exc
    if resp.status_code != 200:
        raise L2ServerError(
            f"RPC {method} HTTP {resp.status_code}: {resp.text[:200]}"
        )
    body = resp.json()
    if "error" in body:
        raise L2ServerError(f"RPC {method} error: {body['error']}")
    return body["result"]



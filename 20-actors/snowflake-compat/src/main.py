    """Create a Warehouse."""
    data = request.json or request.form or {}
    err = _reject_unknown(data, ['name', 'warehouseType', 'warehouseSize', 'scalingPolicy', 'autoSuspend', 'autoResume', 'state'])
    if err:
        return err, 400
    err = _require(data, ['name', 'warehouseType'])

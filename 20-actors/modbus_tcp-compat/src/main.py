    rec["length"] = _as_int(data.get('length'))
    rec["unitId"] = _as_int(data.get('unitId'))
    rec["createdAt"] = now()
    rec["updatedAt"] = rec["createdAt"]
    _persist("MbapHeader", rec)
    return rec, 201


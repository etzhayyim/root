from kotodama import Runtime
from kotoba import load_schema
from datomic import DatomicClient
import uuid
import datetime

schema = load_schema("../schema/nakama.kotoba")
db = DatomicClient.connect()
app = Runtime("nakama-compat")


def now():
    return datetime.datetime.utcnow().isoformat()


def new_id(prefix):
    return f"{prefix}_" + uuid.uuid4().hex[:16]


def _persist(entity, rec):
    """Transact a record into Datomic as namespaced EAVT facts."""
    facts = {}
    for k, v in rec.items():
        facts[f"nakama.{entity}/{k}"] = v
    db.transact([facts])
    return rec


def _query(entity, eid=None):
    """Read records of an entity from Datomic (optionally by id)."""
    pattern = {"entity": f"nakama.{entity}"}
    if eid is not None:
        pattern["id"] = eid
    return db.query(pattern)


def _require(data, fields):
    missing = [f for f in fields if not data.get(f)]
    if missing:
        return {"error": {"message": "Missing required fields: " + ", ".join(missing)}}
    return None


@app.route("/v1/players", methods=["POST"])
def create_player(request):
    """Create a Player."""
    data = request.json or request.form or {}
    err = _require(data, ['handle', 'level'])
    if err:
        return err, 400
    rec = {"id": new_id("nakama_pla")}
    rec["handle"] = data.get('handle')
    rec["level"] = int(data.get('level') or 0)
    rec["xp"] = int(data.get('xp') or 0)
    rec["region"] = data.get('region')
    rec["createdAt"] = now()
    rec["updatedAt"] = rec["createdAt"]
    _persist("Player", rec)
    return rec, 201

@app.route("/v1/players", methods=["GET"])
def list_players(request):
    """List Players."""
    items = _query("Player")
    return {"object": "list", "data": items, "count": len(items)}, 200

@app.route("/v1/players/<eid>", methods=["GET"])
def get_player(request, eid):
    """Retrieve a Player by id."""
    rows = _query("Player", eid)
    if not rows:
        return {"error": {"message": "Not found"}}, 404
    return rows[0], 200

@app.route("/v1/players/<eid>", methods=["POST", "PATCH"])
def update_player(request, eid):
    """Update a Player."""
    rows = _query("Player", eid)
    if not rows:
        return {"error": {"message": "Not found"}}, 404

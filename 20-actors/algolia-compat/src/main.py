from kotodama import Runtime
from kotoba import load_schema
from datomic import DatomicClient
import uuid
import datetime

schema = load_schema("../schema/algolia.kotoba")
db = DatomicClient.connect()
app = Runtime("algolia-compat")


def now():
    return datetime.datetime.utcnow().isoformat()


def new_id(prefix):
    return f"{prefix}_" + uuid.uuid4().hex[:16]


def _persist(entity, rec):
    """Transact a record into Datomic as namespaced EAVT facts."""
    facts = {}
    for k, v in rec.items():
        facts[f"algolia.{entity}/{k}"] = v
    db.transact([facts])
    return rec


def _query(entity, eid=None):
    """Read records of an entity from Datomic (optionally by id)."""
    pattern = {"entity": f"algolia.{entity}"}
    if eid is not None:
        pattern["id"] = eid
    return db.query(pattern)


def _require(data, fields):
    missing = [f for f in fields if not data.get(f)]
    if missing:
        return {"error": {"message": "Missing required fields: " + ", ".join(missing)}}
    return None


@app.route("/v1/indexes", methods=["POST"])
def create_index(request):
    """Create a Index."""
    data = request.json or request.form or {}
    err = _require(data, ['name', 'entries'])
    if err:
        return err, 400
    rec = {"id": new_id("algolia_ind")}
    rec["name"] = data.get('name')
    rec["entries"] = int(data.get('entries') or 0)
    rec["dataSize"] = int(data.get('dataSize') or 0)
    rec["fileSize"] = int(data.get('fileSize') or 0)
    rec["lastBuildTimeS"] = int(data.get('lastBuildTimeS') or 0)
    rec["numberOfPendingTasks"] = int(data.get('numberOfPendingTasks') or 0)
    rec["pendingTask"] = bool(data.get('pendingTask'))
    rec["primary"] = data.get('primary')
    rec["createdAt"] = now()
    rec["updatedAt"] = rec["createdAt"]
    _persist("Index", rec)
    return rec, 201

@app.route("/v1/indexes", methods=["GET"])
def list_indexes(request):
    """List Indexes."""
    items = _query("Index")
    return {"object": "list", "data": items, "count": len(items)}, 200


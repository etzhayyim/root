from kotodama import Runtime
from kotoba import load_schema
from datomic import DatomicClient
import uuid
import datetime

schema = load_schema("../schema/quintessencelabs.kotoba")
db = DatomicClient.connect()
app = Runtime("quintessencelabs-compat")


def now():
    return datetime.datetime.utcnow().isoformat()


def new_id(prefix):
    return f"{prefix}_" + uuid.uuid4().hex[:16]


def _persist(entity, rec):
    """Transact a record into Datomic as namespaced EAVT facts."""
    facts = {}
    for k, v in rec.items():
        facts[f"quintessencelabs.{entity}/{k}"] = v
    db.transact([facts])
    return rec


def _query(entity, eid=None):
    """Read records of an entity from Datomic (optionally by id)."""
    pattern = {"entity": f"quintessencelabs.{entity}"}
    if eid is not None:
        pattern["id"] = eid
    return db.query(pattern)


def _require(data, fields):
    missing = [f for f in fields if not data.get(f)]
    if missing:
        return {"error": {"message": "Missing required fields: " + ", ".join(missing)}}
    return None


@app.route("/v1/keysessions", methods=["POST"])
def create_key_session(request):
    """Create a KeySession."""
    data = request.json or request.form or {}
    err = _require(data, ['protocol', 'status'])
    if err:
        return err, 400
    rec = {"id": new_id("quintess_key")}
    rec["aliceNodeId"] = data.get('aliceNodeId')
    rec["bobNodeId"] = data.get('bobNodeId')
    rec["protocol"] = data.get('protocol')
    rec["status"] = data.get('status')
    rec["createdAt"] = now()
    rec["updatedAt"] = rec["createdAt"]
    _persist("KeySession", rec)
    return rec, 201


    """Create a Header."""
    data = request.json or request.form or {}
    err = _reject_unknown(data, ['id', 'qr', 'opcode', 'aa', 'tc', 'rd', 'ra', 'rcode', 'qdcount', 'ancount', 'nscount', 'arcount'])
    if err:
        return err, 400
    err = _require(data, ['id', 'qr'])

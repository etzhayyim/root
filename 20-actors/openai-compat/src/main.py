from kotodama import Runtime
from kotoba import load_schema
from datomic import DatomicClient
import uuid
import datetime

schema = load_schema("../schema/openai.kotoba")
db = DatomicClient.connect()
app = Runtime("openai-compat")


def now():
    return datetime.datetime.utcnow().isoformat()


def new_id(prefix):
    return f"{prefix}_" + uuid.uuid4().hex[:16]


def _persist(entity, rec):
    """Transact a record into Datomic as namespaced EAVT facts."""
    facts = {}
    for k, v in rec.items():
        facts[f"openai.{entity}/{k}"] = v
    db.transact([facts])
    return rec


def _query(entity, eid=None):
    """Read records of an entity from Datomic (optionally by id)."""
    pattern = {"entity": f"openai.{entity}"}
    if eid is not None:
        pattern["id"] = eid
    return db.query(pattern)


def _require(data, fields):
    missing = [f for f in fields if not data.get(f)]
    if missing:
        return {"error": {"message": "Missing required fields: " + ", ".join(missing)}}
    return None


@app.route("/v1/models", methods=["POST"])
def create_model(request):
    """Create a Model."""
    data = request.json or request.form or {}
    err = _require(data, ['name', 'ownedBy'])
    if err:
        return err, 400
    rec = {"id": new_id("openai_mod")}
    rec["name"] = data.get('name')
    rec["ownedBy"] = data.get('ownedBy')
    rec["contextWindow"] = int(data.get('contextWindow') or 0)
    rec["createdAt"] = now()
    rec["updatedAt"] = rec["createdAt"]
    _persist("Model", rec)
    return rec, 201

@app.route("/v1/models", methods=["GET"])
def list_models(request):
    """List Models."""
    items = _query("Model")
    return {"object": "list", "data": items, "count": len(items)}, 200

@app.route("/v1/models/<eid>", methods=["GET"])
def get_model(request, eid):
    """Retrieve a Model by id."""
    rows = _query("Model", eid)

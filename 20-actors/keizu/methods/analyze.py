"""analyze.py — 系図 (keizu) end-to-end membrane (dry-run). ADR-2606066000.

Load seed → weave + validate → aggregate concentration → dry-run social posts → write
`methods/out/intel-report.md` + `methods/out/relation-graph.kotoba.edn`. Aggregate-first (G3),
edge-primary (G4), non-adjudicating (G2), mirror-not-target (G5). No live posting (G8).

Stdlib only.
"""

from __future__ import annotations

import pathlib

from _edn import load_edn
from social import draft_committee_post, draft_money_post
from weave import concentration, weave

HERE = pathlib.Path(__file__).resolve().parent
SEED = HERE.parent / "data" / "seed-relation-graph.kotoba.edn"
OUT = HERE / "out"


def run(seed_path: pathlib.Path = SEED, out_dir: pathlib.Path = OUT) -> dict:
    g = weave(load_edn(seed_path))
    c = concentration(g)
    posts = []
    if c["committee_cross_organ"]:
        f = c["committee_cross_organ"][0]
        comm = g["committees"].get(f["committee"], {})
        srcs = list(comm.get(":committee/sources", [])) + ["https://www.mof.go.jp/"]
        posts.append(draft_committee_post(f, srcs))
    allsrcs = sorted({s for m in g["money"] for s in m.get(":money/sources", [])})
    if allsrcs:
        posts.append(draft_money_post(c["money_concentration"], allsrcs))

    out_dir.mkdir(parents=True, exist_ok=True)
    _write_report(out_dir / "intel-report.md", c, posts)
    _write_graph(out_dir / "relation-graph.kotoba.edn", g)
    return {"concentration": c, "posts": posts}


def _write_report(path: pathlib.Path, c: dict, posts: list[dict]) -> None:
    L = ["# 系図 (keizu) — government power-relations intel (dry-run)\n",
         "_Accountability map, NOT a target-list. Non-adjudicating. :representative seed._\n",
         f"\nnodes={c['node_count']} committees={c['committee_count']} rels={c['rel_count']} "
         f"money={c['money_count']} statements={c['statement_count']}\n",
         "\n## Committee cross-organ concentration\n"]
    for r in c["committee_cross_organ"]:
        L.append(f"- **{r['label']}** — {r['member_count']} seats from {r['distinct_organs']} organ(s): {', '.join(r['organs'])}")
    L.append("\n## Cross-committee seats (co-membership)\n")
    for r in c["cross_committee_seats"]:
        L.append(f"- `{r['seat']}` sits on {r['committee_count']} committees: {', '.join(r['committees'])}")
    if not c["cross_committee_seats"]:
        L.append("- (none in seed)")
    mc = c["money_concentration"]
    L.append(f"\n## Money concentration (by payee) — HHI={mc['hhi']} over total {mc['total']:.0f}\n")
    for payee, share in mc["shares"]:
        L.append(f"- `{payee}`: {share*100:.1f}%")
    pc = c["payer_concentration"]
    L.append(f"\n## Money concentration (by payer) — HHI={pc['hhi']}\n")
    for payer, share in pc["shares"]:
        L.append(f"- `{payer}`: {share*100:.1f}%")
    L.append("\n## Revolving-door chains\n")
    for r in c["revolving_door"]:
        L.append(f"- {r['from_label']} → {r['to_label']} (as-of {r['as_of']})")
    if not c["revolving_door"]:
        L.append("- (none in seed)")
    L.append("\n## Award-and-fund co-occurrence (FACTUAL, non-adjudicating)\n")
    L.append("_A node that both received public money and made a political donation. A co-occurrence of two disclosed flows — NOT an allegation of wrongdoing._\n")
    for r in c["award_and_fund"]:
        L.append(f"- `{r['node']}` — received {r['received_total']:.0f} from {', '.join(r['received_from'])}; "
                 f"donated {r['donated_total']:.0f} to {', '.join(r['donated_to'])}")
    if not c["award_and_fund"]:
        L.append("- (none in seed)")
    L.append("\n## Dry-run social posts\n")
    for p in posts:
        L.append(f"> {p[':post/body']}\n>\n> _status={p[':post/status']} isMirror={p[':post/is-mirror']} "
                 f"serverHeldKey={p[':post/server-held-key']} sources={len(p[':post/sources'])}_\n")
    path.write_text("\n".join(L) + "\n", encoding="utf-8")


def _write_graph(path: pathlib.Path, g: dict) -> None:
    """Emit the validated relation graph as derived edn (the kotoba-ingest body shape)."""
    lines = [";; GENERATED by keizu analyze.py — validated relation graph (do not hand-edit)",
             "{:graph {:name \"keizu-relations-v1\" :visibility :public}", " :rels ["]
    for r in g["rels"]:
        lines.append(f'  {{:rel/id "{r[":rel/id"]}" :rel/source "{r[":rel/source"]}" '
                     f':rel/target "{r[":rel/target"]}" :rel/kind {r[":rel/kind"]} '
                     f':rel/non-adjudicating-notice true}}')
    lines.append(" ]}")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    res = run()
    c = res["concentration"]
    print(f"# keizu analyze — nodes={c['node_count']} committees={c['committee_count']} "
          f"rels={c['rel_count']} money={c['money_count']}")
    print(f"  money HHI={c['money_concentration']['hhi']}, "
          f"cross-committee seats={len(c['cross_committee_seats'])}, "
          f"revolving-door={len(c['revolving_door'])}, posts={len(res['posts'])}")
    print(f"  → {OUT/'intel-report.md'}")

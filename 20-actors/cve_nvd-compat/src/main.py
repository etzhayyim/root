from kotodama import Runtime
from kotoba import load_schema
from datomic import DatomicClient
import uuid
import datetime

schema = load_schema("../schema/cve_nvd.kotoba")
db = DatomicClient.connect()
app = Runtime("cve_nvd-compat")


def now():
    return datetime.datetime.utcnow().isoformat()


def new_id(prefix):
    return f"{prefix}_" + uuid.uuid4().hex[:16]


def _persist(entity, rec):
    """Transact a record into Datomic as namespaced EAVT facts."""
    facts = {}
    for k, v in rec.items():
        facts[f"cve_nvd.{entity}/{k}"] = v
    db.transact([facts])
    return rec


def _query(entity, eid=None):
    """Read records of an entity from Datomic (optionally by id)."""
    pattern = {"entity": f"cve_nvd.{entity}"}
    if eid is not None:
        pattern["id"] = eid
    return db.query(pattern)


def _require(data, fields):
    missing = [f for f in fields if not data.get(f)]
    if missing:
        return {"error": {"message": "Missing required fields: " + ", ".join(missing)}}
    return None


@app.route("/v1/indicators", methods=["POST"])
def create_indicator(request):
    """Create a Indicator."""
    data = request.json or request.form or {}
    err = _require(data, ['type', 'value'])
    if err:
        return err, 400
    rec = {"id": new_id("cvenvd_ind")}
    rec["type"] = data.get('type')
    rec["value"] = data.get('value')
    rec["confidence"] = int(data.get('confidence') or 0)
    rec["firstSeen"] = data.get('firstSeen')
    rec["createdAt"] = now()
    rec["updatedAt"] = rec["createdAt"]
    _persist("Indicator", rec)
    return rec, 201

@app.route("/v1/indicators", methods=["GET"])
def list_indicators(request):
    """List Indicators."""
    items = _query("Indicator")
    return {"object": "list", "data": items, "count": len(items)}, 200


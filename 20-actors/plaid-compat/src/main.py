from kotodama import Runtime
from kotoba import load_schema
from datomic import DatomicClient
import uuid
import datetime

schema = load_schema("../schema/plaid.kotoba")
db = DatomicClient.connect()
app = Runtime("plaid-compat")


def now():
    return datetime.datetime.utcnow().isoformat()


def new_id(prefix):
    return f"{prefix}_" + uuid.uuid4().hex[:16]


def _persist(entity, rec):
    """Transact a record into Datomic as namespaced EAVT facts."""
    facts = {}
    for k, v in rec.items():
        facts[f"plaid.{entity}/{k}"] = v
    db.transact([facts])
    return rec


def _query(entity, eid=None):
    """Read records of an entity from Datomic (optionally by id)."""
    pattern = {"entity": f"plaid.{entity}"}
    if eid is not None:
        pattern["id"] = eid
    return db.query(pattern)


def _require(data, fields):
    missing = [f for f in fields if not data.get(f)]
    if missing:
        return {"error": {"message": "Missing required fields: " + ", ".join(missing)}}
    return None


@app.route("/v1/items", methods=["POST"])
def create_item(request):
    """Create a Item."""
    data = request.json or request.form or {}
    err = _require(data, ['status', 'consentExpiresAt'])
    if err:
        return err, 400
    rec = {"id": new_id("plaid_ite")}
    rec["institutionId"] = data.get('institutionId')
    rec["status"] = data.get('status')
    rec["consentExpiresAt"] = data.get('consentExpiresAt')
    rec["createdAt"] = now()
    rec["updatedAt"] = rec["createdAt"]
    _persist("Item", rec)
    return rec, 201

@app.route("/v1/items", methods=["GET"])
def list_items(request):
    """List Items."""
    items = _query("Item")
    return {"object": "list", "data": items, "count": len(items)}, 200

@app.route("/v1/items/<eid>", methods=["GET"])
def get_item(request, eid):
    """Retrieve a Item by id."""
    rows = _query("Item", eid)

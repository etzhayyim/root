from kotodama import Runtime
from kotoba import load_schema
from datomic import DatomicClient
import uuid
import datetime

schema = load_schema("../schema/hawkeye360.kotoba")
db = DatomicClient.connect()
app = Runtime("hawkeye360-compat")


def now():
    return datetime.datetime.utcnow().isoformat()


def new_id(prefix):
    return f"{prefix}_" + uuid.uuid4().hex[:16]


def _persist(entity, rec):
    """Transact a record into Datomic as namespaced EAVT facts."""
    facts = {}
    for k, v in rec.items():
        facts[f"hawkeye360.{entity}/{k}"] = v
    db.transact([facts])
    return rec


def _query(entity, eid=None):
    """Read records of an entity from Datomic (optionally by id)."""
    pattern = {"entity": f"hawkeye360.{entity}"}
    if eid is not None:
        pattern["id"] = eid
    return db.query(pattern)


def _require(data, fields):
    missing = [f for f in fields if not data.get(f)]
    if missing:
        return {"error": {"message": "Missing required fields: " + ", ".join(missing)}}
    return None


@app.route("/v1/objects", methods=["POST"])
def create_object(request):
    """Create a Object."""
    data = request.json or request.form or {}
    err = _require(data, ['designator', 'type'])
    if err:
        return err, 400
    rec = {"id": new_id("hawkeye3_obj")}
    rec["designator"] = data.get('designator')
    rec["type"] = data.get('type')
    rec["source"] = data.get('source')
    rec["createdAt"] = now()
    rec["updatedAt"] = rec["createdAt"]
    _persist("Object", rec)
    return rec, 201

@app.route("/v1/objects", methods=["GET"])
def list_objects(request):
    """List Objects."""
    items = _query("Object")
    return {"object": "list", "data": items, "count": len(items)}, 200

@app.route("/v1/objects/<eid>", methods=["GET"])
def get_object(request, eid):
    """Retrieve a Object by id."""
    rows = _query("Object", eid)
    if not rows:
        return {"error": {"message": "Not found"}}, 404
    return rows[0], 200

@app.route("/v1/objects/<eid>", methods=["POST", "PATCH"])
def update_object(request, eid):
    """Update a Object."""
    rows = _query("Object", eid)
    if not rows:
        return {"error": {"message": "Not found"}}, 404
    data = request.json or request.form or {}
    rec = rows[0]
    for k, v in data.items():
        if k in rec and k not in ("id", "createdAt"):
            rec[k] = v
    rec["updatedAt"] = now()
    _persist("Object", rec)
    return rec, 200

@app.route("/v1/objects/<eid>", methods=["DELETE"])
def delete_object(request, eid):
    """Delete a Object."""
    rows = _query("Object", eid)
    if not rows:
        return {"error": {"message": "Not found"}}, 404
    db.retract({"entity": f"hawkeye360.Object", "id": eid})
    return {"id": eid, "deleted": True}, 200


;; coverage.clj — 弾正 (danjo) revenue-ledger HONEST coverage report + maturity scorecard.
;; ADR-2605301600. The matsurigoto `coverage.md` discipline: report what is covered and what is
;; NOT, never inflate. `report` computes the numbers; `coverage-md` renders the scorecard;
;; `-main` regenerates data/REVENUE-COVERAGE.md.
;;
;; Honesty (danjo G5 / matsurigoto G5 coverage-honesty): traceability is reported per (tax, fy),
;; non-traceable taxes are counted as non-traceable (NOT hidden), and reconciliations split into
;; within-budget vs divergence vs outlay-without-appropriation-trace (partial-corpus, declared).
(ns root.danjo.methods.coverage
  (:require [clojure.string :as str]
            [clojure.java.io :as io]))

(load-file "discrepancy.clj")   ; loads revenue_ledger.clj too
(load-file "ingest.clj")
(alias 'rl 'root.danjo.methods.revenue-ledger)
(alias 'd  'root.danjo.methods.discrepancy)
(alias 'in 'root.danjo.methods.ingest)

(defn fiscal-years [model]
  (sort (distinct (concat (map :fiscal-year (:revenue-lines model))
                          (map :fiscal-year (:transfers model))
                          (map :fiscal-year (:appropriations model))
                          (map :fiscal-year (:outlays model))))))

(defn tax-kinds [model] (sort (distinct (map :tax-kind (:revenue-lines model)))))

(defn report
  "Honest coverage map over an ingested model."
  [model]
  (let [fys   (fiscal-years model)
        taxes (tax-kinds model)
        traces (vec (for [fy fys t taxes
                          :when (some #(and (= (:tax-kind %) t) (= (:fiscal-year %) fy))
                                      (:revenue-lines model))]
                      (let [tr (rl/trace model t fy)]
                        {:tax t :fiscal-year fy :traceable? (:traceable? tr)
                         :per-yen? (:per-yen? tr) :residual (:residual tr)
                         :reason (:reason tr)})))
        recon  (mapcat #(d/reconcile model %) fys)
        cat-n  (fn [c] (count (filter #(= c (:category %)) recon)))]
    {:fiscal-years fys
     :tax-kinds taxes
     :accounts (mapv (fn [a] {:id (:id a) :earmark? (:earmark? a)}) (:accounts model))
     :counts {:revenue-lines  (count (:revenue-lines model))
              :transfers      (count (:transfers model))
              :appropriations (count (:appropriations model))
              :outlays        (count (:outlays model))
              :datoms         (count (rl/all-datoms model))}
     :traces traces
     :traceable-tax-years    (count (filter :traceable? traces))
     :nontraceable-tax-years (count (remove :traceable? traces))
     :reconciliations
     {:total (count recon)
      :within                          (cat-n :appropriation-outlay-within)
      :outlay-exceeds-appropriation    (cat-n :outlay-exceeds-appropriation)
      :outlay-without-appropriation-trace (cat-n :outlay-without-appropriation-trace)}
     :verification-status (:verification-status model)}))

(defn- pct [n total] (if (zero? total) "—" (format "%.0f%%" (* 100.0 (/ (double n) total)))))

(defn coverage-md
  "Render the coverage report as a MATURITY-style markdown scorecard."
  [rep]
  (let [c (:counts rep) tt (count (:traces rep))]
    (str
     "# danjo 弾正 revenue-ledger — coverage scorecard\n\n"
     "_Generated by `methods/coverage.clj` (`-main`). HONEST coverage — non-traceable taxes are\n"
     "counted as non-traceable, not hidden (matsurigoto G5 / danjo G5). Verification status: **"
     (name (or (:verification-status rep) :representative)) "** — NOT an authoritative budget statement._\n\n"
     "## Scope\n\n"
     "- Fiscal years: " (str/join ", " (:fiscal-years rep)) "\n"
     "- Tax kinds: " (str/join ", " (map name (:tax-kinds rep))) "\n"
     "- Accounts: " (str/join ", " (map (fn [a] (str (:id a) (if (:earmark? a) " (earmarked)" " (fungible)"))) (:accounts rep))) "\n\n"
     "## Counts\n\n"
     "| revenue-lines | transfers | appropriations | outlays | EAVT datoms |\n"
     "|---|---|---|---|---|\n"
     "| " (:revenue-lines c) " | " (:transfers c) " | " (:appropriations c) " | " (:outlays c) " | " (:datoms c) " |\n\n"
     "## Per-yen traceability (the honest answer)\n\n"
     "Traceable tax-years: **" (:traceable-tax-years rep) "/" tt "** (" (pct (:traceable-tax-years rep) tt) ") · "
     "non-traceable (fungible 一般会計): **" (:nontraceable-tax-years rep) "/" tt "**\n\n"
     "| tax | FY | traceable? | per-yen? | residual |\n|---|---|---|---|---|\n"
     (str/join "\n" (for [t (:traces rep)]
                      (str "| " (name (:tax t)) " | " (:fiscal-year t) " | "
                           (if (:traceable? t) "✅" "❌ " ) (when-not (:traceable? t) (str (name (:reason t)))) " | "
                           (if (:per-yen? t) "✅" "—") " | "
                           (if (:traceable? t) (:residual t) "—") " |")))
     "\n\n## Appropriation↔outlay reconciliation\n\n"
     (let [r (:reconciliations rep)]
       (str "Total program-years: " (:total r) " · within-budget: **" (:within r) "** · "
            "outlay-exceeds-appropriation: " (:outlay-exceeds-appropriation r) " · "
            "outlay-without-appropriation-trace: " (:outlay-without-appropriation-trace r)
            " (partial-corpus / timing — a declared false-positive mode, not a verdict)\n"))
     "\n_danjo finds, never judges (G4). Legal characterization → human counsel via chigiri._\n")))

(defn -main [& args]
  (let [model (in/with-budget (in/ingest (or (first args) "../data/gov-revenue-corpus.jp.edn"))
                              (in/ingest-budget "../data/gov-fiscal-seed.jp.json"))
        rep   (report model)
        out   (io/file "../data/REVENUE-COVERAGE.md")]
    (io/make-parents out)
    (spit out (coverage-md rep))
    (println "wrote" (.getPath out))
    (println "  fiscal-years:" (:fiscal-years rep)
             "| traceable tax-years:" (:traceable-tax-years rep) "/" (count (:traces rep))
             "| datoms:" (:datoms (:counts rep)))))

;; maturity.clj — 弾正 (danjo) revenue-ledger MATURITY gate-verifier + R-level scorecard.
;; ADR-2605301600. Runs the actor's HONESTY INVARIANTS across the WHOLE dataset (not just unit
;; fixtures) and renders data/REVENUE-MATURITY.md. This is the maturity artifact other Tier-B
;; actors carry (MATURITY.md), made executable: an invariant that regresses fails the scorecard.
(ns root.danjo.methods.maturity
  (:require [clojure.string :as str]
            [clojure.java.io :as io]))

(load-file "coverage.clj")        ; transitively loads revenue_ledger/ingest/discrepancy/taxes/org_actor/transfers
(alias 'rl 'root.danjo.methods.revenue-ledger)
(alias 'in 'root.danjo.methods.ingest)
(alias 't  'root.danjo.methods.taxes)
(alias 'o  'root.danjo.methods.org-actor)
(alias 'tr 'root.danjo.methods.transfers)
(alias 'cov 'root.danjo.methods.coverage)

(defn- raises? [f] (try (f) false (catch Exception _ true)))

(defn context []
  (let [nat (t/load-taxes "../data/jp-national-taxes.edn")
        loc (t/load-local-taxes "../data/jp-local-taxes.edn")
        comb (t/combine nat loc)
        orgs (o/load-orgs "../data/jp-fiscal-orgs.edn")
        seed (rl/load-seed "../data/gov-revenue-seed.jp.edn")
        model (in/full-model)
        xfer (tr/compute (tr/load-transfers "../data/jp-fiscal-transfers.edn") nat)]
    {:nat nat :loc loc :comb comb :orgs orgs :seed seed :model model :xfer xfer}))

(def invariants
  "Each: {:id :desc :gate (fn [ctx] bool)}. True = honesty invariant holds across all data."
  [{:id :g4-datoms-clean :gate "G4"
    :desc "all emitted datoms (revenue/tax/org/transfer) contain no verdict token"
    :check (fn [c] (and (not (raises? #(rl/all-datoms (:model c))))
                        (not (raises? #(t/tax-datoms (:comb c))))
                        (not (raises? #(o/org-datoms (:orgs c) (:comb c))))
                        (not (raises? #(tr/transfer-datoms (:xfer c))))))}
   {:id :per-yen-iff-special :gate "honesty"
    :desc "a tax is per-yen-traceable IFF its earmark-kind is :special-account"
    :check (fn [c] (every? (fn [tx] (= (boolean (:per-yen? (t/classify tx)))
                                       (= :special-account (:earmark-kind tx))))
                           (:taxes (:comb c))))}
   {:id :honesty-gate-raises :gate "honesty"
    :desc "linking a tax to an outlay through a non-earmarked (一般会計) account is unrepresentable"
    :check (fn [c] (raises? #(rl/outlay-datoms
                              (update (:model c) :outlays conj
                                      {:record-id "probe" :account :general :program-code "X"
                                       :program-name "x" :cofog "0" :recipient-class "x"
                                       :fiscal-year 2024 :amount-jpy 1 :funded-by-tax :withholding-income
                                       :source-record-cids ["a" "b"]}))))}
   {:id :reconstruction-residual-0 :gate "per-yen"
    :desc "復興特別所得税 reconciles 繰入→歳出 to residual 0 (1円照合)"
    :check (fn [c] (zero? (:residual (rl/trace (:seed c) :reconstruction-surtax 2024))))}
   {:id :withholding-non-traceable :gate "honesty"
    :desc "源泉所得税 stays non-traceable overall (portion transfers never flip it)"
    :check (fn [c] (false? (:traceable? (rl/trace (:seed c) :withholding-income 2024))))}
   {:id :transfer-residual-0 :gate "per-yen"
    :desc "国→地方 法定率繰入 inflow = distributed (residual 0)"
    :check (fn [c] (zero? (:residual (tr/report (:xfer c)))))}
   {:id :orgs-keyless :gate "no-server-key"
    :desc "every org mirror-actor profile is keyless with empty verificationMethod"
    :check (fn [c] (every? #(let [p (o/org-profile % (:orgs c) (:comb c))]
                              (and (true? (:keyless p)) (= [] (:verificationMethod p))))
                           (:orgs (:orgs c))))}
   {:id :g5-provenance :gate "G5"
    :desc "every ingested revenue-line + outlay cites ≥2 source CIDs"
    :check (fn [c] (every? #(>= (count (:source-record-cids %)) 2)
                           (concat (:revenue-lines (:model c)) (:outlays (:model c)))))}
   {:id :representative-only :gate "G5"
    :desc "no dataset claims authoritative status — all :representative"
    :check (fn [c] (every? #(= "representative" (:verification-status %))
                           [(:nat c) (:loc c)]))}])

(defn run-invariants [c]
  (mapv (fn [iv] (assoc (dissoc iv :check) :ok (boolean ((:check iv) c)))) invariants))

(defn scorecard [c]
  (let [results (run-invariants c)
        passed (count (filter :ok results))
        s (t/summary (:comb c))
        rep (cov/report (:model c))]
    (str
     "# danjo 弾正 revenue-ledger — MATURITY scorecard\n\n"
     "_Generated by `methods/maturity.clj` (`-main`). Executable maturity: each row is an honesty\n"
     "invariant checked across the WHOLE dataset; a regression turns it ❌._\n\n"
     "**Status: R0** (offline, `:representative`). **Invariants: " passed "/" (count results) " passing.**\n\n"
     "## Honesty invariants\n\n"
     "| gate | invariant | |\n|---|---|---|\n"
     (str/join "\n" (for [r results]
                      (str "| " (:gate r) " | " (:desc r) " | " (if (:ok r) "✅" "❌") " |")))
     "\n\n## Constitutional gates (danjo discipline)\n\n"
     "- **G3 passive-only** — corpus IS the input; no live portal fetch (ingest reads pinned EDN/JSON).\n"
     "- **G4 non-adjudicating** — verdict token unrepresentable in any datom/category (checked above).\n"
     "- **G5 provenance** — ≥2 source CIDs per record; all figures `:representative`.\n"
     "- **G6 open method** — discrepancy detector method-note is open, versioned, content-CID'd.\n"
     "- **no-server-key** — org mirror-actors keyless; live kotoba bridge uses public DID bearer only.\n\n"
     "## Coverage snapshot\n\n"
     "- Taxes: **" (:tax-count s) "** (国 " (get-in s [:by-level :national :count]) " + 地方 "
     (get-in s [:by-level :local :count]) "), ≈ " (cov/oku (:total-jpy s)) "円 (representative)\n"
     "- Per-yen-traceable share: **" (format "%.1f%%" (* 100 (:per-yen-traceable-share s))) "** (特別会計分のみ)\n"
     "- Org mirror-actors: **" (count (:orgs (:orgs c))) "** (keyless) · Fiscal years: "
     (str/join ", " (:fiscal-years rep)) "\n"
     "- 国→地方 法定率繰入: ≈ " (cov/oku (:total-inflow (:xfer c))) "円 (per-yen traceable)\n\n"
     "## R1 activation triggers (gated)\n\n"
     "1. G7 live verification of the IPFS-pinned `jp_yosan`/`jp_fukko` corpus (Council/operator).\n"
     "2. Lexicon registration for `:gov.tax/* :gov.org/* :gov.transfer/*` + the discrepancy obs shape.\n"
     "3. Live kotoba-engine transact (`DANJO_KOTOBA_LIVE=1`) + fleet heartbeat registration.\n")))

(defn -main [& _]
  (let [c (context)
        results (run-invariants c)
        failed (remove :ok results)]
    (let [out (io/file "../data/REVENUE-MATURITY.md")]
      (io/make-parents out)
      (spit out (scorecard c))
      (println "wrote" (.getPath out)
               "—" (count (filter :ok results)) "/" (count results) "invariants passing"))
    (when (seq failed)
      (doseq [f failed] (println "  ❌" (:id f) "—" (:desc f)))
      (System/exit 1))))

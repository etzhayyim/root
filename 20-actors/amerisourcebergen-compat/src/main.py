from kotodama import Runtime
from kotoba import load_schema
from datomic import DatomicClient
import uuid
import datetime

schema = load_schema("../schema/amerisourcebergen.kotoba")
db = DatomicClient.connect()
app = Runtime("amerisourcebergen-compat")


def now():
    return datetime.datetime.utcnow().isoformat()


def new_id(prefix):
    return f"{prefix}_" + uuid.uuid4().hex[:16]


def _persist(entity, rec):
    """Transact a record into Datomic as namespaced EAVT facts."""
    facts = {}
    for k, v in rec.items():
        facts[f"amerisourcebergen.{entity}/{k}"] = v
    db.transact([facts])
    return rec


def _query(entity, eid=None):
    """Read records of an entity from Datomic (optionally by id)."""
    pattern = {"entity": f"amerisourcebergen.{entity}"}
    if eid is not None:
        pattern["id"] = eid
    return db.query(pattern)


def _require(data, fields):
    missing = [f for f in fields if not data.get(f)]
    if missing:
        return {"error": {"message": "Missing required fields: " + ", ".join(missing)}}
    return None


@app.route("/v1/prescriptions", methods=["POST"])
def create_prescription(request):
    """Create a Prescription."""
    data = request.json or request.form or {}
    err = _require(data, ['quantity', 'refills'])
    if err:
        return err, 400
    rec = {"id": new_id("amerisou_pre")}
    rec["memberId"] = data.get('memberId')
    rec["drugId"] = data.get('drugId')
    rec["quantity"] = int(data.get('quantity') or 0)
    rec["refills"] = int(data.get('refills') or 0)
    rec["status"] = data.get('status')
    rec["createdAt"] = now()
    rec["updatedAt"] = rec["createdAt"]
    _persist("Prescription", rec)
    return rec, 201

@app.route("/v1/prescriptions", methods=["GET"])
def list_prescriptions(request):
    """List Prescriptions."""
    items = _query("Prescription")
    return {"object": "list", "data": items, "count": len(items)}, 200


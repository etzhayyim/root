from kotodama import Runtime
from kotoba import load_schema
from datomic import DatomicClient
import uuid
import datetime

schema = load_schema("../schema/toshiba_global_commerce.kotoba")
db = DatomicClient.connect()
app = Runtime("toshiba_global_commerce-compat")


def now():
    return datetime.datetime.utcnow().isoformat()


def new_id(prefix):
    return f"{prefix}_" + uuid.uuid4().hex[:16]


def _persist(entity, rec):
    """Transact a record into Datomic as namespaced EAVT facts."""
    facts = {}
    for k, v in rec.items():
        facts[f"toshiba_global_commerce.{entity}/{k}"] = v
    db.transact([facts])
    return rec


def _query(entity, eid=None):
    """Read records of an entity from Datomic (optionally by id)."""
    pattern = {"entity": f"toshiba_global_commerce.{entity}"}
    if eid is not None:
        pattern["id"] = eid
    return db.query(pattern)


def _require(data, fields):
    missing = [f for f in fields if not data.get(f)]
    if missing:
        return {"error": {"message": "Missing required fields: " + ", ".join(missing)}}
    return None


@app.route("/v1/products", methods=["POST"])
def create_product(request):
    """Create a Product."""
    data = request.json or request.form or {}
    err = _require(data, ['sku', 'title'])
    if err:
        return err, 400
    rec = {"id": new_id("toshibag_pro")}
    rec["sku"] = data.get('sku')
    rec["title"] = data.get('title')
    rec["price"] = float(data.get('price') or 0)
    rec["currency"] = data.get('currency')
    rec["inventory"] = int(data.get('inventory') or 0)
    rec["createdAt"] = now()
    rec["updatedAt"] = rec["createdAt"]
    _persist("Product", rec)
    return rec, 201

@app.route("/v1/products", methods=["GET"])
def list_products(request):
    """List Products."""
    items = _query("Product")
    return {"object": "list", "data": items, "count": len(items)}, 200

@app.route("/v1/products/<eid>", methods=["GET"])
def get_product(request, eid):
    """Retrieve a Product by id."""

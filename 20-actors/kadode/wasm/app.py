"""kadode 門出 — kotoba pywasm component entry (ADR-2606112238).

Implements the five `etzhayyim:kadode/kadode-actor` world exports (wit/world.wit). The bounded
PUBLIC labour-law seed is embedded read-only (`wasm/_embedded_seed.py`, generated by build.sh)
so the component needs no FS/network at runtime — G1 (使者-not-agent) and no-server-key hold in
WASM (the `relay` export builds an UNSENT record and refuses negotiation-needing scenarios).

Runnable as plain Python (dev mode): falls back to the on-disk seed when the embedded module is
absent, so `python3 wasm/app.py {analyze|datoms|coverage|generate|relay}` verifies the exports.
"""
from __future__ import annotations
import sys, json, pathlib

_HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(_HERE.parent / "methods"))

import analyze as _analyze          # noqa: E402
import datom_emit as _datom_emit    # noqa: E402
import coverage_report as _coverage  # noqa: E402
import generate as _generate        # noqa: E402


def _seed_text() -> str:
    try:
        from _embedded_seed import SEED_EDN  # generated by build.sh; absent in dev
        return SEED_EDN
    except ImportError:
        return (_HERE.parent / "data" / "seed-resignation-graph.kotoba.edn").read_text(encoding="utf-8")


def _load():
    forms = _analyze.read_edn(_seed_text())
    nodes, edges = {}, []
    for f in forms:
        if not isinstance(f, dict):
            continue
        if ":lx/id" in f:
            nodes[f[":lx/id"]] = f
        elif ":en/from" in f and ":en/to" in f:
            edges.append(f)
    return nodes, edges


def analyze() -> str:
    nodes, edges = _load()
    res = _analyze.analyze(nodes, edges)
    routes = {sid: {"route": r["route"], "actor": r.get("route_actor"),
                    "needs_negotiation": r["needs_negotiation"],
                    "can_negotiate": r.get("can_negotiate")}
              for sid, r in res["routes"].items()}
    return json.dumps({"routes": routes, "ground_support": res["ground_support"],
                       "risk_coverage": res["risk_coverage"]}, ensure_ascii=False)


def datoms(tx: int = 1) -> str:
    nodes, edges = _load()
    return _datom_emit.emit(nodes, edges, _analyze.analyze(nodes, edges), int(tx))


def coverage() -> str:
    nodes, edges = _load()
    return _coverage.report(nodes, edges)


def generate(kind: str, fields_json: str) -> str:
    fields = json.loads(fields_json) if fields_json else {}
    return _generate.render(kind, fields)


def relay(scenario_id: str, fields_json: str, worker_did: str, employer_ref: str) -> str:
    nodes, edges = _load()
    fields = json.loads(fields_json) if fields_json else {}
    doc = _generate.render("taishoku-todoke", fields)
    return json.dumps(_generate.build_relay(scenario_id, doc, worker_did, employer_ref, nodes, edges),
                      ensure_ascii=False)


if __name__ == "__main__":
    cmd = sys.argv[1] if len(sys.argv) > 1 else "analyze"
    if cmd == "analyze":
        print(analyze())
    elif cmd == "datoms":
        print(datoms(int(sys.argv[2]) if len(sys.argv) > 2 else 1))
    elif cmd == "coverage":
        print(coverage())
    elif cmd == "generate":
        print(generate(sys.argv[2] if len(sys.argv) > 2 else "taishoku-todoke",
                       sys.argv[3] if len(sys.argv) > 3 else '{"worker":"山田太郎"}'))
    elif cmd == "relay":
        print(relay(sys.argv[2] if len(sys.argv) > 2 else "sc.permanent-cant-face",
                    sys.argv[3] if len(sys.argv) > 3 else '{"worker":"山田太郎"}',
                    "did:plc:worker", "employer-hash"))
    else:
        print(f"unknown export: {cmd}", file=sys.stderr); sys.exit(1)

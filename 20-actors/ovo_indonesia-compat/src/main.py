from kotodama import Runtime
from kotoba import load_schema
from datomic import DatomicClient
import uuid
import datetime

schema = load_schema("../schema/ovo_indonesia.kotoba")
db = DatomicClient.connect()
app = Runtime("ovo_indonesia-compat")


def now():
    return datetime.datetime.utcnow().isoformat()


def new_id(prefix):
    return f"{prefix}_" + uuid.uuid4().hex[:16]


def _persist(entity, rec):
    """Transact a record into Datomic as namespaced EAVT facts."""
    facts = {}
    for k, v in rec.items():
        facts[f"ovo_indonesia.{entity}/{k}"] = v
    db.transact([facts])
    return rec


def _query(entity, eid=None):
    """Read records of an entity from Datomic (optionally by id)."""
    pattern = {"entity": f"ovo_indonesia.{entity}"}
    if eid is not None:
        pattern["id"] = eid
    return db.query(pattern)


def _require(data, fields):
    missing = [f for f in fields if not data.get(f)]
    if missing:
        return {"error": {"message": "Missing required fields: " + ", ".join(missing)}}
    return None


@app.route("/v1/customers", methods=["POST"])
def create_customer(request):
    """Create a Customer."""
    data = request.json or request.form or {}
    err = _require(data, ['email', 'name'])
    if err:
        return err, 400
    rec = {"id": new_id("ovoindon_cus")}
    rec["email"] = data.get('email')
    rec["name"] = data.get('name')
    rec["phone"] = data.get('phone')
    rec["balance"] = int(data.get('balance') or 0)
    rec["createdAt"] = now()
    rec["updatedAt"] = rec["createdAt"]
    _persist("Customer", rec)
    return rec, 201

@app.route("/v1/customers", methods=["GET"])
def list_customers(request):
    """List Customers."""
    items = _query("Customer")
    return {"object": "list", "data": items, "count": len(items)}, 200


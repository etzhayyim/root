from kotodama import Runtime
from kotoba import load_schema
from datomic import DatomicClient
import uuid
import datetime

schema = load_schema("../schema/johndeere_api.kotoba")
db = DatomicClient.connect()
app = Runtime("johndeere_api-compat")


def now():
    return datetime.datetime.utcnow().isoformat()


def new_id(prefix):
    return f"{prefix}_" + uuid.uuid4().hex[:16]


def _persist(entity, rec):
    """Transact a record into Datomic as namespaced EAVT facts."""
    facts = {}
    for k, v in rec.items():
        facts[f"johndeere_api.{entity}/{k}"] = v
    db.transact([facts])
    return rec


def _query(entity, eid=None):
    """Read records of an entity from Datomic (optionally by id)."""
    pattern = {"entity": f"johndeere_api.{entity}"}
    if eid is not None:
        pattern["id"] = eid
    return db.query(pattern)


def _require(data, fields):
    missing = [f for f in fields if not data.get(f)]
    if missing:
        return {"error": {"message": "Missing required fields: " + ", ".join(missing)}}
    return None


@app.route("/v1/fields", methods=["POST"])
def create_field(request):
    """Create a Field."""
    data = request.json or request.form or {}
    err = _require(data, ['name', 'areaHa'])
    if err:
        return err, 400
    rec = {"id": new_id("johndeer_fie")}
    rec["name"] = data.get('name')
    rec["areaHa"] = float(data.get('areaHa') or 0)
    rec["crop"] = data.get('crop')
    rec["lat"] = float(data.get('lat') or 0)
    rec["lon"] = float(data.get('lon') or 0)
    rec["createdAt"] = now()
    rec["updatedAt"] = rec["createdAt"]
    _persist("Field", rec)
    return rec, 201

@app.route("/v1/fields", methods=["GET"])
def list_fields(request):
    """List Fields."""
    items = _query("Field")
    return {"object": "list", "data": items, "count": len(items)}, 200

@app.route("/v1/fields/<eid>", methods=["GET"])
def get_field(request, eid):
    """Retrieve a Field by id."""
    rows = _query("Field", eid)

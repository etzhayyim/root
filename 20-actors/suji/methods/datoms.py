"""suji (筋) — emit analyze results as kotoba EAVT Datoms (G9). Stdlib only.

Closes the G9 audit loop: the same physics `analyze.py` computes is projected into the
canonical kotoba Datom log shape (kotoba/schema.edn), so a body / posture / joint-load /
muscle-tension / strain is a replayable, as-of Datom (非終末論 — no final state). The
datoms here are the live equivalent of the hand-written kotoba/seed.edn, generated from the
solver rather than transcribed.

NON-DIAGNOSTIC (G1): every emitted attribute is a mechanical quantity declared in the
schema; `test_datoms.py` drift-locks the emitted attribute set against schema.edn (so a
clinical attribute could never be emitted) and asserts every ref resolves.
"""

from __future__ import annotations

from analyze import ScenarioResult, analyze_all
from strain import stiffness_band

_JOINT_KW = {"cervicothoracic": ":cervicothoracic", "shoulder": ":shoulder",
             "lumbosacral": ":lumbosacral"}


def _muscle_kw(name: str) -> str:
    return ":" + name.replace("_", "-")


def body_datom(body_id: str, total_mass_kg: float, stature_m: float) -> dict:
    return {":body/id": body_id, ":body/total-mass-kg": round(total_mass_kg, 2),
            ":body/stature-m": round(stature_m, 3), ":body/representative": True}


def scenario_datoms(result: ScenarioResult, body_id: str, idx: int) -> list[dict]:
    """All datoms for one workstation scenario: posture + loads + tensions + strains."""
    pid = f"p-{result.workstation}"
    p = result.posture
    out: list[dict] = [{
        ":posture/id": pid, ":posture/body": body_id, ":posture/workstation": result.workstation,
        ":posture/head-flex-deg": round(p.head_flexion_deg, 2),
        ":posture/trunk-flex-deg": round(p.trunk_flexion_deg, 2),
        ":posture/shoulder-flex-deg": round(p.shoulder_flexion_deg, 2),
        ":posture/arms-supported": p.arms_supported, ":posture/as-of": idx,
    }]
    # joint loads — cervical carries the extra compressive/multiplier attributes
    cerv = result.loads.cervical
    out.append({
        ":load/id": f"{pid}-load-cerv", ":load/posture": pid, ":load/joint": ":cervicothoracic",
        ":load/moment-nm": round(cerv.extensor_moment_nm, 4),
        ":load/compressive-kgf": round(cerv.compressive_load_kgf, 2),
        ":load/mult-vs-head": round(cerv.multiplier_vs_head, 2),
    })
    for j in result.loads.joints:
        if j.joint == "cervicothoracic":
            continue
        out.append({":load/id": f"{pid}-load-{j.joint}", ":load/posture": pid,
                    ":load/joint": _JOINT_KW[j.joint], ":load/moment-nm": round(j.moment_nm, 4)})
    # muscle tensions
    for t in result.tensions:
        out.append({":muscle/id": f"{pid}-musc-{t.name}", ":muscle/posture": pid,
                    ":muscle/group": _muscle_kw(t.name), ":muscle/force-n": round(t.force_n, 2),
                    ":muscle/mvc-pct": round(t.mvc_pct, 2)})
    # strains (endurance inf → -1.0 per schema convention)
    for st in result.strains:
        end = -1.0 if st.endurance_minutes == float("inf") else round(st.endurance_minutes, 2)
        out.append({":strain/id": f"{pid}-strain-{st.name}", ":strain/posture": pid,
                    ":strain/group": _muscle_kw(st.name), ":strain/session-min": st.session_minutes,
                    ":strain/endurance-min": end, ":strain/stiffness": round(st.stiffness_index, 4),
                    ":strain/band": ":" + stiffness_band(st.stiffness_index), ":strain/as-of": idx})
    return out


def results_to_datoms(results: list[ScenarioResult], total_mass_kg: float = 70.0,
                      stature_m: float = 1.70, body_id: str = "ref-adult-70-170") -> list[dict]:
    """Project a full analyze run into a flat list of kotoba Datoms (body shared)."""
    datoms = [body_datom(body_id, total_mass_kg, stature_m)]
    for idx, r in enumerate(results):
        datoms.extend(scenario_datoms(r, body_id, idx))
    return datoms


def _fmt(v) -> str:
    if v is True:
        return "true"
    if v is False:
        return "false"
    if isinstance(v, str) and v.startswith(":"):
        return v               # keyword / ref-as-keyword stays bare
    if isinstance(v, str):
        return f'"{v}"'
    return str(v)


def render_edn(datoms: list[dict]) -> str:
    """Render datoms as seed-style EDN (one map per line)."""
    lines = [";; suji (筋) analyze → kotoba Datoms (G9; generated by methods/datoms.py).",
             ";; NON-DIAGNOSTIC (G1): mechanical attributes only. Self-referenced (G3). 非終末論.",
             "["]
    for d in datoms:
        body = " ".join(f"{k} {_fmt(v)}" for k, v in d.items())
        lines.append(f" {{{body}}}")
    lines.append("]")
    return "\n".join(lines)


def main() -> None:
    import os
    results = analyze_all(session_minutes=120.0)
    datoms = results_to_datoms(results)
    out_dir = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "out")
    os.makedirs(out_dir, exist_ok=True)
    path = os.path.join(out_dir, "posture-datoms.edn")
    with open(path, "w") as fh:
        fh.write(render_edn(datoms) + "\n")
    print(f"[wrote {len(datoms)} datoms → {path}]")


if __name__ == "__main__":
    main()

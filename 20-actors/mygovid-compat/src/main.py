from kotodama import Runtime
from kotoba import load_schema
from datomic import DatomicClient
import uuid
import datetime

schema = load_schema("../schema/mygovid.kotoba")
db = DatomicClient.connect()
app = Runtime("mygovid-compat")


def now():
    return datetime.datetime.utcnow().isoformat()


def new_id(prefix):
    return f"{prefix}_" + uuid.uuid4().hex[:16]


def _persist(entity, rec):
    """Transact a record into Datomic as namespaced EAVT facts."""
    facts = {}
    for k, v in rec.items():
        facts[f"mygovid.{entity}/{k}"] = v
    db.transact([facts])
    return rec


def _query(entity, eid=None):
    """Read records of an entity from Datomic (optionally by id)."""
    pattern = {"entity": f"mygovid.{entity}"}
    if eid is not None:
        pattern["id"] = eid
    return db.query(pattern)


def _require(data, fields):
    missing = [f for f in fields if not data.get(f)]
    if missing:
        return {"error": {"message": "Missing required fields: " + ", ".join(missing)}}
    return None


@app.route("/v1/filings", methods=["POST"])
def create_filing(request):
    """Create a Filing."""
    data = request.json or request.form or {}
    err = _require(data, ['form', 'fiscalYear'])
    if err:
        return err, 400
    rec = {"id": new_id("mygovid_fil")}
    rec["filerId"] = data.get('filerId')
    rec["form"] = data.get('form')
    rec["fiscalYear"] = data.get('fiscalYear')
    rec["status"] = data.get('status')
    rec["createdAt"] = now()
    rec["updatedAt"] = rec["createdAt"]
    _persist("Filing", rec)
    return rec, 201

@app.route("/v1/filings", methods=["GET"])
def list_filings(request):
    """List Filings."""
    items = _query("Filing")
    return {"object": "list", "data": items, "count": len(items)}, 200

@app.route("/v1/filings/<eid>", methods=["GET"])
def get_filing(request, eid):
    """Retrieve a Filing by id."""
    rows = _query("Filing", eid)
    if not rows:
        return {"error": {"message": "Not found"}}, 404
    return rows[0], 200

@app.route("/v1/filings/<eid>", methods=["POST", "PATCH"])
def update_filing(request, eid):
    """Update a Filing."""
    rows = _query("Filing", eid)

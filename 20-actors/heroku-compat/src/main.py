from kotodama import Runtime
from kotoba import load_schema
from datomic import DatomicClient
import uuid
import datetime

schema = load_schema("../schema/heroku.kotoba")
db = DatomicClient.connect()
app = Runtime("heroku-compat")


def now():
    return datetime.datetime.utcnow().isoformat()


def new_id(prefix):
    return f"{prefix}_" + uuid.uuid4().hex[:16]


def _persist(entity, rec):
    """Transact a record into Datomic as namespaced EAVT facts."""
    facts = {}
    for k, v in rec.items():
        facts[f"heroku.{entity}/{k}"] = v
    db.transact([facts])
    return rec


def _query(entity, eid=None):
    """Read records of an entity from Datomic (optionally by id)."""
    pattern = {"entity": f"heroku.{entity}"}
    if eid is not None:
        pattern["id"] = eid
    return db.query(pattern)


def _require(data, fields):
    missing = [f for f in fields if not data.get(f)]
    if missing:
        return {"error": {"message": "Missing required fields: " + ", ".join(missing)}}
    return None


@app.route("/v1/apps", methods=["POST"])
def create_app(request):
    """Create a App."""
    data = request.json or request.form or {}
    err = _require(data, ['name', 'acm'])
    if err:
        return err, 400
    rec = {"id": new_id("heroku_app")}
    rec["name"] = data.get('name')
    rec["acm"] = bool(data.get('acm'))
    rec["gitUrl"] = data.get('gitUrl')
    rec["webUrl"] = data.get('webUrl')
    rec["maintenance"] = bool(data.get('maintenance'))
    rec["internalRouting"] = bool(data.get('internalRouting'))
    rec["buildpackProvidedDescription"] = data.get('buildpackProvidedDescription')
    rec["repoSize"] = int(data.get('repoSize') or 0)
    rec["slugSize"] = int(data.get('slugSize') or 0)
    rec["createdAt"] = now()
    rec["updatedAt"] = rec["createdAt"]
    _persist("App", rec)
    return rec, 201

@app.route("/v1/apps", methods=["GET"])
def list_apps(request):
    """List Apps."""
    items = _query("App")
    return {"object": "list", "data": items, "count": len(items)}, 200

@app.route("/v1/apps/<eid>", methods=["GET"])
def get_app(request, eid):
    """Retrieve a App by id."""
    rows = _query("App", eid)
    if not rows:
        return {"error": {"message": "Not found"}}, 404
    return rows[0], 200

@app.route("/v1/apps/<eid>", methods=["POST", "PATCH"])
def update_app(request, eid):
    """Update a App."""
    rows = _query("App", eid)
    if not rows:
        return {"error": {"message": "Not found"}}, 404
    data = request.json or request.form or {}
    rec = rows[0]
    for k, v in data.items():
        if k in rec and k not in ("id", "createdAt"):
            rec[k] = v
    rec["updatedAt"] = now()
    _persist("App", rec)
    return rec, 200

@app.route("/v1/apps/<eid>", methods=["DELETE"])
def delete_app(request, eid):
    """Delete a App."""
    rows = _query("App", eid)
    if not rows:
        return {"error": {"message": "Not found"}}, 404
    db.retract({"entity": f"heroku.App", "id": eid})
    return {"id": eid, "deleted": True}, 200


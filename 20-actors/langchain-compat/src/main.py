    rec["additionalKwargs"] = data.get('additionalKwargs')
    rec["responseMetadata"] = data.get('responseMetadata')
    rec["type"] = data.get('type')
    rec["name"] = data.get('name')
    rec["createdAt"] = now()
    rec["updatedAt"] = rec["createdAt"]
    _persist("BaseMessage", rec)
    return rec, 201


schema = load_schema("../schema/cohere.kotoba")
db = DatomicClient.connect()
app = Runtime("cohere-compat")

DEFAULT_LIMIT = 20
MAX_LIMIT = 100


def now():
    return datetime.datetime.utcnow().isoformat()


def new_id(prefix):
    return f"{prefix}_" + uuid.uuid4().hex[:16]


def _as_int(v):
    try:
        return int(v)
    except (TypeError, ValueError):
        return 0


def _as_float(v):
    try:
        return float(v)
    except (TypeError, ValueError):
        return 0.0


def _as_bool(v):
    return str(v).lower() in ("1", "true", "yes", "on") if v is not None else False


def _persist(entity, rec):
    """Transact a record into Datomic as namespaced EAVT facts."""
    facts = {}
    for k, v in rec.items():
        facts[f"cohere.{entity}/{k}"] = v
    db.transact([facts])
    return rec


def _query(entity, eid=None):
    pattern = {"entity": f"cohere.{entity}"}
    if eid is not None:
        pattern["id"] = eid
    return db.query(pattern)


def _require(data, fields):
    missing = [f for f in fields if not data.get(f)]
    if missing:
        return {"error": {"message": "Missing required fields: " + ", ".join(missing),
                          "type": "invalid_request_error"}}
    return None


def _reject_unknown(data, allowed):
    """Reject body fields not in the entity schema (strict validation)."""
    extra = [k for k in data if k not in allowed]
    if extra:
        return {"error": {"message": "Unknown fields: " + ", ".join(extra),
                          "type": "invalid_request_error"}}
    return None


def _apply_filters(rows, params, fields):
    """Filter rows by any schema field present in the query params."""
    out = rows
    for f in fields:
        if f in params and params[f] not in (None, ""):
            want = str(params[f])
            out = [r for r in out if str(r.get(f)) == want]
    return out


def _paginate(rows, params):
    """Cursor pagination: limit + starting_after (an id). Returns (page, has_more)."""
    limit = min(max(_as_int(params.get("limit")) or DEFAULT_LIMIT, 1), MAX_LIMIT)
    start = params.get("starting_after")
    if start is not None:
        ids = [r.get("id") for r in rows]
        if start in ids:
            rows = rows[ids.index(start) + 1:]
    page = rows[:limit]
    return page, len(rows) > limit


def _expand(rec, params, refs):
    """?expand=<field> inlines a referenced entity (rec[field+"_obj"])."""
    want = (params.get("expand") or "").split(",")
    for field, ent in refs.items():
        if field in want and rec.get(field):
            rows = _query(ent, rec[field])
            rec[field + "_obj"] = rows[0] if rows else None
    return rec


@app.route("/v1/datasets", methods=["POST"])
def create_dataset(request):
    """Create a Dataset."""
    data = request.json or request.form or {}
    err = _reject_unknown(data, ['id', 'name', 'validationStatus', 'datasetType', 'createdAt'])
    if err:
        return err, 400
    err = _require(data, ['id', 'name'])
    if err:
        return err, 400
    if data.get('validationStatus') and data['validationStatus'] not in ['unknown', 'queued', 'processing', 'failed', 'validated', 'skipped']:
        return {"error": {"message": "invalid validationStatus; allowed: " + ", ".join(['unknown', 'queued', 'processing', 'failed', 'validated', 'skipped']), "type": "invalid_request_error"}}, 400
    if data.get('datasetType') and data['datasetType'] not in ['embed-input', 'embed-result', 'cluster-result', 'cluster-outliers', 'reranker-finetune-input', 'single-label-classification-finetune-input', 'chat-finetune-input', 'multi-label-classification-finetune-input', 'batch-chat-input', 'batch-openai-chat-input', 'batch-embed-v2-input', 'batch-chat-v2-input']:
        return {"error": {"message": "invalid datasetType; allowed: " + ", ".join(['embed-input', 'embed-result', 'cluster-result', 'cluster-outliers', 'reranker-finetune-input', 'single-label-classification-finetune-input', 'chat-finetune-input', 'multi-label-classification-finetune-input', 'batch-chat-input', 'batch-openai-chat-input', 'batch-embed-v2-input', 'batch-chat-v2-input']), "type": "invalid_request_error"}}, 400
    rec = {"id": new_id("cohere_dat")}
    rec["id"] = data.get('id')
    rec["name"] = data.get('name')
    rec["validationStatus"] = data.get('validationStatus')
    rec["datasetType"] = data.get('datasetType')
    rec["createdAt"] = data.get('createdAt')
    rec["createdAt"] = now()
    rec["updatedAt"] = rec["createdAt"]
    _persist("Dataset", rec)
    return rec, 201

@app.route("/v1/datasets", methods=["GET"])
def list_datasets(request):
    """List Datasets with filtering + cursor pagination."""
    params = request.query or {}
    rows = _query("Dataset")
    rows = _apply_filters(rows, params, ['id', 'name', 'validationStatus', 'datasetType', 'createdAt'])
    page, has_more = _paginate(rows, params)
    return {"object": "list", "data": page, "has_more": has_more,
            "count": len(page), "total": len(rows)}, 200


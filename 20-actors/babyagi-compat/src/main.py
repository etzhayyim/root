from kotodama import Runtime
from kotoba import load_schema
from datomic import DatomicClient
import uuid
import datetime

schema = load_schema("../schema/babyagi.kotoba")
db = DatomicClient.connect()
app = Runtime("babyagi-compat")


def now():
    return datetime.datetime.utcnow().isoformat()


def new_id(prefix):
    return f"{prefix}_" + uuid.uuid4().hex[:16]


def _persist(entity, rec):
    """Transact a record into Datomic as namespaced EAVT facts."""
    facts = {}
    for k, v in rec.items():
        facts[f"babyagi.{entity}/{k}"] = v
    db.transact([facts])
    return rec


def _query(entity, eid=None):
    """Read records of an entity from Datomic (optionally by id)."""
    pattern = {"entity": f"babyagi.{entity}"}
    if eid is not None:
        pattern["id"] = eid
    return db.query(pattern)


def _require(data, fields):
    missing = [f for f in fields if not data.get(f)]
    if missing:
        return {"error": {"message": "Missing required fields: " + ", ".join(missing)}}
    return None


@app.route("/v1/agents", methods=["POST"])
def create_agent(request):
    """Create a Agent."""
    data = request.json or request.form or {}
    err = _require(data, ['name', 'role'])
    if err:
        return err, 400
    rec = {"id": new_id("babyagi_age")}
    rec["name"] = data.get('name')
    rec["role"] = data.get('role')
    rec["modelRef"] = data.get('modelRef')
    rec["status"] = data.get('status')
    rec["createdAt"] = now()
    rec["updatedAt"] = rec["createdAt"]
    _persist("Agent", rec)
    return rec, 201

@app.route("/v1/agents", methods=["GET"])
def list_agents(request):
    """List Agents."""
    items = _query("Agent")
    return {"object": "list", "data": items, "count": len(items)}, 200

@app.route("/v1/agents/<eid>", methods=["GET"])
def get_agent(request, eid):
    """Retrieve a Agent by id."""
    rows = _query("Agent", eid)

from kotodama import Runtime
from kotoba import load_schema
from datomic import DatomicClient
import uuid
import datetime

schema = load_schema("../schema/bandwidth.kotoba")
db = DatomicClient.connect()
app = Runtime("bandwidth-compat")


def now():
    return datetime.datetime.utcnow().isoformat()


def new_id(prefix):
    return f"{prefix}_" + uuid.uuid4().hex[:16]


def _persist(entity, rec):
    """Transact a record into Datomic as namespaced EAVT facts."""
    facts = {}
    for k, v in rec.items():
        facts[f"bandwidth.{entity}/{k}"] = v
    db.transact([facts])
    return rec


def _query(entity, eid=None):
    """Read records of an entity from Datomic (optionally by id)."""
    pattern = {"entity": f"bandwidth.{entity}"}
    if eid is not None:
        pattern["id"] = eid
    return db.query(pattern)


def _require(data, fields):
    missing = [f for f in fields if not data.get(f)]
    if missing:
        return {"error": {"message": "Missing required fields: " + ", ".join(missing)}}
    return None


@app.route("/v1/channels", methods=["POST"])
def create_channel(request):
    """Create a Channel."""
    data = request.json or request.form or {}
    err = _require(data, ['name', 'type'])
    if err:
        return err, 400
    rec = {"id": new_id("bandwidt_cha")}
    rec["name"] = data.get('name')
    rec["type"] = data.get('type')
    rec["topic"] = data.get('topic')
    rec["memberCount"] = int(data.get('memberCount') or 0)
    rec["createdAt"] = now()
    rec["updatedAt"] = rec["createdAt"]
    _persist("Channel", rec)
    return rec, 201

@app.route("/v1/channels", methods=["GET"])
def list_channels(request):
    """List Channels."""
    items = _query("Channel")
    return {"object": "list", "data": items, "count": len(items)}, 200

@app.route("/v1/channels/<eid>", methods=["GET"])
def get_channel(request, eid):
    """Retrieve a Channel by id."""
    rows = _query("Channel", eid)

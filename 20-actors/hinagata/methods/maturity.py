#!/usr/bin/env python3
"""hinagata 雛形 — maturity dashboard generator (ADR-2606111954).

Rolls up every measured dimension of the legal-template commons — size, statute grounding,
legal-system / language / per-jurisdiction breadth, integrity, and the eight globally-grounded
core clauses — into a single MATURITY.md scorecard with an honest readiness assessment. This is
the actor's maturity SSoT: it is generated, never hand-edited, so it cannot drift from the graph.

Pure stdlib (reuses analyze / coverage / validate). Usage:
    python3 maturity.py [seed.edn]        # → MATURITY.md
"""
from __future__ import annotations
import sys, pathlib
from collections import Counter
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from analyze import load, CITE_KINDS  # noqa: E402
import validate as _validate  # noqa: E402

# the eight cross-cutting clauses the commons aims to ground worldwide
CORE_CLAUSES = ["cl.signature-esign", "cl.data-subject-rights", "cl.warranty-conformity",
                "cl.employment-termination", "cl.lease-term-generic", "cl.ip-assignment",
                "cl.cooling-off", "cl.dispute-arbitration"]


def _by_kind(nodes, kind):
    return [n for n in nodes.values() if n.get(":lt/kind") == kind]


def maturity(nodes: dict, edges: list) -> str:
    tmpls = _by_kind(nodes, ":template")
    clauses = _by_kind(nodes, ":clause")
    statutes = _by_kind(nodes, ":statute")
    jurisdictions = _by_kind(nodes, ":jurisdiction")
    concepts = _by_kind(nodes, ":concept")

    errors, warnings = _validate.validate(nodes, edges)
    langs = Counter(t.get(":template/lang") for t in tmpls)
    systems = {j.get(":jurisdiction/system") for j in jurisdictions}
    cited = {e[":en/to"] for e in edges if e.get(":en/kind") in CITE_KINDS}
    bound_clauses = {e[":en/from"] for e in edges if e.get(":en/kind") in CITE_KINDS
                     and nodes.get(e[":en/from"], {}).get(":lt/kind") == ":clause"}
    translated = {e[":en/from"] for e in edges if e.get(":en/kind") == ":translates"}

    # how many jurisdictions each core clause is grounded across (via applies-in of cited statutes)
    st_jx = {s[":lt/id"]: s.get(":statute/jurisdiction") for s in statutes}
    core_reach = {}
    for cl in CORE_CLAUSES:
        jx = {st_jx.get(e[":en/to"]) for e in edges
              if e.get(":en/kind") in CITE_KINDS and e[":en/from"] == cl}
        core_reach[cl] = len({j for j in jx if j})

    L = []
    L.append("# hinagata 雛形 — maturity scorecard\n")
    L.append("> GENERATED by `methods/maturity.py` from the kotoba-EDN graph — do not hand-edit. "
             "ADR-2606111954.\n")
    L.append("## Size\n")
    L.append("| dimension | count |")
    L.append("|---|---:|")
    L.append(f"| templates | {len(tmpls)} |")
    L.append(f"| clauses | {len(clauses)} |")
    L.append(f"| statutes | {len(statutes)} |")
    L.append(f"| jurisdictions | {len(jurisdictions)} |")
    L.append(f"| concepts | {len(concepts)} |")
    L.append(f"| 縁 (edges) | {len(edges)} |")
    L.append(f"| languages | {len([k for k in langs if k])} |")

    L.append("\n## Quality gates\n")
    L.append("| gate | status |")
    L.append("|---|:--|")
    L.append(f"| integrity (validate.py) | {'✅ 0 errors / 0 warnings' if not errors and not warnings else ('❌ ' + str(len(errors)) + ' errors') if errors else ('⚠ ' + str(len(warnings)) + ' warnings')} |")
    L.append(f"| clause statute-binding | {len(bound_clauses)}/{len(clauses)} bound |")
    L.append(f"| statute grounding | {len([s for s in statutes if s[':lt/id'] in cited])}/{len(statutes)} cited |")
    L.append(f"| legal systems | {len([s for s in systems if s])}/6 represented |")
    L.append(f"| translation linkage | {len(translated)}/{len(tmpls)} templates linked |")

    L.append("\n## Core-clause worldwide grounding (the 8 most cross-cutting concerns)\n")
    L.append("| clause | jurisdictions grounded |")
    L.append("|---|---:|")
    for cl in CORE_CLAUSES:
        label = nodes.get(cl, {}).get(":lt/label", cl)
        L.append(f"| {label} | {core_reach.get(cl, 0)} |")

    # honest readiness line
    ok = (not errors and len([s for s in systems if s]) == 6 and len(langs) >= 6
          and len(bound_clauses) >= len(clauses) - 3)
    L.append("\n## Readiness\n")
    L.append(("**R1 — mature**: clean integrity, all 6 legal systems, multilingual, core clauses "
              "globally grounded. Live legal-corpus binding + IPFS pin/IPNS remain G7-gated."
              if ok else
              "**R0/R1 — in progress**: see gaps above."))
    L.append("\n---\n_hinagata 雛形 · ADR-2606111954 · generated maturity scorecard._\n")
    return "\n".join(L)


def main(argv):
    here = pathlib.Path(__file__).resolve().parent.parent
    seed = pathlib.Path(argv[1]) if len(argv) > 1 and not argv[1].startswith("--") \
        else here / "data" / "seed-legal-template-graph.kotoba.edn"
    nodes, edges = load(seed)
    (here / "MATURITY.md").write_text(maturity(nodes, edges), encoding="utf-8")
    print(f"hinagata maturity → {here/'MATURITY.md'}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))

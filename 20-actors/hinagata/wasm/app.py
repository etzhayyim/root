"""hinagata 雛形 — kotoba pywasm component entry (ADR-2606111954).

Implements the four `etzhayyim:hinagata/hinagata-actor` world exports (wit/world.wit) as
module-level functions, the shape componentize-py binds. The bounded PUBLIC template-commons
seed is embedded as a read-only string (`wasm/_embedded_seed.py`, generated by `build.sh`) so
the component needs NO filesystem or network at runtime — G1 holds in WASM (a commons of
public templates, never advice; the component cannot leak what it does not contain), and
no-server-key holds (the `envelope` export builds an UNSIGNED record only).

Runnable as plain Python too (dev mode): if the embedded seed module is absent it falls back
to reading `data/seed-legal-template-graph.kotoba.edn`, so `python3 wasm/app.py {analyze|
datoms|coverage|envelope}` verifies the exact export bodies before the componentize-py build.
"""
from __future__ import annotations
import sys
import json
import pathlib

_HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(_HERE.parent / "methods"))

import analyze as _analyze            # noqa: E402  (pure-stdlib methods)
import datom_emit as _datom_emit      # noqa: E402
import coverage_report as _coverage   # noqa: E402
import esign as _esign                # noqa: E402


def _seed_text() -> str:
    """Embedded seed (WASM) or on-disk seed (dev). Bounded PUBLIC reference templates only."""
    try:
        from _embedded_seed import SEED_EDN  # generated by build.sh; absent in dev
        return SEED_EDN
    except ImportError:
        return (_HERE.parent / "data" / "seed-legal-template-graph.kotoba.edn").read_text(
            encoding="utf-8")


def _load():
    forms = _analyze.read_edn(_seed_text())
    nodes, edges = {}, []
    for f in forms:
        if not isinstance(f, dict):
            continue
        if ":lt/id" in f:
            nodes[f[":lt/id"]] = f
        elif ":en/from" in f and ":en/to" in f:
            edges.append(f)
    return nodes, edges


# ── world exports ─────────────────────────────────────────────────────────────
def analyze() -> str:
    nodes, edges = _load()
    res = _analyze.analyze(nodes, edges)

    def rows(d, n=20):
        return [{"id": nid, "label": nodes.get(nid, {}).get(":lt/label", nid),
                 "score": round(v, 4)} for nid, v in
                sorted(d.items(), key=lambda kv: (-kv[1], kv[0]))[:n]]

    return json.dumps({"grounded": rows(res["grounded"]), "reuse": rows(res["reuse"]),
                       "statute_pull": rows(res["statute_pull"])}, ensure_ascii=False)


def datoms(tx: int = 1) -> str:
    nodes, edges = _load()
    res = _analyze.analyze(nodes, edges)
    return _datom_emit.emit(nodes, edges, res, int(tx))


def coverage() -> str:
    nodes, edges = _load()
    return _coverage.report(nodes, edges)


def envelope(template_id: str, requester_did: str, signers_csv: str) -> str:
    """Render a template + build an UNSIGNED esign envelope (no-server-key). JSON out."""
    nodes, edges = _load()
    signers = [s.strip() for s in signers_csv.split(",") if s.strip()]
    doc = _esign.render_document(template_id, nodes, edges)
    env = _esign.build_envelope(doc, requester_did, signers,
                                subject=nodes.get(template_id, {}).get(":template/title", ""))
    return json.dumps({"document": doc, "envelope": env}, ensure_ascii=False)


if __name__ == "__main__":
    cmd = sys.argv[1] if len(sys.argv) > 1 else "analyze"
    if cmd == "analyze":
        print(analyze())
    elif cmd == "datoms":
        print(datoms(int(sys.argv[2]) if len(sys.argv) > 2 else 1))
    elif cmd == "coverage":
        print(coverage())
    elif cmd == "envelope":
        tid = sys.argv[2] if len(sys.argv) > 2 else "tmpl.nda-mutual"
        req = sys.argv[3] if len(sys.argv) > 3 else "did:web:etzhayyim.com:actor:hinagata"
        signers = sys.argv[4] if len(sys.argv) > 4 else "did:plc:alice,did:plc:bob"
        print(envelope(tid, req, signers))
    else:
        print(f"unknown export: {cmd} (analyze|datoms|coverage|envelope)", file=sys.stderr)
        sys.exit(1)

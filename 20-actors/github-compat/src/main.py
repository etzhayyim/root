from kotodama import Runtime
from kotoba import load_schema
from datomic import DatomicClient
import uuid
import datetime

schema = load_schema("../schema/github.kotoba")
db = DatomicClient.connect()
app = Runtime("github-compat")


def now():
    return datetime.datetime.utcnow().isoformat()


def new_id(prefix):
    return f"{prefix}_" + uuid.uuid4().hex[:16]


def _persist(entity, rec):
    """Transact a record into Datomic as namespaced EAVT facts."""
    facts = {}
    for k, v in rec.items():
        facts[f"github.{entity}/{k}"] = v
    db.transact([facts])
    return rec


def _query(entity, eid=None):
    """Read records of an entity from Datomic (optionally by id)."""
    pattern = {"entity": f"github.{entity}"}
    if eid is not None:
        pattern["id"] = eid
    return db.query(pattern)


def _require(data, fields):
    missing = [f for f in fields if not data.get(f)]
    if missing:
        return {"error": {"message": "Missing required fields: " + ", ".join(missing)}}
    return None


@app.route("/v1/repositories", methods=["POST"])
def create_repository(request):
    """Create a Repository."""
    data = request.json or request.form or {}
    err = _require(data, ['name', 'owner'])
    if err:
        return err, 400
    rec = {"id": new_id("github_rep")}
    rec["name"] = data.get('name')
    rec["owner"] = data.get('owner')
    rec["defaultBranch"] = data.get('defaultBranch')
    rec["private"] = bool(data.get('private'))
    rec["stars"] = int(data.get('stars') or 0)
    rec["createdAt"] = now()
    rec["updatedAt"] = rec["createdAt"]
    _persist("Repository", rec)
    return rec, 201

@app.route("/v1/repositories", methods=["GET"])
def list_repositories(request):
    """List Repositories."""
    items = _query("Repository")
    return {"object": "list", "data": items, "count": len(items)}, 200

@app.route("/v1/repositories/<eid>", methods=["GET"])
def get_repository(request, eid):
    """Retrieve a Repository by id."""

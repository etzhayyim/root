from kotodama import Runtime
from kotoba import load_schema
from datomic import DatomicClient
import uuid
import datetime

schema = load_schema("../schema/dna_script.kotoba")
db = DatomicClient.connect()
app = Runtime("dna_script-compat")


def now():
    return datetime.datetime.utcnow().isoformat()


def new_id(prefix):
    return f"{prefix}_" + uuid.uuid4().hex[:16]


def _persist(entity, rec):
    """Transact a record into Datomic as namespaced EAVT facts."""
    facts = {}
    for k, v in rec.items():
        facts[f"dna_script.{entity}/{k}"] = v
    db.transact([facts])
    return rec


def _query(entity, eid=None):
    """Read records of an entity from Datomic (optionally by id)."""
    pattern = {"entity": f"dna_script.{entity}"}
    if eid is not None:
        pattern["id"] = eid
    return db.query(pattern)


def _require(data, fields):
    missing = [f for f in fields if not data.get(f)]
    if missing:
        return {"error": {"message": "Missing required fields: " + ", ".join(missing)}}
    return None


@app.route("/v1/strains", methods=["POST"])
def create_strain(request):
    """Create a Strain."""
    data = request.json or request.form or {}
    err = _require(data, ['name', 'organism'])
    if err:
        return err, 400
    rec = {"id": new_id("dnascrip_str")}
    rec["name"] = data.get('name')
    rec["organism"] = data.get('organism')
    rec["genotype"] = data.get('genotype')
    rec["createdAt"] = now()
    rec["updatedAt"] = rec["createdAt"]
    _persist("Strain", rec)
    return rec, 201

@app.route("/v1/strains", methods=["GET"])
def list_strains(request):
    """List Strains."""
    items = _query("Strain")
    return {"object": "list", "data": items, "count": len(items)}, 200

@app.route("/v1/strains/<eid>", methods=["GET"])
def get_strain(request, eid):
    """Retrieve a Strain by id."""
    rows = _query("Strain", eid)
    if not rows:
        return {"error": {"message": "Not found"}}, 404
    return rows[0], 200

@app.route("/v1/strains/<eid>", methods=["POST", "PATCH"])
def update_strain(request, eid):
    """Update a Strain."""
    rows = _query("Strain", eid)
    if not rows:
        return {"error": {"message": "Not found"}}, 404
    data = request.json or request.form or {}
    rec = rows[0]
    for k, v in data.items():
        if k in rec and k not in ("id", "createdAt"):
            rec[k] = v
    rec["updatedAt"] = now()
    _persist("Strain", rec)
    return rec, 200

@app.route("/v1/strains/<eid>", methods=["DELETE"])
def delete_strain(request, eid):
    """Delete a Strain."""
    rows = _query("Strain", eid)
    if not rows:
        return {"error": {"message": "Not found"}}, 404
    db.retract({"entity": f"dna_script.Strain", "id": eid})
    return {"id": eid, "deleted": True}, 200


from kotodama import Runtime
from kotoba import load_schema
from datomic import DatomicClient
import uuid
import datetime

schema = load_schema("../schema/launchdarkly.kotoba")
db = DatomicClient.connect()
app = Runtime("launchdarkly-compat")


def now():
    return datetime.datetime.utcnow().isoformat()


def new_id(prefix):
    return f"{prefix}_" + uuid.uuid4().hex[:16]


def _persist(entity, rec):
    """Transact a record into Datomic as namespaced EAVT facts."""
    facts = {}
    for k, v in rec.items():
        facts[f"launchdarkly.{entity}/{k}"] = v
    db.transact([facts])
    return rec


def _query(entity, eid=None):
    """Read records of an entity from Datomic (optionally by id)."""
    pattern = {"entity": f"launchdarkly.{entity}"}
    if eid is not None:
        pattern["id"] = eid
    return db.query(pattern)


def _require(data, fields):
    missing = [f for f in fields if not data.get(f)]
    if missing:
        return {"error": {"message": "Missing required fields: " + ", ".join(missing)}}
    return None


@app.route("/v1/featureflags", methods=["POST"])
def create_feature_flag(request):
    """Create a FeatureFlag."""
    data = request.json or request.form or {}
    err = _require(data, ['key', 'name'])
    if err:
        return err, 400
    rec = {"id": new_id("launchda_fea")}
    rec["key"] = data.get('key')
    rec["name"] = data.get('name')
    rec["kind"] = data.get('kind')
    rec["description"] = data.get('description')
    rec["includeInSnippet"] = bool(data.get('includeInSnippet'))
    rec["temporary"] = bool(data.get('temporary'))
    rec["maintainerId"] = data.get('maintainerId')
    rec["maintainerTeamKey"] = data.get('maintainerTeamKey')
    rec["archived"] = bool(data.get('archived'))
    rec["deprecated"] = bool(data.get('deprecated'))
    rec["createdAt"] = now()
    rec["updatedAt"] = rec["createdAt"]
    _persist("FeatureFlag", rec)
    return rec, 201


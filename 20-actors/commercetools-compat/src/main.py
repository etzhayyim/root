from kotodama import Runtime
from kotoba import load_schema
from datomic import DatomicClient
import uuid
import datetime

schema = load_schema("../schema/commercetools.kotoba")
db = DatomicClient.connect()
app = Runtime("commercetools-compat")


def now():
    return datetime.datetime.utcnow().isoformat()


def new_id(prefix):
    return f"{prefix}_" + uuid.uuid4().hex[:16]


def _persist(entity, rec):
    """Transact a record into Datomic as namespaced EAVT facts."""
    facts = {}
    for k, v in rec.items():
        facts[f"commercetools.{entity}/{k}"] = v
    db.transact([facts])
    return rec


def _query(entity, eid=None):
    """Read records of an entity from Datomic (optionally by id)."""
    pattern = {"entity": f"commercetools.{entity}"}
    if eid is not None:
        pattern["id"] = eid
    return db.query(pattern)


def _require(data, fields):
    missing = [f for f in fields if not data.get(f)]
    if missing:
        return {"error": {"message": "Missing required fields: " + ", ".join(missing)}}
    return None


@app.route("/v1/contententries", methods=["POST"])
def create_content_entry(request):
    """Create a ContentEntry."""
    data = request.json or request.form or {}
    err = _require(data, ['modelName', 'title'])
    if err:
        return err, 400
    rec = {"id": new_id("commerce_con")}
    rec["modelName"] = data.get('modelName')
    rec["title"] = data.get('title')
    rec["locale"] = data.get('locale')
    rec["published"] = bool(data.get('published'))
    rec["createdAt"] = now()
    rec["updatedAt"] = rec["createdAt"]
    _persist("ContentEntry", rec)
    return rec, 201


from kotodama import Runtime
from kotoba import load_schema
from datomic import DatomicClient
import uuid
import datetime

schema = load_schema("../schema/pinecone.kotoba")
db = DatomicClient.connect()
app = Runtime("pinecone-compat")

DEFAULT_LIMIT = 20
MAX_LIMIT = 100


def now():
    return datetime.datetime.utcnow().isoformat()


def new_id(prefix):
    return f"{prefix}_" + uuid.uuid4().hex[:16]


def _as_int(v):
    try:
        return int(v)
    except (TypeError, ValueError):
        return 0


def _as_float(v):
    try:
        return float(v)
    except (TypeError, ValueError):
        return 0.0


def _as_bool(v):
    return str(v).lower() in ("1", "true", "yes", "on") if v is not None else False


def _persist(entity, rec):
    """Transact a record into Datomic as namespaced EAVT facts."""
    facts = {}
    for k, v in rec.items():
        facts[f"pinecone.{entity}/{k}"] = v
    db.transact([facts])
    return rec


def _query(entity, eid=None):
    pattern = {"entity": f"pinecone.{entity}"}
    if eid is not None:
        pattern["id"] = eid
    return db.query(pattern)


def _require(data, fields):
    missing = [f for f in fields if not data.get(f)]
    if missing:
        return {"error": {"message": "Missing required fields: " + ", ".join(missing),
                          "type": "invalid_request_error"}}
    return None


def _reject_unknown(data, allowed):
    """Reject body fields not in the entity schema (strict validation)."""
    extra = [k for k in data if k not in allowed]
    if extra:
        return {"error": {"message": "Unknown fields: " + ", ".join(extra),
                          "type": "invalid_request_error"}}
    return None


def _apply_filters(rows, params, fields):
    """Filter rows by any schema field present in the query params."""
    out = rows
    for f in fields:
        if f in params and params[f] not in (None, ""):
            want = str(params[f])
            out = [r for r in out if str(r.get(f)) == want]
    return out


def _paginate(rows, params):
    """Cursor pagination: limit + starting_after (an id). Returns (page, has_more)."""
    limit = min(max(_as_int(params.get("limit")) or DEFAULT_LIMIT, 1), MAX_LIMIT)
    start = params.get("starting_after")
    if start is not None:
        ids = [r.get("id") for r in rows]
        if start in ids:
            rows = rows[ids.index(start) + 1:]
    page = rows[:limit]
    return page, len(rows) > limit


def _expand(rec, params, refs):
    """?expand=<field> inlines a referenced entity (rec[field+"_obj"])."""
    want = (params.get("expand") or "").split(",")
    for field, ent in refs.items():
        if field in want and rec.get(field):
            rows = _query(ent, rec[field])
            rec[field + "_obj"] = rows[0] if rows else None
    return rec


@app.route("/v1/indexes", methods=["POST"])
def create_index(request):
    """Create a Index."""
    data = request.json or request.form or {}
    err = _reject_unknown(data, ['name', 'dimension', 'metric', 'host', 'state', 'deletionProtection', 'vectorType', 'cloud', 'ready'])
    if err:
        return err, 400
    err = _require(data, ['name', 'dimension'])
    if err:
        return err, 400
    if data.get('metric') and data['metric'] not in ['cosine', 'euclidean', 'dotproduct']:
        return {"error": {"message": "invalid metric; allowed: " + ", ".join(['cosine', 'euclidean', 'dotproduct']), "type": "invalid_request_error"}}, 400
    if data.get('state') and data['state'] not in ['Initializing', 'InitializationFailed', 'ScalingUp', 'ScalingDown', 'ScalingUpPodSize', 'ScalingDownPodSize', 'Terminating', 'Ready', 'Disabled']:
        return {"error": {"message": "invalid state; allowed: " + ", ".join(['Initializing', 'InitializationFailed', 'ScalingUp', 'ScalingDown', 'ScalingUpPodSize', 'ScalingDownPodSize', 'Terminating', 'Ready', 'Disabled']), "type": "invalid_request_error"}}, 400
    if data.get('deletionProtection') and data['deletionProtection'] not in ['enabled', 'disabled']:
        return {"error": {"message": "invalid deletionProtection; allowed: " + ", ".join(['enabled', 'disabled']), "type": "invalid_request_error"}}, 400
    if data.get('vectorType') and data['vectorType'] not in ['dense', 'sparse']:
        return {"error": {"message": "invalid vectorType; allowed: " + ", ".join(['dense', 'sparse']), "type": "invalid_request_error"}}, 400
    if data.get('cloud') and data['cloud'] not in ['aws', 'gcp', 'azure']:
        return {"error": {"message": "invalid cloud; allowed: " + ", ".join(['aws', 'gcp', 'azure']), "type": "invalid_request_error"}}, 400
    rec = {"id": new_id("pinecone_ind")}
    rec["name"] = data.get('name')
    rec["dimension"] = _as_int(data.get('dimension'))
    rec["metric"] = data.get('metric')
    rec["host"] = data.get('host')
    rec["state"] = data.get('state')
    rec["deletionProtection"] = data.get('deletionProtection')
    rec["vectorType"] = data.get('vectorType')
    rec["cloud"] = data.get('cloud')
    rec["ready"] = _as_bool(data.get('ready'))
    rec["createdAt"] = now()
    rec["updatedAt"] = rec["createdAt"]
    _persist("Index", rec)
    return rec, 201


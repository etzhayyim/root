from kotodama import Runtime
from kotoba import load_schema
from datomic import DatomicClient
import uuid
import datetime

schema = load_schema("../schema/swift_iso20022.kotoba")
db = DatomicClient.connect()
app = Runtime("swift_iso20022-compat")


def now():
    return datetime.datetime.utcnow().isoformat()


def new_id(prefix):
    return f"{prefix}_" + uuid.uuid4().hex[:16]


def _persist(entity, rec):
    """Transact a record into Datomic as namespaced EAVT facts."""
    facts = {}
    for k, v in rec.items():
        facts[f"swift_iso20022.{entity}/{k}"] = v
    db.transact([facts])
    return rec


def _query(entity, eid=None):
    """Read records of an entity from Datomic (optionally by id)."""
    pattern = {"entity": f"swift_iso20022.{entity}"}
    if eid is not None:
        pattern["id"] = eid
    return db.query(pattern)


def _require(data, fields):
    missing = [f for f in fields if not data.get(f)]
    if missing:
        return {"error": {"message": "Missing required fields: " + ", ".join(missing)}}
    return None


@app.route("/v1/accounts", methods=["POST"])
def create_account(request):
    """Create a Account."""
    data = request.json or request.form or {}
    err = _require(data, ['iban', 'currency'])
    if err:
        return err, 400
    rec = {"id": new_id("swiftiso_acc")}
    rec["holderId"] = data.get('holderId')
    rec["iban"] = data.get('iban')
    rec["currency"] = data.get('currency')
    rec["balance"] = float(data.get('balance') or 0)
    rec["createdAt"] = now()
    rec["updatedAt"] = rec["createdAt"]
    _persist("Account", rec)
    return rec, 201

@app.route("/v1/accounts", methods=["GET"])
def list_accounts(request):
    """List Accounts."""
    items = _query("Account")
    return {"object": "list", "data": items, "count": len(items)}, 200

@app.route("/v1/accounts/<eid>", methods=["GET"])
def get_account(request, eid):
    """Retrieve a Account by id."""
    rows = _query("Account", eid)
    if not rows:
        return {"error": {"message": "Not found"}}, 404

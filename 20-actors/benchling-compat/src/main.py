from kotodama import Runtime
from kotoba import load_schema
from datomic import DatomicClient
import uuid
import datetime

schema = load_schema("../schema/benchling.kotoba")
db = DatomicClient.connect()
app = Runtime("benchling-compat")


def now():
    return datetime.datetime.utcnow().isoformat()


def new_id(prefix):
    return f"{prefix}_" + uuid.uuid4().hex[:16]


def _persist(entity, rec):
    """Transact a record into Datomic as namespaced EAVT facts."""
    facts = {}
    for k, v in rec.items():
        facts[f"benchling.{entity}/{k}"] = v
    db.transact([facts])
    return rec


def _query(entity, eid=None):
    """Read records of an entity from Datomic (optionally by id)."""
    pattern = {"entity": f"benchling.{entity}"}
    if eid is not None:
        pattern["id"] = eid
    return db.query(pattern)


def _require(data, fields):
    missing = [f for f in fields if not data.get(f)]
    if missing:
        return {"error": {"message": "Missing required fields: " + ", ".join(missing)}}
    return None


@app.route("/v1/customentities", methods=["POST"])
def create_custom_entity(request):
    """Create a CustomEntity."""
    data = request.json or request.form or {}
    err = _require(data, ['apiURL', 'modifiedAt'])
    if err:
        return err, 400
    rec = {"id": new_id("benchlin_cus")}
    rec["apiURL"] = data.get('apiURL')
    rec["entityRegistryId"] = data.get('entityRegistryId')
    rec["folderId"] = data.get('folderId')
    rec["modifiedAt"] = data.get('modifiedAt')
    rec["name"] = data.get('name')
    rec["registryId"] = data.get('registryId')
    rec["url"] = data.get('url')
    rec["webURL"] = data.get('webURL')
    rec["createdAt"] = now()
    rec["updatedAt"] = rec["createdAt"]
    _persist("CustomEntity", rec)
    return rec, 201

@app.route("/v1/customentities", methods=["GET"])
def list_custom_entities(request):
    """List CustomEntities."""
    items = _query("CustomEntity")
    return {"object": "list", "data": items, "count": len(items)}, 200


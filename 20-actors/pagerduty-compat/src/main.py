from kotodama import Runtime
from kotoba import load_schema
from datomic import DatomicClient
import uuid
import datetime

schema = load_schema("../schema/pagerduty.kotoba")
db = DatomicClient.connect()
app = Runtime("pagerduty-compat")


def now():
    return datetime.datetime.utcnow().isoformat()


def new_id(prefix):
    return f"{prefix}_" + uuid.uuid4().hex[:16]


def _persist(entity, rec):
    """Transact a record into Datomic as namespaced EAVT facts."""
    facts = {}
    for k, v in rec.items():
        facts[f"pagerduty.{entity}/{k}"] = v
    db.transact([facts])
    return rec


def _query(entity, eid=None):
    """Read records of an entity from Datomic (optionally by id)."""
    pattern = {"entity": f"pagerduty.{entity}"}
    if eid is not None:
        pattern["id"] = eid
    return db.query(pattern)


def _require(data, fields):
    missing = [f for f in fields if not data.get(f)]
    if missing:
        return {"error": {"message": "Missing required fields: " + ", ".join(missing)}}
    return None


@app.route("/v1/incidents", methods=["POST"])
def create_incident(request):
    """Create a Incident."""
    data = request.json or request.form or {}
    err = _require(data, ['incidentNumber', 'title'])
    if err:
        return err, 400
    rec = {"id": new_id("pagerdut_inc")}
    rec["incidentNumber"] = int(data.get('incidentNumber') or 0)
    rec["title"] = data.get('title')
    rec["status"] = data.get('status')
    rec["incidentKey"] = data.get('incidentKey')
    rec["assignedVia"] = data.get('assignedVia')
    rec["lastStatusChangeAt"] = data.get('lastStatusChangeAt')
    rec["resolvedAt"] = data.get('resolvedAt')
    rec["isMergeable"] = bool(data.get('isMergeable'))
    rec["urgency"] = data.get('urgency')
    rec["createdAt"] = now()
    rec["updatedAt"] = rec["createdAt"]
    _persist("Incident", rec)
    return rec, 201

@app.route("/v1/incidents", methods=["GET"])
def list_incidents(request):
    """List Incidents."""
    items = _query("Incident")
    return {"object": "list", "data": items, "count": len(items)}, 200


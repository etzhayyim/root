from kotodama import Runtime
from kotoba import load_schema
from datomic import DatomicClient
import uuid
import datetime

schema = load_schema("../schema/pagerduty.kotoba")
db = DatomicClient.connect()
app = Runtime("pagerduty-compat")


def now():
    return datetime.datetime.utcnow().isoformat()


def new_id(prefix):
    return f"{prefix}_" + uuid.uuid4().hex[:16]


def _persist(entity, rec):
    """Transact a record into Datomic as namespaced EAVT facts."""
    facts = {}
    for k, v in rec.items():
        facts[f"pagerduty.{entity}/{k}"] = v
    db.transact([facts])
    return rec


def _query(entity, eid=None):
    """Read records of an entity from Datomic (optionally by id)."""
    pattern = {"entity": f"pagerduty.{entity}"}
    if eid is not None:
        pattern["id"] = eid
    return db.query(pattern)


def _require(data, fields):
    missing = [f for f in fields if not data.get(f)]
    if missing:
        return {"error": {"message": "Missing required fields: " + ", ".join(missing)}}
    return None


@app.route("/v1/services", methods=["POST"])
def create_service(request):
    """Create a Service."""
    data = request.json or request.form or {}
    err = _require(data, ['name', 'environment'])
    if err:
        return err, 400
    rec = {"id": new_id("pagerdut_ser")}
    rec["name"] = data.get('name')
    rec["environment"] = data.get('environment')
    rec["language"] = data.get('language')
    rec["createdAt"] = now()
    rec["updatedAt"] = rec["createdAt"]
    _persist("Service", rec)
    return rec, 201

@app.route("/v1/services", methods=["GET"])
def list_services(request):
    """List Services."""
    items = _query("Service")
    return {"object": "list", "data": items, "count": len(items)}, 200

@app.route("/v1/services/<eid>", methods=["GET"])
def get_service(request, eid):
    """Retrieve a Service by id."""
    rows = _query("Service", eid)
    if not rows:
        return {"error": {"message": "Not found"}}, 404
    return rows[0], 200

@app.route("/v1/services/<eid>", methods=["POST", "PATCH"])
def update_service(request, eid):
    """Update a Service."""
    rows = _query("Service", eid)
    if not rows:
        return {"error": {"message": "Not found"}}, 404
    data = request.json or request.form or {}
    rec = rows[0]
    for k, v in data.items():
        if k in rec and k not in ("id", "createdAt"):
            rec[k] = v
    rec["updatedAt"] = now()
    _persist("Service", rec)
    return rec, 200

@app.route("/v1/services/<eid>", methods=["DELETE"])
def delete_service(request, eid):
    """Delete a Service."""
    rows = _query("Service", eid)
    if not rows:
        return {"error": {"message": "Not found"}}, 404
    db.retract({"entity": f"pagerduty.Service", "id": eid})

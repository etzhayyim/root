from kotodama import Runtime
from kotoba import load_schema
from datomic import DatomicClient
import uuid
import datetime

schema = load_schema("../schema/universal_robots.kotoba")
db = DatomicClient.connect()
app = Runtime("universal_robots-compat")


def now():
    return datetime.datetime.utcnow().isoformat()


def new_id(prefix):
    return f"{prefix}_" + uuid.uuid4().hex[:16]


def _persist(entity, rec):
    """Transact a record into Datomic as namespaced EAVT facts."""
    facts = {}
    for k, v in rec.items():
        facts[f"universal_robots.{entity}/{k}"] = v
    db.transact([facts])
    return rec


def _query(entity, eid=None):
    """Read records of an entity from Datomic (optionally by id)."""
    pattern = {"entity": f"universal_robots.{entity}"}
    if eid is not None:
        pattern["id"] = eid
    return db.query(pattern)


def _require(data, fields):
    missing = [f for f in fields if not data.get(f)]
    if missing:
        return {"error": {"message": "Missing required fields: " + ", ".join(missing)}}
    return None


@app.route("/v1/rtderobotstates", methods=["POST"])
def create_rtde_robot_state(request):
    """Create a RtdeRobotState."""
    data = request.json or request.form or {}
    err = _require(data, ['timestamp', 'robot_mode'])
    if err:
        return err, 400
    rec = {"id": new_id("universa_rtd")}
    rec["timestamp"] = float(data.get('timestamp') or 0)
    rec["robot_mode"] = int(data.get('robot_mode') or 0)
    rec["robot_status_bits"] = int(data.get('robot_status_bits') or 0)
    rec["safety_mode"] = int(data.get('safety_mode') or 0)
    rec["safety_status_bits"] = int(data.get('safety_status_bits') or 0)
    rec["actual_main_voltage"] = float(data.get('actual_main_voltage') or 0)
    rec["actual_robot_voltage"] = float(data.get('actual_robot_voltage') or 0)
    rec["actual_robot_current"] = float(data.get('actual_robot_current') or 0)
    rec["createdAt"] = now()
    rec["updatedAt"] = rec["createdAt"]
    _persist("RtdeRobotState", rec)
    return rec, 201


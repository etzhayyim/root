from kotodama import Runtime
from kotoba import load_schema
from datomic import DatomicClient
import uuid
import datetime

schema = load_schema("../schema/paystack.kotoba")
db = DatomicClient.connect()
app = Runtime("paystack-compat")


def now():
    return datetime.datetime.utcnow().isoformat()


def new_id(prefix):
    return f"{prefix}_" + uuid.uuid4().hex[:16]


def _persist(entity, rec):
    """Transact a record into Datomic as namespaced EAVT facts."""
    facts = {}
    for k, v in rec.items():
        facts[f"paystack.{entity}/{k}"] = v
    db.transact([facts])
    return rec


def _query(entity, eid=None):
    """Read records of an entity from Datomic (optionally by id)."""
    pattern = {"entity": f"paystack.{entity}"}
    if eid is not None:
        pattern["id"] = eid
    return db.query(pattern)


def _require(data, fields):
    missing = [f for f in fields if not data.get(f)]
    if missing:
        return {"error": {"message": "Missing required fields: " + ", ".join(missing)}}
    return None


@app.route("/v1/transactions", methods=["POST"])
def create_transaction(request):
    """Create a Transaction."""
    data = request.json or request.form or {}
    err = _require(data, ['email', 'amount'])
    if err:
        return err, 400
    rec = {"id": new_id("paystack_tra")}
    rec["email"] = data.get('email')
    rec["amount"] = int(data.get('amount') or 0)
    rec["reference"] = data.get('reference')
    rec["callbackUrl"] = data.get('callbackUrl')
    rec["plan"] = data.get('plan')
    rec["invoiceLimit"] = int(data.get('invoiceLimit') or 0)
    rec["splitCode"] = data.get('splitCode')
    rec["subaccount"] = data.get('subaccount')
    rec["transactionCharge"] = data.get('transactionCharge')
    rec["bearer"] = data.get('bearer')
    rec["label"] = data.get('label')
    rec["createdAt"] = now()
    rec["updatedAt"] = rec["createdAt"]
    _persist("Transaction", rec)
    return rec, 201

@app.route("/v1/transactions", methods=["GET"])
def list_transactions(request):
    """List Transactions."""
    items = _query("Transaction")
    return {"object": "list", "data": items, "count": len(items)}, 200


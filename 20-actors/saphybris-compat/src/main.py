from kotodama import Runtime
from kotoba import load_schema
from datomic import DatomicClient
import uuid
import datetime

schema = load_schema("../schema/saphybris.kotoba")
db = DatomicClient.connect()
app = Runtime("saphybris-compat")


def now():
    return datetime.datetime.utcnow().isoformat()


def new_id(prefix):
    return f"{prefix}_" + uuid.uuid4().hex[:16]


def _persist(entity, rec):
    """Transact a record into Datomic as namespaced EAVT facts."""
    facts = {}
    for k, v in rec.items():
        facts[f"saphybris.{entity}/{k}"] = v
    db.transact([facts])
    return rec


def _query(entity, eid=None):
    """Read records of an entity from Datomic (optionally by id)."""
    pattern = {"entity": f"saphybris.{entity}"}
    if eid is not None:
        pattern["id"] = eid
    return db.query(pattern)


def _require(data, fields):
    missing = [f for f in fields if not data.get(f)]
    if missing:
        return {"error": {"message": "Missing required fields: " + ", ".join(missing)}}
    return None


@app.route("/v1/catalogs", methods=["POST"])
def create_catalog(request):
    """Create a Catalog."""
    data = request.json or request.form or {}
    err = _require(data, ['name', 'itemCount'])
    if err:
        return err, 400
    rec = {"id": new_id("saphybri_cat")}
    rec["name"] = data.get('name')
    rec["supplierId"] = data.get('supplierId')
    rec["itemCount"] = int(data.get('itemCount') or 0)
    rec["createdAt"] = now()
    rec["updatedAt"] = rec["createdAt"]
    _persist("Catalog", rec)
    return rec, 201

@app.route("/v1/catalogs", methods=["GET"])
def list_catalogs(request):
    """List Catalogs."""
    items = _query("Catalog")
    return {"object": "list", "data": items, "count": len(items)}, 200

@app.route("/v1/catalogs/<eid>", methods=["GET"])
def get_catalog(request, eid):
    """Retrieve a Catalog by id."""
    rows = _query("Catalog", eid)

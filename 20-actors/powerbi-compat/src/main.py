    """Create a Dataset."""
    data = request.json or request.form or {}
    err = _reject_unknown(data, ['name', 'description', 'contentProviderType', 'targetStorageMode', 'isRefreshable', 'addRowsAPIEnabled'])
    if err:
        return err, 400
    err = _require(data, ['name', 'description'])
    if err:
        return err, 400

from kotodama import Runtime
from kotoba import load_schema
from datomic import DatomicClient
import uuid
import datetime

schema = load_schema("../schema/deliveroo.kotoba")
db = DatomicClient.connect()
app = Runtime("deliveroo-compat")


def now():
    return datetime.datetime.utcnow().isoformat()


def new_id(prefix):
    return f"{prefix}_" + uuid.uuid4().hex[:16]


def _persist(entity, rec):
    """Transact a record into Datomic as namespaced EAVT facts."""
    facts = {}
    for k, v in rec.items():
        facts[f"deliveroo.{entity}/{k}"] = v
    db.transact([facts])
    return rec


def _query(entity, eid=None):
    """Read records of an entity from Datomic (optionally by id)."""
    pattern = {"entity": f"deliveroo.{entity}"}
    if eid is not None:
        pattern["id"] = eid
    return db.query(pattern)


def _require(data, fields):
    missing = [f for f in fields if not data.get(f)]
    if missing:
        return {"error": {"message": "Missing required fields: " + ", ".join(missing)}}
    return None


@app.route("/v1/orders", methods=["POST"])
def create_order(request):
    """Create a Order."""
    data = request.json or request.form or {}
    err = _require(data, ['total', 'status'])
    if err:
        return err, 400
    rec = {"id": new_id("delivero_ord")}
    rec["customerId"] = data.get('customerId')
    rec["merchantId"] = data.get('merchantId')
    rec["total"] = float(data.get('total') or 0)
    rec["status"] = data.get('status')
    rec["createdAt"] = now()
    rec["updatedAt"] = rec["createdAt"]
    _persist("Order", rec)
    return rec, 201

@app.route("/v1/orders", methods=["GET"])
def list_orders(request):
    """List Orders."""
    items = _query("Order")
    return {"object": "list", "data": items, "count": len(items)}, 200

@app.route("/v1/orders/<eid>", methods=["GET"])
def get_order(request, eid):
    """Retrieve a Order by id."""

from kotodama import Runtime
from kotoba import load_schema
from datomic import DatomicClient
import uuid
import datetime

schema = load_schema("../schema/netlify.kotoba")
db = DatomicClient.connect()
app = Runtime("netlify-compat")


def now():
    return datetime.datetime.utcnow().isoformat()


def new_id(prefix):
    return f"{prefix}_" + uuid.uuid4().hex[:16]


def _persist(entity, rec):
    """Transact a record into Datomic as namespaced EAVT facts."""
    facts = {}
    for k, v in rec.items():
        facts[f"netlify.{entity}/{k}"] = v
    db.transact([facts])
    return rec


def _query(entity, eid=None):
    """Read records of an entity from Datomic (optionally by id)."""
    pattern = {"entity": f"netlify.{entity}"}
    if eid is not None:
        pattern["id"] = eid
    return db.query(pattern)


def _require(data, fields):
    missing = [f for f in fields if not data.get(f)]
    if missing:
        return {"error": {"message": "Missing required fields: " + ", ".join(missing)}}
    return None


@app.route("/v1/sites", methods=["POST"])
def create_site(request):
    """Create a Site."""
    data = request.json or request.form or {}
    err = _require(data, ['name', 'url'])
    if err:
        return err, 400
    rec = {"id": new_id("netlify_sit")}
    rec["name"] = data.get('name')
    rec["url"] = data.get('url')
    rec["adminUrl"] = data.get('adminUrl')
    rec["customDomain"] = data.get('customDomain')
    rec["state"] = data.get('state')
    rec["plan"] = data.get('plan')
    rec["accountId"] = data.get('accountId')
    rec["accountSlug"] = data.get('accountSlug')
    rec["gitProvider"] = data.get('gitProvider')
    rec["buildImage"] = data.get('buildImage')
    rec["sslUrl"] = data.get('sslUrl')
    rec["ssl"] = bool(data.get('ssl'))
    rec["forceSsl"] = bool(data.get('forceSsl'))
    rec["userId"] = data.get('userId')
    rec["createdAt"] = now()
    rec["updatedAt"] = rec["createdAt"]
    _persist("Site", rec)
    return rec, 201

@app.route("/v1/sites", methods=["GET"])
def list_sites(request):
    """List Sites."""
    items = _query("Site")
    return {"object": "list", "data": items, "count": len(items)}, 200


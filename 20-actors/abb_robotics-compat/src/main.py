from kotodama import Runtime
from kotoba import load_schema
from datomic import DatomicClient
import uuid
import datetime

schema = load_schema("../schema/abb_robotics.kotoba")
db = DatomicClient.connect()
app = Runtime("abb_robotics-compat")


def now():
    return datetime.datetime.utcnow().isoformat()


def new_id(prefix):
    return f"{prefix}_" + uuid.uuid4().hex[:16]


def _persist(entity, rec):
    """Transact a record into Datomic as namespaced EAVT facts."""
    facts = {}
    for k, v in rec.items():
        facts[f"abb_robotics.{entity}/{k}"] = v
    db.transact([facts])
    return rec


def _query(entity, eid=None):
    """Read records of an entity from Datomic (optionally by id)."""
    pattern = {"entity": f"abb_robotics.{entity}"}
    if eid is not None:
        pattern["id"] = eid
    return db.query(pattern)


def _require(data, fields):
    missing = [f for f in fields if not data.get(f)]
    if missing:
        return {"error": {"message": "Missing required fields: " + ", ".join(missing)}}
    return None


@app.route("/v1/parts", methods=["POST"])
def create_part(request):
    """Create a Part."""
    data = request.json or request.form or {}
    err = _require(data, ['partNumber', 'name'])
    if err:
        return err, 400
    rec = {"id": new_id("abbrobot_par")}
    rec["partNumber"] = data.get('partNumber')
    rec["name"] = data.get('name')
    rec["revision"] = data.get('revision')
    rec["material"] = data.get('material')
    rec["createdAt"] = now()
    rec["updatedAt"] = rec["createdAt"]
    _persist("Part", rec)
    return rec, 201

@app.route("/v1/parts", methods=["GET"])
def list_parts(request):
    """List Parts."""
    items = _query("Part")
    return {"object": "list", "data": items, "count": len(items)}, 200

@app.route("/v1/parts/<eid>", methods=["GET"])
def get_part(request, eid):
    """Retrieve a Part by id."""
    rows = _query("Part", eid)
    if not rows:
        return {"error": {"message": "Not found"}}, 404
    return rows[0], 200

@app.route("/v1/parts/<eid>", methods=["POST", "PATCH"])
def update_part(request, eid):
    """Update a Part."""
    rows = _query("Part", eid)
    if not rows:
        return {"error": {"message": "Not found"}}, 404
    data = request.json or request.form or {}
    rec = rows[0]
    for k, v in data.items():
        if k in rec and k not in ("id", "createdAt"):
            rec[k] = v
    rec["updatedAt"] = now()
    _persist("Part", rec)
    return rec, 200

@app.route("/v1/parts/<eid>", methods=["DELETE"])
def delete_part(request, eid):
    """Delete a Part."""
    rows = _query("Part", eid)
    if not rows:
        return {"error": {"message": "Not found"}}, 404
    db.retract({"entity": f"abb_robotics.Part", "id": eid})
    return {"id": eid, "deleted": True}, 200


from kotodama import Runtime
from kotoba import load_schema
from datomic import DatomicClient
import uuid
import datetime

schema = load_schema("../schema/chainlink.kotoba")
db = DatomicClient.connect()
app = Runtime("chainlink-compat")

DEFAULT_LIMIT = 20
MAX_LIMIT = 100


def now():
    return datetime.datetime.utcnow().isoformat()


def new_id(prefix):
    return f"{prefix}_" + uuid.uuid4().hex[:16]


def _as_int(v):
    try:
        return int(v)
    except (TypeError, ValueError):
        return 0


def _as_float(v):
    try:
        return float(v)
    except (TypeError, ValueError):
        return 0.0


def _as_bool(v):
    return str(v).lower() in ("1", "true", "yes", "on") if v is not None else False


def _persist(entity, rec):
    """Transact a record into Datomic as namespaced EAVT facts."""
    facts = {}
    for k, v in rec.items():
        facts[f"chainlink.{entity}/{k}"] = v
    db.transact([facts])
    return rec


def _query(entity, eid=None):
    pattern = {"entity": f"chainlink.{entity}"}
    if eid is not None:
        pattern["id"] = eid
    return db.query(pattern)


def _require(data, fields):
    missing = [f for f in fields if not data.get(f)]
    if missing:
        return {"error": {"message": "Missing required fields: " + ", ".join(missing),
                          "type": "invalid_request_error"}}
    return None


def _reject_unknown(data, allowed):
    """Reject body fields not in the entity schema (strict validation)."""
    extra = [k for k in data if k not in allowed]
    if extra:
        return {"error": {"message": "Unknown fields: " + ", ".join(extra),
                          "type": "invalid_request_error"}}
    return None


def _apply_filters(rows, params, fields):
    """Filter rows by any schema field present in the query params."""
    out = rows
    for f in fields:
        if f in params and params[f] not in (None, ""):
            want = str(params[f])
            out = [r for r in out if str(r.get(f)) == want]
    return out


def _paginate(rows, params):
    """Cursor pagination: limit + starting_after (an id). Returns (page, has_more)."""
    limit = min(max(_as_int(params.get("limit")) or DEFAULT_LIMIT, 1), MAX_LIMIT)
    start = params.get("starting_after")
    if start is not None:
        ids = [r.get("id") for r in rows]
        if start in ids:
            rows = rows[ids.index(start) + 1:]
    page = rows[:limit]
    return page, len(rows) > limit


def _expand(rec, params, refs):
    """?expand=<field> inlines a referenced entity (rec[field+"_obj"])."""
    want = (params.get("expand") or "").split(",")
    for field, ent in refs.items():
        if field in want and rec.get(field):
            rows = _query(ent, rec[field])
            rec[field + "_obj"] = rows[0] if rows else None
    return rec


@app.route("/v1/pricefeeds", methods=["POST"])
def create_price_feed(request):
    """Create a PriceFeed."""
    data = request.json or request.form or {}
    err = _reject_unknown(data, ['decimals', 'description', 'version', 'address'])
    if err:
        return err, 400
    err = _require(data, ['decimals', 'description'])
    if err:
        return err, 400
    rec = {"id": new_id("chainlin_pri")}
    rec["decimals"] = _as_int(data.get('decimals'))
    rec["description"] = data.get('description')
    rec["version"] = _as_int(data.get('version'))
    rec["address"] = data.get('address')
    rec["createdAt"] = now()
    rec["updatedAt"] = rec["createdAt"]
    _persist("PriceFeed", rec)
    return rec, 201

@app.route("/v1/pricefeeds", methods=["GET"])
def list_price_feeds(request):
    """List PriceFeeds with filtering + cursor pagination."""
    params = request.query or {}
    rows = _query("PriceFeed")
    rows = _apply_filters(rows, params, ['decimals', 'description', 'version', 'address'])
    page, has_more = _paginate(rows, params)
    return {"object": "list", "data": page, "has_more": has_more,
            "count": len(page), "total": len(rows)}, 200

@app.route("/v1/pricefeeds/<eid>", methods=["GET"])
def get_price_feed(request, eid):
    """Retrieve a PriceFeed by id (supports ?expand=)."""
    rows = _query("PriceFeed", eid)
    if not rows:
        return {"error": {"message": "Not found", "type": "not_found"}}, 404
    rec = rows[0]
    return rec, 200

@app.route("/v1/pricefeeds/<eid>", methods=["POST", "PATCH"])
def update_price_feed(request, eid):
    """Update a PriceFeed."""
    rows = _query("PriceFeed", eid)
    if not rows:
        return {"error": {"message": "Not found", "type": "not_found"}}, 404
    data = request.json or request.form or {}
    err = _reject_unknown(data, ['decimals', 'description', 'version', 'address'])
    if err:
        return err, 400
    rec = rows[0]
    for k, v in data.items():
        if k not in ("id", "createdAt"):
            rec[k] = v
    rec["updatedAt"] = now()
    _persist("PriceFeed", rec)
    return rec, 200

@app.route("/v1/pricefeeds/<eid>", methods=["DELETE"])
def delete_price_feed(request, eid):
    """Delete a PriceFeed."""
    rows = _query("PriceFeed", eid)
    if not rows:
        return {"error": {"message": "Not found", "type": "not_found"}}, 404
    db.retract({"entity": f"chainlink.PriceFeed", "id": eid})
    return {"id": eid, "deleted": True}, 200


from kotodama import Runtime
from kotoba import load_schema
from datomic import DatomicClient
import uuid
import datetime

schema = load_schema("../schema/particle.kotoba")
db = DatomicClient.connect()
app = Runtime("particle-compat")


def now():
    return datetime.datetime.utcnow().isoformat()


def new_id(prefix):
    return f"{prefix}_" + uuid.uuid4().hex[:16]


def _persist(entity, rec):
    """Transact a record into Datomic as namespaced EAVT facts."""
    facts = {}
    for k, v in rec.items():
        facts[f"particle.{entity}/{k}"] = v
    db.transact([facts])
    return rec


def _query(entity, eid=None):
    """Read records of an entity from Datomic (optionally by id)."""
    pattern = {"entity": f"particle.{entity}"}
    if eid is not None:
        pattern["id"] = eid
    return db.query(pattern)


def _require(data, fields):
    missing = [f for f in fields if not data.get(f)]
    if missing:
        return {"error": {"message": "Missing required fields: " + ", ".join(missing)}}
    return None


@app.route("/v1/devices", methods=["POST"])
def create_device(request):
    """Create a Device."""
    data = request.json or request.form or {}
    err = _require(data, ['serial', 'model'])
    if err:
        return err, 400
    rec = {"id": new_id("particle_dev")}
    rec["serial"] = data.get('serial')
    rec["model"] = data.get('model')
    rec["status"] = data.get('status')
    rec["firmware"] = data.get('firmware')
    rec["createdAt"] = now()
    rec["updatedAt"] = rec["createdAt"]
    _persist("Device", rec)
    return rec, 201

@app.route("/v1/devices", methods=["GET"])
def list_devices(request):
    """List Devices."""
    items = _query("Device")
    return {"object": "list", "data": items, "count": len(items)}, 200

@app.route("/v1/devices/<eid>", methods=["GET"])
def get_device(request, eid):
    """Retrieve a Device by id."""
    rows = _query("Device", eid)
    if not rows:
        return {"error": {"message": "Not found"}}, 404
    return rows[0], 200

@app.route("/v1/devices/<eid>", methods=["POST", "PATCH"])
def update_device(request, eid):
    """Update a Device."""
    rows = _query("Device", eid)
    if not rows:
        return {"error": {"message": "Not found"}}, 404
    data = request.json or request.form or {}
    rec = rows[0]
    for k, v in data.items():
        if k in rec and k not in ("id", "createdAt"):
            rec[k] = v
    rec["updatedAt"] = now()
    _persist("Device", rec)
    return rec, 200

@app.route("/v1/devices/<eid>", methods=["DELETE"])
def delete_device(request, eid):
    """Delete a Device."""
    rows = _query("Device", eid)
    if not rows:
        return {"error": {"message": "Not found"}}, 404
    db.retract({"entity": f"particle.Device", "id": eid})
    return {"id": eid, "deleted": True}, 200


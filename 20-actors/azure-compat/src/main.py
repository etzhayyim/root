DEFAULT_LIMIT = 20
MAX_LIMIT = 100


def now():
    return datetime.datetime.utcnow().isoformat()


def new_id(prefix):
    return f"{prefix}_" + uuid.uuid4().hex[:16]


def _as_int(v):
    try:
        return int(v)
    except (TypeError, ValueError):
        return 0


def _as_float(v):
    try:
        return float(v)
    except (TypeError, ValueError):
        return 0.0


def _as_bool(v):
    return str(v).lower() in ("1", "true", "yes", "on") if v is not None else False


def _persist(entity, rec):
    """Transact a record into Datomic as namespaced EAVT facts."""
    facts = {}
    for k, v in rec.items():
        facts[f"azure.{entity}/{k}"] = v
    db.transact([facts])
    return rec


def _query(entity, eid=None):
    pattern = {"entity": f"azure.{entity}"}
    if eid is not None:
        pattern["id"] = eid
    return db.query(pattern)


def _require(data, fields):
    missing = [f for f in fields if not data.get(f)]
    if missing:
        return {"error": {"message": "Missing required fields: " + ", ".join(missing),
                          "type": "invalid_request_error"}}
    return None


def _reject_unknown(data, allowed):
    """Reject body fields not in the entity schema (strict validation)."""
    extra = [k for k in data if k not in allowed]
    if extra:
        return {"error": {"message": "Unknown fields: " + ", ".join(extra),
                          "type": "invalid_request_error"}}
    return None


def _apply_filters(rows, params, fields):
    """Filter rows by any schema field present in the query params."""
    out = rows
    for f in fields:
        if f in params and params[f] not in (None, ""):
            want = str(params[f])
            out = [r for r in out if str(r.get(f)) == want]
    return out


def _paginate(rows, params):
    """Cursor pagination: limit + starting_after (an id). Returns (page, has_more)."""
    limit = min(max(_as_int(params.get("limit")) or DEFAULT_LIMIT, 1), MAX_LIMIT)
    start = params.get("starting_after")
    if start is not None:
        ids = [r.get("id") for r in rows]
        if start in ids:
            rows = rows[ids.index(start) + 1:]
    page = rows[:limit]
    return page, len(rows) > limit


def _expand(rec, params, refs):
    """?expand=<field> inlines a referenced entity (rec[field+"_obj"])."""
    want = (params.get("expand") or "").split(",")
    for field, ent in refs.items():
        if field in want and rec.get(field):
            rows = _query(ent, rec[field])
            rec[field + "_obj"] = rows[0] if rows else None
    return rec


@app.route("/v1/virtualmachines", methods=["POST"])
def create_virtual_machine(request):
    """Create a VirtualMachine."""
    data = request.json or request.form or {}
    err = _reject_unknown(data, ['vmId', 'provisioningState', 'priority', 'evictionPolicy', 'licenseType', 'extensionsTimeBudget', 'platformFaultDomain', 'userData', 'timeCreated', 'vmSize'])
    if err:
        return err, 400
    err = _require(data, ['provisioningState', 'priority'])
    if err:
        return err, 400
    if data.get('priority') and data['priority'] not in ['Regular', 'Low', 'Spot']:
        return {"error": {"message": "invalid priority; allowed: " + ", ".join(['Regular', 'Low', 'Spot']), "type": "invalid_request_error"}}, 400
    if data.get('evictionPolicy') and data['evictionPolicy'] not in ['Deallocate', 'Delete']:
        return {"error": {"message": "invalid evictionPolicy; allowed: " + ", ".join(['Deallocate', 'Delete']), "type": "invalid_request_error"}}, 400
    rec = {"id": new_id("azure_vir")}
    rec["vmId"] = data.get('vmId')
    rec["provisioningState"] = data.get('provisioningState')
    rec["priority"] = data.get('priority')
    rec["evictionPolicy"] = data.get('evictionPolicy')
    rec["licenseType"] = data.get('licenseType')
    rec["extensionsTimeBudget"] = data.get('extensionsTimeBudget')
    rec["platformFaultDomain"] = _as_int(data.get('platformFaultDomain'))
    rec["userData"] = data.get('userData')
    rec["timeCreated"] = data.get('timeCreated')
    rec["vmSize"] = data.get('vmSize')
    rec["createdAt"] = now()
    rec["updatedAt"] = rec["createdAt"]
    _persist("VirtualMachine", rec)
    return rec, 201


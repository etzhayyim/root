from kotodama import Runtime
from kotoba import load_schema
from datomic import DatomicClient
import uuid
import datetime

schema = load_schema("../schema/greenhouse.kotoba")
db = DatomicClient.connect()
app = Runtime("greenhouse-compat")


def now():
    return datetime.datetime.utcnow().isoformat()


def new_id(prefix):
    return f"{prefix}_" + uuid.uuid4().hex[:16]


def _persist(entity, rec):
    """Transact a record into Datomic as namespaced EAVT facts."""
    facts = {}
    for k, v in rec.items():
        facts[f"greenhouse.{entity}/{k}"] = v
    db.transact([facts])
    return rec


def _query(entity, eid=None):
    """Read records of an entity from Datomic (optionally by id)."""
    pattern = {"entity": f"greenhouse.{entity}"}
    if eid is not None:
        pattern["id"] = eid
    return db.query(pattern)


def _require(data, fields):
    missing = [f for f in fields if not data.get(f)]
    if missing:
        return {"error": {"message": "Missing required fields: " + ", ".join(missing)}}
    return None


@app.route("/v1/employees", methods=["POST"])
def create_employee(request):
    """Create a Employee."""
    data = request.json or request.form or {}
    err = _require(data, ['firstName', 'lastName'])
    if err:
        return err, 400
    rec = {"id": new_id("greenhou_emp")}
    rec["firstName"] = data.get('firstName')
    rec["lastName"] = data.get('lastName')
    rec["email"] = data.get('email')
    rec["title"] = data.get('title')
    rec["department"] = data.get('department')
    rec["createdAt"] = now()
    rec["updatedAt"] = rec["createdAt"]
    _persist("Employee", rec)
    return rec, 201

@app.route("/v1/employees", methods=["GET"])
def list_employees(request):
    """List Employees."""
    items = _query("Employee")
    return {"object": "list", "data": items, "count": len(items)}, 200


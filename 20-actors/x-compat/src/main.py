from kotodama import Runtime
from kotoba import load_schema
from datomic import DatomicClient
import uuid
import datetime

schema = load_schema("../schema/x.kotoba")
db = DatomicClient.connect()
app = Runtime("x-compat")


def now():
    return datetime.datetime.utcnow().isoformat()


def new_id(prefix):
    return f"{prefix}_" + uuid.uuid4().hex[:16]


def _persist(entity, rec):
    """Transact a record into Datomic as namespaced EAVT facts."""
    facts = {}
    for k, v in rec.items():
        facts[f"x.{entity}/{k}"] = v
    db.transact([facts])
    return rec


def _query(entity, eid=None):
    """Read records of an entity from Datomic (optionally by id)."""
    pattern = {"entity": f"x.{entity}"}
    if eid is not None:
        pattern["id"] = eid
    return db.query(pattern)


def _require(data, fields):
    missing = [f for f in fields if not data.get(f)]
    if missing:
        return {"error": {"message": "Missing required fields: " + ", ".join(missing)}}
    return None


@app.route("/v1/tweets", methods=["POST"])
def create_tweet(request):
    """Create a Tweet."""
    data = request.json or request.form or {}
    err = _require(data, ['text', 'lang'])
    if err:
        return err, 400
    rec = {"id": new_id("x_twe")}
    rec["text"] = data.get('text')
    rec["lang"] = data.get('lang')
    rec["source"] = data.get('source')
    rec["paidPartnership"] = bool(data.get('paidPartnership'))
    rec["possiblySensitive"] = bool(data.get('possiblySensitive'))
    rec["replySettings"] = data.get('replySettings')
    rec["conversationId"] = data.get('conversationId')
    rec["authorId"] = data.get('authorId')
    rec["createdAt"] = now()
    rec["updatedAt"] = rec["createdAt"]
    _persist("Tweet", rec)
    return rec, 201

@app.route("/v1/tweets", methods=["GET"])
def list_tweets(request):
    """List Tweets."""
    items = _query("Tweet")
    return {"object": "list", "data": items, "count": len(items)}, 200


DEFAULT_LIMIT = 20
MAX_LIMIT = 100


def now():
    return datetime.datetime.utcnow().isoformat()


def new_id(prefix):
    return f"{prefix}_" + uuid.uuid4().hex[:16]


def _as_int(v):
    try:
        return int(v)
    except (TypeError, ValueError):
        return 0


def _as_float(v):
    try:
        return float(v)
    except (TypeError, ValueError):
        return 0.0


def _as_bool(v):
    return str(v).lower() in ("1", "true", "yes", "on") if v is not None else False


def _persist(entity, rec):
    """Transact a record into Datomic as namespaced EAVT facts."""
    facts = {}
    for k, v in rec.items():
        facts[f"brightcove.{entity}/{k}"] = v
    db.transact([facts])
    return rec


def _query(entity, eid=None):
    pattern = {"entity": f"brightcove.{entity}"}
    if eid is not None:
        pattern["id"] = eid
    return db.query(pattern)


def _require(data, fields):
    missing = [f for f in fields if not data.get(f)]
    if missing:
        return {"error": {"message": "Missing required fields: " + ", ".join(missing),
                          "type": "invalid_request_error"}}
    return None


def _reject_unknown(data, allowed):
    """Reject body fields not in the entity schema (strict validation)."""
    extra = [k for k in data if k not in allowed]
    if extra:
        return {"error": {"message": "Unknown fields: " + ", ".join(extra),
                          "type": "invalid_request_error"}}
    return None


def _apply_filters(rows, params, fields):
    """Filter rows by any schema field present in the query params."""
    out = rows
    for f in fields:
        if f in params and params[f] not in (None, ""):
            want = str(params[f])
            out = [r for r in out if str(r.get(f)) == want]
    return out


def _paginate(rows, params):
    """Cursor pagination: limit + starting_after (an id). Returns (page, has_more)."""
    limit = min(max(_as_int(params.get("limit")) or DEFAULT_LIMIT, 1), MAX_LIMIT)
    start = params.get("starting_after")
    if start is not None:
        ids = [r.get("id") for r in rows]
        if start in ids:
            rows = rows[ids.index(start) + 1:]
    page = rows[:limit]
    return page, len(rows) > limit


def _expand(rec, params, refs):
    """?expand=<field> inlines a referenced entity (rec[field+"_obj"])."""
    want = (params.get("expand") or "").split(",")
    for field, ent in refs.items():
        if field in want and rec.get(field):
            rows = _query(ent, rec[field])
            rec[field + "_obj"] = rows[0] if rows else None
    return rec


@app.route("/v1/videos", methods=["POST"])
def create_video(request):
    """Create a Video."""
    data = request.json or request.form or {}
    err = _reject_unknown(data, ['name', 'description', 'state', 'economics', 'deliveryType', 'duration', 'complete', 'createdAt', 'drmDisabled', 'hasDigitalMaster', 'folderId'])
    if err:
        return err, 400
    err = _require(data, ['name', 'description'])
    if err:
        return err, 400
    if data.get('state') and data['state'] not in ['ACTIVE', 'INACTIVE', 'PENDING', 'DELETED']:
        return {"error": {"message": "invalid state; allowed: " + ", ".join(['ACTIVE', 'INACTIVE', 'PENDING', 'DELETED']), "type": "invalid_request_error"}}, 400
    if data.get('economics') and data['economics'] not in ['AD_SUPPORTED', 'FREE']:
        return {"error": {"message": "invalid economics; allowed: " + ", ".join(['AD_SUPPORTED', 'FREE']), "type": "invalid_request_error"}}, 400
    if data.get('deliveryType') and data['deliveryType'] not in ['remote', 'dynamic_origin', 'live_origin', 'unknown']:
        return {"error": {"message": "invalid deliveryType; allowed: " + ", ".join(['remote', 'dynamic_origin', 'live_origin', 'unknown']), "type": "invalid_request_error"}}, 400
    rec = {"id": new_id("brightco_vid")}
    rec["name"] = data.get('name')
    rec["description"] = data.get('description')
    rec["state"] = data.get('state')
    rec["economics"] = data.get('economics')
    rec["deliveryType"] = data.get('deliveryType')
    rec["duration"] = _as_int(data.get('duration'))
    rec["complete"] = _as_bool(data.get('complete'))
    rec["createdAt"] = data.get('createdAt')
    rec["drmDisabled"] = _as_bool(data.get('drmDisabled'))
    rec["hasDigitalMaster"] = _as_bool(data.get('hasDigitalMaster'))
    rec["folderId"] = data.get('folderId')
    rec["createdAt"] = now()
    rec["updatedAt"] = rec["createdAt"]
    _persist("Video", rec)
    return rec, 201


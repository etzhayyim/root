from kotodama import Runtime
from kotoba import load_schema
from datomic import DatomicClient
import uuid
import datetime

schema = load_schema("../schema/fdic.kotoba")
db = DatomicClient.connect()
app = Runtime("fdic-compat")

DEFAULT_LIMIT = 20
MAX_LIMIT = 100


def now():
    return datetime.datetime.utcnow().isoformat()


def new_id(prefix):
    return f"{prefix}_" + uuid.uuid4().hex[:16]


def _as_int(v):
    try:
        return int(v)
    except (TypeError, ValueError):
        return 0


def _as_float(v):
    try:
        return float(v)
    except (TypeError, ValueError):
        return 0.0


def _as_bool(v):
    return str(v).lower() in ("1", "true", "yes", "on") if v is not None else False


def _persist(entity, rec):
    """Transact a record into Datomic as namespaced EAVT facts."""
    facts = {}
    for k, v in rec.items():
        facts[f"fdic.{entity}/{k}"] = v
    db.transact([facts])
    return rec


def _query(entity, eid=None):
    pattern = {"entity": f"fdic.{entity}"}
    if eid is not None:
        pattern["id"] = eid
    return db.query(pattern)


def _require(data, fields):
    missing = [f for f in fields if not data.get(f)]
    if missing:
        return {"error": {"message": "Missing required fields: " + ", ".join(missing),
                          "type": "invalid_request_error"}}
    return None


def _reject_unknown(data, allowed):
    """Reject body fields not in the entity schema (strict validation)."""
    extra = [k for k in data if k not in allowed]
    if extra:
        return {"error": {"message": "Unknown fields: " + ", ".join(extra),
                          "type": "invalid_request_error"}}
    return None


def _apply_filters(rows, params, fields):
    """Filter rows by any schema field present in the query params."""
    out = rows
    for f in fields:
        if f in params and params[f] not in (None, ""):
            want = str(params[f])
            out = [r for r in out if str(r.get(f)) == want]
    return out


def _paginate(rows, params):
    """Cursor pagination: limit + starting_after (an id). Returns (page, has_more)."""
    limit = min(max(_as_int(params.get("limit")) or DEFAULT_LIMIT, 1), MAX_LIMIT)
    start = params.get("starting_after")
    if start is not None:
        ids = [r.get("id") for r in rows]
        if start in ids:
            rows = rows[ids.index(start) + 1:]
    page = rows[:limit]
    return page, len(rows) > limit


def _expand(rec, params, refs):
    """?expand=<field> inlines a referenced entity (rec[field+"_obj"])."""
    want = (params.get("expand") or "").split(",")
    for field, ent in refs.items():
        if field in want and rec.get(field):
            rows = _query(ent, rec[field])
            rec[field + "_obj"] = rows[0] if rows else None
    return rec


@app.route("/v1/institutions", methods=["POST"])
def create_institution(request):
    """Create a Institution."""
    data = request.json or request.form or {}
    err = _reject_unknown(data, ['name', 'cert', 'city', 'stname', 'zip', 'bkclass', 'active', 'charter', 'insdate', 'effdate', 'webaddr'])
    if err:
        return err, 400
    err = _require(data, ['name', 'cert'])
    if err:
        return err, 400
    rec = {"id": new_id("fdic_ins")}
    rec["name"] = data.get('name')
    rec["cert"] = _as_int(data.get('cert'))
    rec["city"] = data.get('city')
    rec["stname"] = data.get('stname')
    rec["zip"] = data.get('zip')
    rec["bkclass"] = data.get('bkclass')
    rec["active"] = _as_bool(data.get('active'))
    rec["charter"] = data.get('charter')
    rec["insdate"] = data.get('insdate')
    rec["effdate"] = data.get('effdate')
    rec["webaddr"] = data.get('webaddr')
    rec["createdAt"] = now()
    rec["updatedAt"] = rec["createdAt"]
    _persist("Institution", rec)
    return rec, 201

@app.route("/v1/institutions", methods=["GET"])
def list_institutions(request):
    """List Institutions with filtering + cursor pagination."""
    params = request.query or {}
    rows = _query("Institution")
    rows = _apply_filters(rows, params, ['name', 'cert', 'city', 'stname', 'zip', 'bkclass', 'active', 'charter', 'insdate', 'effdate', 'webaddr'])
    page, has_more = _paginate(rows, params)
    return {"object": "list", "data": page, "has_more": has_more,
            "count": len(page), "total": len(rows)}, 200

@app.route("/v1/institutions/<eid>", methods=["GET"])
def get_institution(request, eid):
    """Retrieve a Institution by id (supports ?expand=)."""
    rows = _query("Institution", eid)
    if not rows:
        return {"error": {"message": "Not found", "type": "not_found"}}, 404
    rec = rows[0]
    return rec, 200

@app.route("/v1/institutions/<eid>", methods=["POST", "PATCH"])
def update_institution(request, eid):
    """Update a Institution."""
    rows = _query("Institution", eid)
    if not rows:
        return {"error": {"message": "Not found", "type": "not_found"}}, 404
    data = request.json or request.form or {}
    err = _reject_unknown(data, ['name', 'cert', 'city', 'stname', 'zip', 'bkclass', 'active', 'charter', 'insdate', 'effdate', 'webaddr'])
    if err:
        return err, 400
    rec = rows[0]
    for k, v in data.items():
        if k not in ("id", "createdAt"):
            rec[k] = v
    rec["updatedAt"] = now()
    _persist("Institution", rec)
    return rec, 200

@app.route("/v1/institutions/<eid>", methods=["DELETE"])
def delete_institution(request, eid):
    """Delete a Institution."""
    rows = _query("Institution", eid)
    if not rows:
        return {"error": {"message": "Not found", "type": "not_found"}}, 404
    db.retract({"entity": f"fdic.Institution", "id": eid})
    return {"id": eid, "deleted": True}, 200


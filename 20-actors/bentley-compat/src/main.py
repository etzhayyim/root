from kotodama import Runtime
from kotoba import load_schema
from datomic import DatomicClient
import uuid
import datetime

schema = load_schema("../schema/bentley.kotoba")
db = DatomicClient.connect()
app = Runtime("bentley-compat")


def now():
    return datetime.datetime.utcnow().isoformat()


def new_id(prefix):
    return f"{prefix}_" + uuid.uuid4().hex[:16]


def _persist(entity, rec):
    """Transact a record into Datomic as namespaced EAVT facts."""
    facts = {}
    for k, v in rec.items():
        facts[f"bentley.{entity}/{k}"] = v
    db.transact([facts])
    return rec


def _query(entity, eid=None):
    """Read records of an entity from Datomic (optionally by id)."""
    pattern = {"entity": f"bentley.{entity}"}
    if eid is not None:
        pattern["id"] = eid
    return db.query(pattern)


def _require(data, fields):
    missing = [f for f in fields if not data.get(f)]
    if missing:
        return {"error": {"message": "Missing required fields: " + ", ".join(missing)}}
    return None


@app.route("/v1/imodels", methods=["POST"])
def create_i_model(request):
    """Create a iModel."""
    data = request.json or request.form or {}
    err = _require(data, ['name', 'description'])
    if err:
        return err, 400
    rec = {"id": new_id("bentley_imo")}
    rec["name"] = data.get('name')
    rec["description"] = data.get('description')
    rec["iTwinId"] = data.get('iTwinId')
    rec["state"] = data.get('state')
    rec["createdDateTime"] = data.get('createdDateTime')
    rec["dataCenterLocation"] = data.get('dataCenterLocation')
    rec["initialized"] = bool(data.get('initialized'))
    rec["displayName"] = data.get('displayName')
    rec["createdAt"] = now()
    rec["updatedAt"] = rec["createdAt"]
    _persist("iModel", rec)
    return rec, 201


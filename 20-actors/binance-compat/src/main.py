from kotodama import Runtime
from kotoba import load_schema
from datomic import DatomicClient
import uuid
import datetime

schema = load_schema("../schema/binance.kotoba")
db = DatomicClient.connect()
app = Runtime("binance-compat")

DEFAULT_LIMIT = 20
MAX_LIMIT = 100


def now():
    return datetime.datetime.utcnow().isoformat()


def new_id(prefix):
    return f"{prefix}_" + uuid.uuid4().hex[:16]


def _as_int(v):
    try:
        return int(v)
    except (TypeError, ValueError):
        return 0


def _as_float(v):
    try:
        return float(v)
    except (TypeError, ValueError):
        return 0.0


def _as_bool(v):
    return str(v).lower() in ("1", "true", "yes", "on") if v is not None else False


def _persist(entity, rec):
    """Transact a record into Datomic as namespaced EAVT facts."""
    facts = {}
    for k, v in rec.items():
        facts[f"binance.{entity}/{k}"] = v
    db.transact([facts])
    return rec


def _query(entity, eid=None):
    pattern = {"entity": f"binance.{entity}"}
    if eid is not None:
        pattern["id"] = eid
    return db.query(pattern)


def _require(data, fields):
    missing = [f for f in fields if not data.get(f)]
    if missing:
        return {"error": {"message": "Missing required fields: " + ", ".join(missing),
                          "type": "invalid_request_error"}}
    return None


def _reject_unknown(data, allowed):
    """Reject body fields not in the entity schema (strict validation)."""
    extra = [k for k in data if k not in allowed]
    if extra:
        return {"error": {"message": "Unknown fields: " + ", ".join(extra),
                          "type": "invalid_request_error"}}
    return None


def _apply_filters(rows, params, fields):
    """Filter rows by any schema field present in the query params."""
    out = rows
    for f in fields:
        if f in params and params[f] not in (None, ""):
            want = str(params[f])
            out = [r for r in out if str(r.get(f)) == want]
    return out


def _paginate(rows, params):
    """Cursor pagination: limit + starting_after (an id). Returns (page, has_more)."""
    limit = min(max(_as_int(params.get("limit")) or DEFAULT_LIMIT, 1), MAX_LIMIT)
    start = params.get("starting_after")
    if start is not None:
        ids = [r.get("id") for r in rows]
        if start in ids:
            rows = rows[ids.index(start) + 1:]
    page = rows[:limit]
    return page, len(rows) > limit


def _expand(rec, params, refs):
    """?expand=<field> inlines a referenced entity (rec[field+"_obj"])."""
    want = (params.get("expand") or "").split(",")
    for field, ent in refs.items():
        if field in want and rec.get(field):
            rows = _query(ent, rec[field])
            rec[field + "_obj"] = rows[0] if rows else None
    return rec


@app.route("/v1/orders", methods=["POST"])
def create_order(request):
    """Create a Order."""
    data = request.json or request.form or {}
    err = _reject_unknown(data, ['symbol', 'orderId', 'clientOrderId', 'price', 'origQty', 'executedQty', 'cummulativeQuoteQty', 'status', 'type', 'side', 'timeInForce', 'transactTime'])
    if err:
        return err, 400
    err = _require(data, ['symbol', 'price'])
    if err:
        return err, 400
    if data.get('status') and data['status'] not in ['NEW', 'PENDING_NEW', 'PARTIALLY_FILLED', 'FILLED', 'CANCELED', 'PENDING_CANCEL', 'REJECTED', 'EXPIRED', 'EXPIRED_IN_MATCH']:
        return {"error": {"message": "invalid status; allowed: " + ", ".join(['NEW', 'PENDING_NEW', 'PARTIALLY_FILLED', 'FILLED', 'CANCELED', 'PENDING_CANCEL', 'REJECTED', 'EXPIRED', 'EXPIRED_IN_MATCH']), "type": "invalid_request_error"}}, 400
    if data.get('type') and data['type'] not in ['LIMIT', 'MARKET', 'STOP_LOSS', 'STOP_LOSS_LIMIT', 'TAKE_PROFIT', 'TAKE_PROFIT_LIMIT', 'LIMIT_MAKER']:
        return {"error": {"message": "invalid type; allowed: " + ", ".join(['LIMIT', 'MARKET', 'STOP_LOSS', 'STOP_LOSS_LIMIT', 'TAKE_PROFIT', 'TAKE_PROFIT_LIMIT', 'LIMIT_MAKER']), "type": "invalid_request_error"}}, 400
    if data.get('side') and data['side'] not in ['BUY', 'SELL']:
        return {"error": {"message": "invalid side; allowed: " + ", ".join(['BUY', 'SELL']), "type": "invalid_request_error"}}, 400
    if data.get('timeInForce') and data['timeInForce'] not in ['GTC', 'IOC', 'FOK']:
        return {"error": {"message": "invalid timeInForce; allowed: " + ", ".join(['GTC', 'IOC', 'FOK']), "type": "invalid_request_error"}}, 400
    rec = {"id": new_id("binance_ord")}
    rec["symbol"] = data.get('symbol')
    rec["orderId"] = _as_int(data.get('orderId'))
    rec["clientOrderId"] = data.get('clientOrderId')
    rec["price"] = data.get('price')
    rec["origQty"] = data.get('origQty')
    rec["executedQty"] = data.get('executedQty')
    rec["cummulativeQuoteQty"] = data.get('cummulativeQuoteQty')
    rec["status"] = data.get('status')
    rec["type"] = data.get('type')
    rec["side"] = data.get('side')
    rec["timeInForce"] = data.get('timeInForce')
    rec["transactTime"] = _as_int(data.get('transactTime'))
    rec["createdAt"] = now()
    rec["updatedAt"] = rec["createdAt"]
    _persist("Order", rec)
    return rec, 201


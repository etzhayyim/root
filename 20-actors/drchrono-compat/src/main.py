from kotodama import Runtime
from kotoba import load_schema
from datomic import DatomicClient
import uuid
import datetime

schema = load_schema("../schema/drchrono.kotoba")
db = DatomicClient.connect()
app = Runtime("drchrono-compat")


def now():
    return datetime.datetime.utcnow().isoformat()


def new_id(prefix):
    return f"{prefix}_" + uuid.uuid4().hex[:16]


def _persist(entity, rec):
    """Transact a record into Datomic as namespaced EAVT facts."""
    facts = {}
    for k, v in rec.items():
        facts[f"drchrono.{entity}/{k}"] = v
    db.transact([facts])
    return rec


def _query(entity, eid=None):
    """Read records of an entity from Datomic (optionally by id)."""
    pattern = {"entity": f"drchrono.{entity}"}
    if eid is not None:
        pattern["id"] = eid
    return db.query(pattern)


def _require(data, fields):
    missing = [f for f in fields if not data.get(f)]
    if missing:
        return {"error": {"message": "Missing required fields: " + ", ".join(missing)}}
    return None


@app.route("/v1/patients", methods=["POST"])
def create_patient(request):
    """Create a Patient."""
    data = request.json or request.form or {}
    err = _require(data, ['dateOfBirth', 'email'])
    if err:
        return err, 400
    rec = {"id": new_id("drchrono_pat")}
    rec["chartId"] = data.get('chartId')
    rec["dateOfBirth"] = data.get('dateOfBirth')
    rec["email"] = data.get('email')
    rec["cellPhone"] = data.get('cellPhone')
    rec["address"] = data.get('address')
    rec["city"] = data.get('city')
    rec["copay"] = data.get('copay')
    rec["defaultPharmacy"] = data.get('defaultPharmacy')
    rec["disableSmsMessages"] = bool(data.get('disableSmsMessages'))
    rec["doctor"] = int(data.get('doctor') or 0)
    rec["emergencyContactName"] = data.get('emergencyContactName')
    rec["emergencyContactPhone"] = data.get('emergencyContactPhone')
    rec["employer"] = data.get('employer')
    rec["dateOfFirstAppointment"] = data.get('dateOfFirstAppointment')
    rec["dateOfLastAppointment"] = data.get('dateOfLastAppointment')
    rec["createdAt"] = now()
    rec["updatedAt"] = rec["createdAt"]
    _persist("Patient", rec)
    return rec, 201

@app.route("/v1/patients", methods=["GET"])
def list_patients(request):
    """List Patients."""
    items = _query("Patient")
    return {"object": "list", "data": items, "count": len(items)}, 200


from kotodama import Runtime
from kotoba import load_schema
from datomic import DatomicClient
import uuid
import datetime

schema = load_schema("../schema/veriff.kotoba")
db = DatomicClient.connect()
app = Runtime("veriff-compat")


def now():
    return datetime.datetime.utcnow().isoformat()


def new_id(prefix):
    return f"{prefix}_" + uuid.uuid4().hex[:16]


def _persist(entity, rec):
    """Transact a record into Datomic as namespaced EAVT facts."""
    facts = {}
    for k, v in rec.items():
        facts[f"veriff.{entity}/{k}"] = v
    db.transact([facts])
    return rec


def _query(entity, eid=None):
    """Read records of an entity from Datomic (optionally by id)."""
    pattern = {"entity": f"veriff.{entity}"}
    if eid is not None:
        pattern["id"] = eid
    return db.query(pattern)


def _require(data, fields):
    missing = [f for f in fields if not data.get(f)]
    if missing:
        return {"error": {"message": "Missing required fields: " + ", ".join(missing)}}
    return None


@app.route("/v1/identities", methods=["POST"])
def create_identity(request):
    """Create a Identity."""
    data = request.json or request.form or {}
    err = _require(data, ['jurisdiction', 'verified'])
    if err:
        return err, 400
    rec = {"id": new_id("veriff_ide")}
    rec["externalId"] = data.get('externalId')
    rec["jurisdiction"] = data.get('jurisdiction')
    rec["verified"] = bool(data.get('verified'))
    rec["createdAt"] = now()
    rec["updatedAt"] = rec["createdAt"]
    _persist("Identity", rec)
    return rec, 201

@app.route("/v1/identities", methods=["GET"])
def list_identities(request):
    """List Identities."""
    items = _query("Identity")
    return {"object": "list", "data": items, "count": len(items)}, 200

@app.route("/v1/identities/<eid>", methods=["GET"])
def get_identity(request, eid):
    """Retrieve a Identity by id."""
    rows = _query("Identity", eid)

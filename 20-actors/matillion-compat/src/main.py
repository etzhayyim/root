from kotodama import Runtime
from kotoba import load_schema
from datomic import DatomicClient
import uuid
import datetime

schema = load_schema("../schema/matillion.kotoba")
db = DatomicClient.connect()
app = Runtime("matillion-compat")


def now():
    return datetime.datetime.utcnow().isoformat()


def new_id(prefix):
    return f"{prefix}_" + uuid.uuid4().hex[:16]


def _persist(entity, rec):
    """Transact a record into Datomic as namespaced EAVT facts."""
    facts = {}
    for k, v in rec.items():
        facts[f"matillion.{entity}/{k}"] = v
    db.transact([facts])
    return rec


def _query(entity, eid=None):
    """Read records of an entity from Datomic (optionally by id)."""
    pattern = {"entity": f"matillion.{entity}"}
    if eid is not None:
        pattern["id"] = eid
    return db.query(pattern)


def _require(data, fields):
    missing = [f for f in fields if not data.get(f)]
    if missing:
        return {"error": {"message": "Missing required fields: " + ", ".join(missing)}}
    return None


@app.route("/v1/connectors", methods=["POST"])
def create_connector(request):
    """Create a Connector."""
    data = request.json or request.form or {}
    err = _require(data, ['name', 'source'])
    if err:
        return err, 400
    rec = {"id": new_id("matillio_con")}
    rec["name"] = data.get('name')
    rec["source"] = data.get('source')
    rec["destination"] = data.get('destination')
    rec["status"] = data.get('status')
    rec["createdAt"] = now()
    rec["updatedAt"] = rec["createdAt"]
    _persist("Connector", rec)
    return rec, 201

@app.route("/v1/connectors", methods=["GET"])
def list_connectors(request):
    """List Connectors."""
    items = _query("Connector")
    return {"object": "list", "data": items, "count": len(items)}, 200

@app.route("/v1/connectors/<eid>", methods=["GET"])
def get_connector(request, eid):
    """Retrieve a Connector by id."""
    rows = _query("Connector", eid)
    if not rows:
        return {"error": {"message": "Not found"}}, 404
    return rows[0], 200


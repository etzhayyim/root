from kotodama import Runtime
from kotoba import load_schema
from datomic import DatomicClient
import uuid
import datetime

schema = load_schema("../schema/nasdaq_itch.kotoba")
db = DatomicClient.connect()
app = Runtime("nasdaq_itch-compat")


def now():
    return datetime.datetime.utcnow().isoformat()


def new_id(prefix):
    return f"{prefix}_" + uuid.uuid4().hex[:16]


def _persist(entity, rec):
    """Transact a record into Datomic as namespaced EAVT facts."""
    facts = {}
    for k, v in rec.items():
        facts[f"nasdaq_itch.{entity}/{k}"] = v
    db.transact([facts])
    return rec


def _query(entity, eid=None):
    """Read records of an entity from Datomic (optionally by id)."""
    pattern = {"entity": f"nasdaq_itch.{entity}"}
    if eid is not None:
        pattern["id"] = eid
    return db.query(pattern)


def _require(data, fields):
    missing = [f for f in fields if not data.get(f)]
    if missing:
        return {"error": {"message": "Missing required fields: " + ", ".join(missing)}}
    return None


@app.route("/v1/instruments", methods=["POST"])
def create_instrument(request):
    """Create a Instrument."""
    data = request.json or request.form or {}
    err = _require(data, ['symbol', 'assetClass'])
    if err:
        return err, 400
    rec = {"id": new_id("nasdaqit_ins")}
    rec["symbol"] = data.get('symbol')
    rec["assetClass"] = data.get('assetClass')
    rec["exchange"] = data.get('exchange')
    rec["currency"] = data.get('currency')
    rec["createdAt"] = now()
    rec["updatedAt"] = rec["createdAt"]
    _persist("Instrument", rec)
    return rec, 201

@app.route("/v1/instruments", methods=["GET"])
def list_instruments(request):
    """List Instruments."""
    items = _query("Instrument")
    return {"object": "list", "data": items, "count": len(items)}, 200


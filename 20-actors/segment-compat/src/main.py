from kotodama import Runtime
from kotoba import load_schema
from datomic import DatomicClient
import uuid
import datetime

schema = load_schema("../schema/segment.kotoba")
db = DatomicClient.connect()
app = Runtime("segment-compat")


def now():
    return datetime.datetime.utcnow().isoformat()


def new_id(prefix):
    return f"{prefix}_" + uuid.uuid4().hex[:16]


def _persist(entity, rec):
    """Transact a record into Datomic as namespaced EAVT facts."""
    facts = {}
    for k, v in rec.items():
        facts[f"segment.{entity}/{k}"] = v
    db.transact([facts])
    return rec


def _query(entity, eid=None):
    """Read records of an entity from Datomic (optionally by id)."""
    pattern = {"entity": f"segment.{entity}"}
    if eid is not None:
        pattern["id"] = eid
    return db.query(pattern)


def _require(data, fields):
    missing = [f for f in fields if not data.get(f)]
    if missing:
        return {"error": {"message": "Missing required fields: " + ", ".join(missing)}}
    return None


@app.route("/v1/campaigns", methods=["POST"])
def create_campaign(request):
    """Create a Campaign."""
    data = request.json or request.form or {}
    err = _require(data, ['name', 'channel'])
    if err:
        return err, 400
    rec = {"id": new_id("segment_cam")}
    rec["name"] = data.get('name')
    rec["channel"] = data.get('channel')
    rec["status"] = data.get('status')
    rec["budget"] = float(data.get('budget') or 0)
    rec["createdAt"] = now()
    rec["updatedAt"] = rec["createdAt"]
    _persist("Campaign", rec)
    return rec, 201

@app.route("/v1/campaigns", methods=["GET"])
def list_campaigns(request):
    """List Campaigns."""
    items = _query("Campaign")
    return {"object": "list", "data": items, "count": len(items)}, 200

@app.route("/v1/campaigns/<eid>", methods=["GET"])
def get_campaign(request, eid):
    """Retrieve a Campaign by id."""
    rows = _query("Campaign", eid)

from kotodama import Runtime
from kotoba import load_schema
from datomic import DatomicClient
import uuid
import datetime

schema = load_schema("../schema/miro.kotoba")
db = DatomicClient.connect()
app = Runtime("miro-compat")


def now():
    return datetime.datetime.utcnow().isoformat()


def new_id(prefix):
    return f"{prefix}_" + uuid.uuid4().hex[:16]


def _persist(entity, rec):
    """Transact a record into Datomic as namespaced EAVT facts."""
    facts = {}
    for k, v in rec.items():
        facts[f"miro.{entity}/{k}"] = v
    db.transact([facts])
    return rec


def _query(entity, eid=None):
    """Read records of an entity from Datomic (optionally by id)."""
    pattern = {"entity": f"miro.{entity}"}
    if eid is not None:
        pattern["id"] = eid
    return db.query(pattern)


def _require(data, fields):
    missing = [f for f in fields if not data.get(f)]
    if missing:
        return {"error": {"message": "Missing required fields: " + ", ".join(missing)}}
    return None


@app.route("/v1/boards", methods=["POST"])
def create_board(request):
    """Create a Board."""
    data = request.json or request.form or {}
    err = _require(data, ['name', 'description'])
    if err:
        return err, 400
    rec = {"id": new_id("miro_boa")}
    rec["name"] = data.get('name')
    rec["description"] = data.get('description')
    rec["type"] = data.get('type')
    rec["viewLink"] = data.get('viewLink')
    rec["createdAt"] = now()
    rec["updatedAt"] = rec["createdAt"]
    _persist("Board", rec)
    return rec, 201

@app.route("/v1/boards", methods=["GET"])
def list_boards(request):
    """List Boards."""
    items = _query("Board")
    return {"object": "list", "data": items, "count": len(items)}, 200

@app.route("/v1/boards/<eid>", methods=["GET"])
def get_board(request, eid):
    """Retrieve a Board by id."""
    rows = _query("Board", eid)
    if not rows:
        return {"error": {"message": "Not found"}}, 404
    return rows[0], 200

@app.route("/v1/boards/<eid>", methods=["POST", "PATCH"])
def update_board(request, eid):
    """Update a Board."""
    rows = _query("Board", eid)
    if not rows:
        return {"error": {"message": "Not found"}}, 404
    data = request.json or request.form or {}
    rec = rows[0]
    for k, v in data.items():
        if k in rec and k not in ("id", "createdAt"):
            rec[k] = v
    rec["updatedAt"] = now()
    _persist("Board", rec)
    return rec, 200

@app.route("/v1/boards/<eid>", methods=["DELETE"])
def delete_board(request, eid):
    """Delete a Board."""
    rows = _query("Board", eid)
    if not rows:
        return {"error": {"message": "Not found"}}, 404
    db.retract({"entity": f"miro.Board", "id": eid})
    return {"id": eid, "deleted": True}, 200


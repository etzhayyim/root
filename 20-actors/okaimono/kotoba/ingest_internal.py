#!/usr/bin/env python3
"""okaimono 御買物 — Ring 1 internal-catalog ingester (ADR-2606012100 §R1).

Producing actors own their goods catalog: each declares a `products.edn` in its
actor dir (shared :product/* vocabulary). This ingester scans the integrated maker
actors, validates each entry (ring=internal, maker-actor set, source=internal-actor),
and merges them into okaimono's internal catalog at `kotoba/internal-catalog.edn`
(the generated Ring 1 view; the per-actor products.edn files remain the SSoT).

This is read-only over the maker actors + a local write of the merged view; no
network, no LLM (G5), no on-chain action (G7/G11). Run before deploy.sh ingest.

Usage:
    python3 ingest_internal.py [--actors-dir ../..] [--out kotoba/internal-catalog.edn] [--check]
"""
from __future__ import annotations

import argparse
import os
import re
import sys

# Maker actors integrated into Ring 1 (mirrors manifest.edn :actor/integrates).
MAKER_ACTORS = ["makura", "mitsuho", "yakushi", "tsutae", "futawa", "hikari"]

HERE = os.path.dirname(os.path.abspath(__file__))
ACTORS_DIR = os.path.abspath(os.path.join(HERE, "..", ".."))  # 20-actors/


def _read(path: str) -> str:
    with open(path, encoding="utf-8") as f:
        return f.read()


def _split_top_maps(edn: str):
    """Yield each top-level {...} map literal in the outer [ ... ] vector (comment-stripped)."""
    # strip ;; line comments (no string-literal ';' in products.edn by construction)
    edn = "\n".join(line.split(";", 1)[0] for line in edn.splitlines())
    start = edn.find("[")
    depth, buf, out = 0, [], []
    for c in edn[start + 1 :] if start >= 0 else "":
        if c == "{":
            depth += 1
            buf.append(c)
        elif c == "}":
            depth -= 1
            buf.append(c)
            if depth == 0:
                out.append("".join(buf).strip())
                buf = []
        elif depth > 0:
            buf.append(c)
    return out


def _kv(entity: str, key: str):
    m = re.search(rf"{re.escape(key)}\s+(\"[^\"]*\"|:[^\s\]}}]+|[-\d.]+)", entity)
    if not m:
        return None
    v = m.group(1)
    if v.startswith('"'):
        return v[1:-1]
    if v.startswith(":"):
        return v
    return v


def collect():
    products, problems = [], []
    for actor in MAKER_ACTORS:
        path = os.path.join(ACTORS_DIR, actor, "products.edn")
        if not os.path.exists(path):
            problems.append(f"{actor}: no products.edn (R1 catalog not yet declared)")
            continue
        for ent in _split_top_maps(_read(path)):
            pid = _kv(ent, ":product/id")
            ring = _kv(ent, ":product/ring")
            maker = _kv(ent, ":product/maker-actor")
            source = _kv(ent, ":product/source")
            # validation gates (G2/G6/G8/G13)
            if ring != ":internal":
                problems.append(f"{actor}/{pid}: ring must be :internal for Ring 1 (got {ring})")
                continue
            if maker != f'"{actor}"' and maker != actor:
                problems.append(f"{actor}/{pid}: maker-actor mismatch ({maker} != {actor})")
                continue
            if source != ":internal-actor":
                problems.append(f"{actor}/{pid}: source must be :internal-actor (got {source})")
                continue
            if _kv(ent, ":product/lifecycle-route") is None:
                problems.append(f"{actor}/{pid}: missing :product/lifecycle-route (G13)")
                continue
            products.append((actor, pid, ent))
    return products, problems


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=os.path.join(HERE, "internal-catalog.edn"))
    ap.add_argument("--check", action="store_true", help="validate only; non-zero exit on problems")
    args = ap.parse_args()

    products, problems = collect()
    for p in problems:
        print(f"  !! {p}")
    print(f"  collected {len(products)} internal products from {len(MAKER_ACTORS)} maker actors")
    for actor, pid, _ in products:
        print(f"     {actor:9s} {pid}")

    if args.check:
        return 1 if problems else 0

    body = "\n".join(ent for _, _, ent in products)
    header = (
        ";; okaimono 御買物 — Ring 1 internal catalog (GENERATED by ingest_internal.py)\n"
        ";; ADR-2606012100 §R1. SSoT = each maker actor's products.edn; do not edit by hand.\n"
    )
    with open(args.out, "w", encoding="utf-8") as f:
        f.write(header + "[" + body + "]\n")
    print(f"  wrote {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())

from kotodama import Runtime
from kotoba import load_schema
from datomic import DatomicClient
import uuid
import datetime

schema = load_schema("../schema/webflow.kotoba")
db = DatomicClient.connect()
app = Runtime("webflow-compat")


def now():
    return datetime.datetime.utcnow().isoformat()


def new_id(prefix):
    return f"{prefix}_" + uuid.uuid4().hex[:16]


def _persist(entity, rec):
    """Transact a record into Datomic as namespaced EAVT facts."""
    facts = {}
    for k, v in rec.items():
        facts[f"webflow.{entity}/{k}"] = v
    db.transact([facts])
    return rec


def _query(entity, eid=None):
    """Read records of an entity from Datomic (optionally by id)."""
    pattern = {"entity": f"webflow.{entity}"}
    if eid is not None:
        pattern["id"] = eid
    return db.query(pattern)


def _require(data, fields):
    missing = [f for f in fields if not data.get(f)]
    if missing:
        return {"error": {"message": "Missing required fields: " + ", ".join(missing)}}
    return None


@app.route("/v1/sites", methods=["POST"])
def create_site(request):
    """Create a Site."""
    data = request.json or request.form or {}
    err = _require(data, ['displayName', 'shortName'])
    if err:
        return err, 400
    rec = {"id": new_id("webflow_sit")}
    rec["workspaceId"] = data.get('workspaceId')
    rec["displayName"] = data.get('displayName')
    rec["shortName"] = data.get('shortName')
    rec["previewUrl"] = data.get('previewUrl')
    rec["timeZone"] = data.get('timeZone')
    rec["parentFolderId"] = data.get('parentFolderId')
    rec["lastPublished"] = data.get('lastPublished')
    rec["dataCollectionEnabled"] = bool(data.get('dataCollectionEnabled'))
    rec["dataCollectionType"] = data.get('dataCollectionType')
    rec["createdAt"] = now()
    rec["updatedAt"] = rec["createdAt"]
    _persist("Site", rec)
    return rec, 201

@app.route("/v1/sites", methods=["GET"])
def list_sites(request):
    """List Sites."""
    items = _query("Site")
    return {"object": "list", "data": items, "count": len(items)}, 200


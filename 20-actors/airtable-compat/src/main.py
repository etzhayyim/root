from kotodama import Runtime
from kotoba import load_schema
from datomic import DatomicClient
import uuid
import datetime

schema = load_schema("../schema/airtable.kotoba")
db = DatomicClient.connect()
app = Runtime("airtable-compat")


def now():
    return datetime.datetime.utcnow().isoformat()


def new_id(prefix):
    return f"{prefix}_" + uuid.uuid4().hex[:16]


def _persist(entity, rec):
    """Transact a record into Datomic as namespaced EAVT facts."""
    facts = {}
    for k, v in rec.items():
        facts[f"airtable.{entity}/{k}"] = v
    db.transact([facts])
    return rec


def _query(entity, eid=None):
    """Read records of an entity from Datomic (optionally by id)."""
    pattern = {"entity": f"airtable.{entity}"}
    if eid is not None:
        pattern["id"] = eid
    return db.query(pattern)


def _require(data, fields):
    missing = [f for f in fields if not data.get(f)]
    if missing:
        return {"error": {"message": "Missing required fields: " + ", ".join(missing)}}
    return None


@app.route("/v1/workspaces", methods=["POST"])
def create_workspace(request):
    """Create a Workspace."""
    data = request.json or request.form or {}
    err = _require(data, ['name', 'plan'])
    if err:
        return err, 400
    rec = {"id": new_id("airtable_wor")}
    rec["name"] = data.get('name')
    rec["ownerId"] = data.get('ownerId')
    rec["plan"] = data.get('plan')
    rec["createdAt"] = now()
    rec["updatedAt"] = rec["createdAt"]
    _persist("Workspace", rec)
    return rec, 201

@app.route("/v1/workspaces", methods=["GET"])
def list_workspaces(request):
    """List Workspaces."""
    items = _query("Workspace")
    return {"object": "list", "data": items, "count": len(items)}, 200

@app.route("/v1/workspaces/<eid>", methods=["GET"])
def get_workspace(request, eid):
    """Retrieve a Workspace by id."""

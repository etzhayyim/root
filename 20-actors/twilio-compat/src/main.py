from kotodama import Runtime
from kotoba import load_schema
from datomic import DatomicClient
import uuid
import datetime

schema = load_schema("../schema/twilio.kotoba")
db = DatomicClient.connect()
app = Runtime("twilio-compat")


def now():
    return datetime.datetime.utcnow().isoformat()


def new_id(prefix):
    return f"{prefix}_" + uuid.uuid4().hex[:16]


def _persist(entity, rec):
    """Transact a record into Datomic as namespaced EAVT facts."""
    facts = {}
    for k, v in rec.items():
        facts[f"twilio.{entity}/{k}"] = v
    db.transact([facts])
    return rec


def _query(entity, eid=None):
    """Read records of an entity from Datomic (optionally by id)."""
    pattern = {"entity": f"twilio.{entity}"}
    if eid is not None:
        pattern["id"] = eid
    return db.query(pattern)


def _require(data, fields):
    missing = [f for f in fields if not data.get(f)]
    if missing:
        return {"error": {"message": "Missing required fields: " + ", ".join(missing)}}
    return None


@app.route("/v1/messages", methods=["POST"])
def create_message(request):
    """Create a Message."""
    data = request.json or request.form or {}
    err = _require(data, ['fromNumber', 'toNumber'])
    if err:
        return err, 400
    rec = {"id": new_id("twilio_mes")}
    rec["fromNumber"] = data.get('fromNumber')
    rec["toNumber"] = data.get('toNumber')
    rec["body"] = data.get('body')
    rec["status"] = data.get('status')
    rec["direction"] = data.get('direction')
    rec["createdAt"] = now()
    rec["updatedAt"] = rec["createdAt"]
    _persist("Message", rec)
    return rec, 201

@app.route("/v1/messages", methods=["GET"])
def list_messages(request):
    """List Messages."""
    items = _query("Message")
    return {"object": "list", "data": items, "count": len(items)}, 200

@app.route("/v1/messages/<eid>", methods=["GET"])
def get_message(request, eid):
    """Retrieve a Message by id."""
    rows = _query("Message", eid)

from kotodama import Runtime
from kotoba import load_schema
from datomic import DatomicClient
import uuid
import datetime

schema = load_schema("../schema/shopee.kotoba")
db = DatomicClient.connect()
app = Runtime("shopee-compat")


def now():
    return datetime.datetime.utcnow().isoformat()


def new_id(prefix):
    return f"{prefix}_" + uuid.uuid4().hex[:16]


def _persist(entity, rec):
    """Transact a record into Datomic as namespaced EAVT facts."""
    facts = {}
    for k, v in rec.items():
        facts[f"shopee.{entity}/{k}"] = v
    db.transact([facts])
    return rec


def _query(entity, eid=None):
    """Read records of an entity from Datomic (optionally by id)."""
    pattern = {"entity": f"shopee.{entity}"}
    if eid is not None:
        pattern["id"] = eid
    return db.query(pattern)


def _require(data, fields):
    missing = [f for f in fields if not data.get(f)]
    if missing:
        return {"error": {"message": "Missing required fields: " + ", ".join(missing)}}
    return None


@app.route("/v1/users", methods=["POST"])
def create_user(request):
    """Create a User."""
    data = request.json or request.form or {}
    err = _require(data, ['phone', 'displayName'])
    if err:
        return err, 400
    rec = {"id": new_id("shopee_use")}
    rec["phone"] = data.get('phone')
    rec["displayName"] = data.get('displayName')
    rec["kycStatus"] = data.get('kycStatus')
    rec["walletId"] = data.get('walletId')
    rec["createdAt"] = now()
    rec["updatedAt"] = rec["createdAt"]
    _persist("User", rec)
    return rec, 201

@app.route("/v1/users", methods=["GET"])
def list_users(request):
    """List Users."""
    items = _query("User")
    return {"object": "list", "data": items, "count": len(items)}, 200

@app.route("/v1/users/<eid>", methods=["GET"])
def get_user(request, eid):
    """Retrieve a User by id."""
    rows = _query("User", eid)
    if not rows:
        return {"error": {"message": "Not found"}}, 404

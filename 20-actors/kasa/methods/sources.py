#!/usr/bin/env python3
"""kasa 嵩 — source catalogue (the G1 admissibility layer).

The single source of truth for WHICH public sources kasa may ingest. Mirrors kanjō's
concept_map.py role: a small, auditable registry that encodes the constitutional G1 rule
(Charter Rider §2(e) anti-gatekeeping + §2(c) vendor query-tracking) —

  ADMISSIBLE  : public, redistributable HEADLINE figures + open datasets
                (WSTS/SIA press releases · TrendForce/JPR press releases · TOP500 public list ·
                 Epoch AI CC-BY · Our World in Data CC-BY · company filings)
  PROHIBITED  : the PAID, copyrighted FULL reports + subscription terminals
                (Gartner / IDC-report / Omdia / Bloomberg / S&P / Statista-Pro full products).
                The headline figure a vendor puts in a FREE press release is admissible; the
                paywalled report / terminal compilation is not. Read the press release, never
                the terminal.

Run directly to emit the `:compute.source`-shaped catalogue + a prohibited-list note:

    python3 methods/sources.py            # → out/source-catalogue.kotoba.edn

Used by ingest.py (admissible(publisher, access) gate). ADR-2606072000.
"""
from __future__ import annotations
import os

# publisher -> (default-license, default-access, note). These are the ADMISSIBLE public sources.
ADMISSIBLE = {
    "wsts":             (":press-release", ":press-release", "WSTS Blue Book headline actuals (free press releases)."),
    "sia":              (":press-release", ":press-release", "SIA Global Semiconductor Sales (free monthly/annual press)."),
    "trendforce":       (":press-release", ":press-release", "TrendForce DRAM/NAND revenue (free press releases)."),
    "jpr":              (":press-release", ":press-release", "Jon Peddie Research GPU/AIB market (free press summaries)."),
    "idc":              (":press-release", ":press-release", "IDC HEADLINE shipment figures in free press releases ONLY — never the paid IDC report/tracker subscription."),
    "top500":           (":public-domain", ":public-list", "TOP500 public semiannual list (aggregate Rmax)."),
    "epoch-ai":         (":cc-by", ":open-dataset", "Epoch AI Notable AI Models database (CC-BY, redistributable)."),
    "our-world-in-data": (":cc-by", ":open-dataset", "Our World in Data (CC-BY, redistributable)."),
    "company-filing":   (":public-domain", ":company-filing", "Issuer primary disclosure (10-K / 有報) — public; cross-links kanjō."),
}

# PROHIBITED publishers / access channels (G1 — Charter Rider §2(e)+§2(c)). Paid full reports +
# subscription terminals whose distinctive value is a gatekept compilation and whose vendor would
# learn the member's query posture. (Their FREE press-release headline figures remain admissible
# under the matching ADMISSIBLE entry — e.g. `idc` press-release — but the PAID PRODUCT is not.)
PROHIBITED = {
    "gartner-report", "idc-report", "idc-tracker", "omdia", "bloomberg-terminal",
    "sp-capital-iq", "refinitiv", "factset", "statista-pro", "yole-report",
}
PROHIBITED_ACCESS = {":paid-terminal", ":subscription", ":paywalled-report"}


def admissible(publisher: str, access: str | None = None) -> bool:
    """G1 gate: True iff this (publisher, access) is a public/redistributable source kasa may ingest."""
    pub = publisher.lstrip(":")
    if pub in PROHIBITED:
        return False
    if access is not None and access.lstrip(":") and (":" + access.lstrip(":")) in PROHIBITED_ACCESS:
        return False
    return pub in ADMISSIBLE


def _s(x: str) -> str:
    return '"' + x.replace("\\", "\\\\").replace('"', '\\"') + '"'


def _edn():
    lines = [
        ";; kasa 嵩 — source catalogue (G1 admissibility layer)",
        ";; GENERATED by methods/sources.py — ADR-2606072000. Encodes Charter Rider §2(e)+§2(c).",
        ";; ADMISSIBLE = public headline / open dataset. PROHIBITED list below is the paid-terminal bar.",
        "[",
    ]
    for pub, (lic, access, note) in ADMISSIBLE.items():
        lines.append(
            " {:compute.source/publisher :" + pub
            + f" :compute.source/license {lic}"
            + f" :compute.source/access {access}"
            + f" :compute.source/note {_s(note)}"
            + " :compute.source/admissible true}"
        )
    for pub in sorted(PROHIBITED):
        lines.append(
            " {:compute.source/publisher :" + pub
            + " :compute.source/admissible false"
            + " :compute.source/note " + _s("PROHIBITED paid report / terminal (G1, Charter Rider §2(e)+§2(c)) — read the free press release, never the paid product.") + "}"
        )
    lines.append("]")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    here = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    outdir = os.path.join(here, "out")
    os.makedirs(outdir, exist_ok=True)
    path = os.path.join(outdir, "source-catalogue.kotoba.edn")
    with open(path, "w") as f:
        f.write(_edn())
    print(f"wrote {len(ADMISSIBLE)} admissible + {len(PROHIBITED)} prohibited publishers → {path}")
    # self-check
    assert admissible("sia")
    assert admissible(":epoch-ai", ":open-dataset")
    assert not admissible("bloomberg-terminal")
    assert not admissible("idc", ":paid-terminal")  # IDC press-release ok, IDC terminal not
    assert admissible("idc", ":press-release")
    print("sources self-check ok")

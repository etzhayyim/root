"""analyze.py — 潮目 (shionome) end-to-end membrane (dry-run). ADR-2606072200.

Load seed → weave + validate → aggregate concentration → dry-run social posts → write
`methods/out/intel-report.md` + `methods/out/capital-flow-graph.kotoba.edn` +
`methods/out/kanae-render.json`. Aggregate-first (G3), edge-primary (G4), non-advisory /
no-trade (G2, トレードはしない), mirror-not-signal (G5). No live posting (G8).

Stdlib only.
"""

from __future__ import annotations

import pathlib

from _edn import load_edn
from export import render_json, to_kanae_flows
from social import draft_netflow_post, draft_regime_post, draft_rotation_post
from weave import concentration, weave

HERE = pathlib.Path(__file__).resolve().parent
SEED = HERE.parent / "data" / "seed-capital-flow-graph.kotoba.edn"
OUT = HERE / "out"


def run(seed_path: pathlib.Path = SEED, out_dir: pathlib.Path = OUT) -> dict:
    g = weave(load_edn(seed_path))
    c = concentration(g)
    allsrcs = sorted({s for f in g["flows"] for s in f.get(":flow/sources", [])})
    posts = []
    if allsrcs:
        if c["net_flow_by_bucket"]:
            posts.append(draft_netflow_post(c["net_flow_by_bucket"], allsrcs))
        if c["rotation_pairs"]:
            posts.append(draft_rotation_post(c["rotation_pairs"], allsrcs))
        posts.append(draft_regime_post(c["regime"], allsrcs))

    out_dir.mkdir(parents=True, exist_ok=True)
    _write_report(out_dir / "intel-report.md", c, posts)
    _write_graph(out_dir / "capital-flow-graph.kotoba.edn", g)
    (out_dir / "kanae-render.json").write_text(render_json(c), encoding="utf-8")
    kanae_flows = to_kanae_flows(g)
    return {"concentration": c, "posts": posts, "kanae_flows": kanae_flows}


def _write_report(path: pathlib.Path, c: dict, posts: list[dict]) -> None:
    L = ["# 潮目 (shionome) — cross-asset capital-flow intel (dry-run)\n",
         "_Observational mirror of where money moved — NOT financial advice, NOT a trade signal. "
         "トレードはしない. :representative seed._\n",
         f"\nbuckets={c['bucket_count']} flows={c['flow_count']} snapshots={c['snapshot_count']}\n",
         f"\n_referential integrity: {c['integrity']['dangling_count']} dangling reference(s)._\n",
         f"\n## Cross-asset regime: **{c['regime']['regime']}** "
         f"(risk_net={c['regime']['risk_net']:+.1f} / safe_net={c['regime']['safe_net']:+.1f}) "
         f"— descriptive, not advice\n",
         "\n## Net flow by bucket (どこに資金が向かっているか)\n"]
    for r in c["net_flow_by_bucket"]:
        arrow = "▲ in" if r["net"] > 0 else ("▼ out" if r["net"] < 0 else "= flat")
        L.append(f"- **{r['label']}** — net {r['net']:+.2f} {arrow} (in {r['inflow']:.2f} / out {r['outflow']:.2f})")
    L.append("\n## Rotation pairs (どこからどこへ)\n")
    for r in c["rotation_pairs"]:
        L.append(f"- {r['from_label']} → {r['to_label']}: {r['magnitude']:.2f}")
    if not c["rotation_pairs"]:
        L.append("- (none in seed)")
    L.append("\n## By asset class\n")
    for r in c["by_asset_class"]:
        L.append(f"- **{r['asset_class']}** — net {r['net']:+.2f} ({r['buckets']} bucket(s))")
    L.append("\n## By region\n")
    for r in c["by_region"]:
        L.append(f"- **{r['region']}** — net {r['net']:+.2f} ({r['buckets']} bucket(s))")
    ic = c["inflow_concentration"]
    L.append(f"\n## Inflow concentration — HHI={ic['hhi']} over total {ic['total']:.2f}\n")
    for bucket, share in ic["shares"]:
        L.append(f"- `{bucket}`: {share*100:.1f}%")
    L.append("\n## Correlation clusters\n")
    for cl in c["correlation_clusters"]:
        L.append(f"- {{{', '.join(cl['members'])}}} (size {cl['size']})")
    if not c["correlation_clusters"]:
        L.append("- (none in seed)")
    L.append("\n## Dry-run social posts\n")
    for p in posts:
        L.append(f"> {p[':post/body']}\n>\n> _status={p[':post/status']} isMirror={p[':post/is-mirror']} "
                 f"noTrade={p[':post/no-trade-notice']} serverHeldKey={p[':post/server-held-key']} "
                 f"sources={len(p[':post/sources'])}_\n")
    path.write_text("\n".join(L) + "\n", encoding="utf-8")


def _write_graph(path: pathlib.Path, g: dict) -> None:
    """Emit the validated capital-flow graph as derived edn (the kotoba-ingest body shape)."""
    lines = [";; GENERATED by shionome analyze.py — validated capital-flow graph (do not hand-edit)",
             "{:graph {:name \"shionome-capital-flow-v1\" :visibility :public}", " :flows ["]
    for f in g["flows"]:
        lines.append(f'  {{:flow/id "{f[":flow/id"]}" :flow/source "{f[":flow/source"]}" '
                     f':flow/target "{f[":flow/target"]}" :flow/kind {f[":flow/kind"]} '
                     f':flow/magnitude {f[":flow/magnitude"]} :flow/no-trade-notice true}}')
    lines.append(" ]}")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    res = run()
    c = res["concentration"]
    print(f"# shionome analyze — buckets={c['bucket_count']} flows={c['flow_count']} "
          f"snapshots={c['snapshot_count']}")
    print(f"  regime={c['regime']['regime']}, inflow HHI={c['inflow_concentration']['hhi']}, "
          f"rotation pairs={len(c['rotation_pairs'])}, posts={len(res['posts'])}")
    print(f"  kanae flows exported: {len(res['kanae_flows']['flows'])} "
          f"({res['kanae_flows']['skipped_count']} observation-only skipped)")
    print(f"  → {OUT/'intel-report.md'}  +  {OUT/'kanae-render.json'}")

from kotodama import Runtime
from kotoba import load_schema
from datomic import DatomicClient
import uuid
import datetime

schema = load_schema("../schema/gtfs.kotoba")
db = DatomicClient.connect()
app = Runtime("gtfs-compat")


def now():
    return datetime.datetime.utcnow().isoformat()


def new_id(prefix):
    return f"{prefix}_" + uuid.uuid4().hex[:16]


def _persist(entity, rec):
    """Transact a record into Datomic as namespaced EAVT facts."""
    facts = {}
    for k, v in rec.items():
        facts[f"gtfs.{entity}/{k}"] = v
    db.transact([facts])
    return rec


def _query(entity, eid=None):
    """Read records of an entity from Datomic (optionally by id)."""
    pattern = {"entity": f"gtfs.{entity}"}
    if eid is not None:
        pattern["id"] = eid
    return db.query(pattern)


def _require(data, fields):
    missing = [f for f in fields if not data.get(f)]
    if missing:
        return {"error": {"message": "Missing required fields: " + ", ".join(missing)}}
    return None


@app.route("/v1/stops", methods=["POST"])
def create_stop(request):
    """Create a Stop."""
    data = request.json or request.form or {}
    err = _require(data, ['code', 'name'])
    if err:
        return err, 400
    rec = {"id": new_id("gtfs_sto")}
    rec["code"] = data.get('code')
    rec["name"] = data.get('name')
    rec["lat"] = float(data.get('lat') or 0)
    rec["lon"] = float(data.get('lon') or 0)
    rec["createdAt"] = now()
    rec["updatedAt"] = rec["createdAt"]
    _persist("Stop", rec)
    return rec, 201

@app.route("/v1/stops", methods=["GET"])
def list_stops(request):
    """List Stops."""
    items = _query("Stop")
    return {"object": "list", "data": items, "count": len(items)}, 200

@app.route("/v1/stops/<eid>", methods=["GET"])
def get_stop(request, eid):
    """Retrieve a Stop by id."""
    rows = _query("Stop", eid)
    if not rows:
        return {"error": {"message": "Not found"}}, 404

from kotodama import Runtime
from kotoba import load_schema
from datomic import DatomicClient
import uuid
import datetime

schema = load_schema("../schema/vimeo.kotoba")
db = DatomicClient.connect()
app = Runtime("vimeo-compat")


def now():
    return datetime.datetime.utcnow().isoformat()


def new_id(prefix):
    return f"{prefix}_" + uuid.uuid4().hex[:16]


def _persist(entity, rec):
    """Transact a record into Datomic as namespaced EAVT facts."""
    facts = {}
    for k, v in rec.items():
        facts[f"vimeo.{entity}/{k}"] = v
    db.transact([facts])
    return rec


def _query(entity, eid=None):
    """Read records of an entity from Datomic (optionally by id)."""
    pattern = {"entity": f"vimeo.{entity}"}
    if eid is not None:
        pattern["id"] = eid
    return db.query(pattern)


def _require(data, fields):
    missing = [f for f in fields if not data.get(f)]
    if missing:
        return {"error": {"message": "Missing required fields: " + ", ".join(missing)}}
    return None


@app.route("/v1/videos", methods=["POST"])
def create_video(request):
    """Create a Video."""
    data = request.json or request.form or {}
    err = _require(data, ['name', 'description'])
    if err:
        return err, 400
    rec = {"id": new_id("vimeo_vid")}
    rec["name"] = data.get('name')
    rec["description"] = data.get('description')
    rec["duration"] = float(data.get('duration') or 0)
    rec["width"] = int(data.get('width') or 0)
    rec["height"] = int(data.get('height') or 0)
    rec["language"] = data.get('language')
    rec["license"] = data.get('license')
    rec["status"] = data.get('status')
    rec["link"] = data.get('link')
    rec["releaseTime"] = data.get('releaseTime')
    rec["resourceKey"] = data.get('resourceKey')
    rec["uri"] = data.get('uri')
    rec["createdAt"] = now()
    rec["updatedAt"] = rec["createdAt"]
    _persist("Video", rec)
    return rec, 201

@app.route("/v1/videos", methods=["GET"])
def list_videos(request):
    """List Videos."""
    items = _query("Video")
    return {"object": "list", "data": items, "count": len(items)}, 200


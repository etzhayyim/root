from kotodama import Runtime
from kotoba import load_schema
from datomic import DatomicClient
import uuid
import datetime

schema = load_schema("../schema/woocommerce.kotoba")
db = DatomicClient.connect()
app = Runtime("woocommerce-compat")


def now():
    return datetime.datetime.utcnow().isoformat()


def new_id(prefix):
    return f"{prefix}_" + uuid.uuid4().hex[:16]


def _persist(entity, rec):
    """Transact a record into Datomic as namespaced EAVT facts."""
    facts = {}
    for k, v in rec.items():
        facts[f"woocommerce.{entity}/{k}"] = v
    db.transact([facts])
    return rec


def _query(entity, eid=None):
    """Read records of an entity from Datomic (optionally by id)."""
    pattern = {"entity": f"woocommerce.{entity}"}
    if eid is not None:
        pattern["id"] = eid
    return db.query(pattern)


def _require(data, fields):
    missing = [f for f in fields if not data.get(f)]
    if missing:
        return {"error": {"message": "Missing required fields: " + ", ".join(missing)}}
    return None


@app.route("/v1/products", methods=["POST"])
def create_product(request):
    """Create a Product."""
    data = request.json or request.form or {}
    err = _require(data, ['name', 'slug'])
    if err:
        return err, 400
    rec = {"id": new_id("woocomme_pro")}
    rec["name"] = data.get('name')
    rec["slug"] = data.get('slug')
    rec["permalink"] = data.get('permalink')
    rec["type"] = data.get('type')
    rec["status"] = data.get('status')
    rec["featured"] = bool(data.get('featured'))
    rec["catalogVisibility"] = data.get('catalogVisibility')
    rec["description"] = data.get('description')
    rec["shortDescription"] = data.get('shortDescription')
    rec["sku"] = data.get('sku')
    rec["price"] = data.get('price')
    rec["regularPrice"] = data.get('regularPrice')
    rec["salePrice"] = data.get('salePrice')
    rec["onSale"] = bool(data.get('onSale'))
    rec["purchasable"] = bool(data.get('purchasable'))
    rec["totalSales"] = int(data.get('totalSales') or 0)
    rec["virtual"] = bool(data.get('virtual'))
    rec["downloadable"] = bool(data.get('downloadable'))
    rec["taxStatus"] = data.get('taxStatus')
    rec["manageStock"] = bool(data.get('manageStock'))
    rec["stockQuantity"] = int(data.get('stockQuantity') or 0)
    rec["stockStatus"] = data.get('stockStatus')
    rec["backorders"] = data.get('backorders')
    rec["weight"] = data.get('weight')
    rec["averageRating"] = data.get('averageRating')
    rec["ratingCount"] = int(data.get('ratingCount') or 0)
    rec["parentId"] = int(data.get('parentId') or 0)
    rec["menuOrder"] = int(data.get('menuOrder') or 0)
    rec["createdAt"] = now()
    rec["updatedAt"] = rec["createdAt"]
    _persist("Product", rec)
    return rec, 201


from kotodama import Runtime
from kotoba import load_schema
from datomic import DatomicClient
import uuid
import datetime

schema = load_schema("../schema/mux.kotoba")
db = DatomicClient.connect()
app = Runtime("mux-compat")


def now():
    return datetime.datetime.utcnow().isoformat()


def new_id(prefix):
    return f"{prefix}_" + uuid.uuid4().hex[:16]


def _persist(entity, rec):
    """Transact a record into Datomic as namespaced EAVT facts."""
    facts = {}
    for k, v in rec.items():
        facts[f"mux.{entity}/{k}"] = v
    db.transact([facts])
    return rec


def _query(entity, eid=None):
    """Read records of an entity from Datomic (optionally by id)."""
    pattern = {"entity": f"mux.{entity}"}
    if eid is not None:
        pattern["id"] = eid
    return db.query(pattern)


def _require(data, fields):
    missing = [f for f in fields if not data.get(f)]
    if missing:
        return {"error": {"message": "Missing required fields: " + ", ".join(missing)}}
    return None


@app.route("/v1/assets", methods=["POST"])
def create_asset(request):
    """Create a Asset."""
    data = request.json or request.form or {}
    err = _require(data, ['status', 'duration'])
    if err:
        return err, 400
    rec = {"id": new_id("mux_ass")}
    rec["status"] = data.get('status')
    rec["duration"] = float(data.get('duration') or 0)
    rec["maxStoredResolution"] = data.get('maxStoredResolution')
    rec["resolutionTier"] = data.get('resolutionTier')
    rec["encodingTier"] = data.get('encodingTier')
    rec["videoQuality"] = data.get('videoQuality')
    rec["aspectRatio"] = data.get('aspectRatio')
    rec["maxStoredFrameRate"] = float(data.get('maxStoredFrameRate') or 0)
    rec["uploadId"] = data.get('uploadId')
    rec["isLive"] = bool(data.get('isLive'))
    rec["liveStreamId"] = data.get('liveStreamId')
    rec["masterAccess"] = data.get('masterAccess')
    rec["mp4Support"] = data.get('mp4Support')
    rec["passthrough"] = data.get('passthrough')
    rec["ingestType"] = data.get('ingestType')
    rec["test"] = bool(data.get('test'))
    rec["createdAt"] = now()
    rec["updatedAt"] = rec["createdAt"]
    _persist("Asset", rec)
    return rec, 201

@app.route("/v1/assets", methods=["GET"])
def list_assets(request):
    """List Assets."""
    items = _query("Asset")
    return {"object": "list", "data": items, "count": len(items)}, 200


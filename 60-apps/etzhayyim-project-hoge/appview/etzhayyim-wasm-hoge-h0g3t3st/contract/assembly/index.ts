/**
 * Hoge WASM Contract — AssemblyScript validation module.
 *
 * Pure numeric functions with no imports (no GC, no allocations).
 * Compiled to basic WASM module and instantiated per-request in CF Workers.
 *
 * Memory layout (single 64KB page):
 *   [0 .. 8191]    input buffer  — host writes UTF-8 bytes here before calling shannonScore
 *   [8192 .. 9215] freq scratch  — 256 × u32 counters used by shannonScore
 */

/** Add two 32-bit integers. */
export function add(a: i32, b: i32): i32 {
  return a + b;
}

/**
 * Fibonacci (recursive).
 * @param n - index, clamped to [0, 20] to avoid stack overflow
 */
export function fib(n: i32): i32 {
  if (n <= 0) return 0;
  if (n === 1) return 1;
  if (n > 20) n = 20; // safety clamp
  return fib(n - 1) + fib(n - 2);
}

/** Sum integers 1..n (inclusive). */
export function sum(n: i32): i32 {
  let s: i32 = 0;
  for (let i: i32 = 1; i <= n; i++) {
    s += i;
  }
  return s;
}

/** Multiply two 32-bit integers. */
export function mul(a: i32, b: i32): i32 {
  return a * b;
}

// ── Pattern A: WIT-shaped manual ABI ────────────────────────────────────────
//
// Implements the WIT contract:
//   shannon-score: func(params: string) -> result<string, string>
//
// ABI bridge (generated by etzhayyim wit-gen as-glue pattern):
//   1. Host encodes params text as UTF-8, writes bytes to memory[inputPtr()..len]
//   2. Host calls shannonScore(len) → f64
//   3. Host wraps result: JSON.stringify({ score, len, pattern:"manual" })
//
// No allocations, no GC — compatible with --runtime stub --noExportRuntime.

/** Returns the fixed input buffer offset (always 0). Host writes input here. */
export function inputPtr(): i32 {
  return 0;
}

/**
 * Compute Shannon entropy (bits) of bytes at memory[0..len].
 *
 * H = -Σ p(x) · log₂(p(x))
 *
 * Uses 8192..9215 as scratch space (256 × u32 frequency counters).
 * Input is clamped to 8192 bytes to stay within the scratch boundary.
 *
 * @param len - number of bytes to read from memory[0]
 * @returns entropy in bits
 */
export function shannonScore(len: i32): f64 {
  if (len <= 0) return 0.0;
  if (len > 8192) len = 8192;

  const SCRATCH: i32 = 8192; // start of 256×4-byte freq table

  // Zero the 256 counters (1024 bytes)
  for (let i: i32 = 0; i < 1024; i++) {
    store<u8>(SCRATCH + i, 0);
  }

  // Count byte frequencies
  for (let i: i32 = 0; i < len; i++) {
    const b: i32 = load<u8>(i);
    const cnt: u32 = load<u32>(SCRATCH + b * 4);
    store<u32>(SCRATCH + b * 4, cnt + 1);
  }

  // H = -Σ p · log₂(p)
  let h: f64 = 0.0;
  const n: f64 = f64(len);
  for (let i: i32 = 0; i < 256; i++) {
    const c: u32 = load<u32>(SCRATCH + i * 4);
    if (c > 0) {
      const p: f64 = f64(c) / n;
      h -= p * (Math.log(p) / Math.LN2);
    }
  }
  return h;
}

use libp2p::{gossipsub, identify, kad, ping, request_response, swarm::NetworkBehaviour};
use crate::bitswap::BitswapCodec;

/// Combined NetworkBehaviour for KOTOBA nodes.
///
/// The `#[derive(NetworkBehaviour)]` macro (libp2p "macros" feature) auto-generates:
///   - `KotobaBehaviourEvent` enum with one variant per field
///   - `poll()` / `handle_pending_inbound_connection()` / etc. delegation
#[derive(NetworkBehaviour)]
pub struct KotobaBehaviour {
    pub gossipsub: gossipsub::Behaviour,
    pub kademlia:  kad::Behaviour<kad::store::MemoryStore>,
    pub identify:  identify::Behaviour,
    pub ping:      ping::Behaviour,
    pub bitswap:   request_response::Behaviour<BitswapCodec>,
}

#[cfg(test)]
mod tests {
    use super::*;
    use libp2p::identity::Keypair;
    use libp2p::PeerId;
    use crate::bitswap::BITSWAP_PROTOCOL;
    use crate::protocol::KOTOBA_SYNC_PROTOCOL;

    /// Build a `KotobaBehaviour` exactly the way `KotobaSwarm::with_keypair` does,
    /// so this test guards the struct's field set + sub-behaviour types against drift.
    fn make_behaviour() -> KotobaBehaviour {
        let keypair = Keypair::generate_ed25519();
        let local_peer_id = PeerId::from_public_key(&keypair.public());

        let gossipsub_config = gossipsub::ConfigBuilder::default()
            .heartbeat_interval(std::time::Duration::from_secs(10))
            .validation_mode(gossipsub::ValidationMode::Strict)
            .build()
            .expect("gossipsub config");
        let gossipsub = gossipsub::Behaviour::new(
            gossipsub::MessageAuthenticity::Signed(keypair.clone()),
            gossipsub_config,
        )
        .expect("gossipsub init");

        let kademlia = kad::Behaviour::new(
            local_peer_id,
            kad::store::MemoryStore::new(local_peer_id),
        );

        let identify = identify::Behaviour::new(identify::Config::new(
            KOTOBA_SYNC_PROTOCOL.to_string(),
            keypair.public(),
        ));

        let ping = ping::Behaviour::default();

        let bitswap = request_response::Behaviour::new(
            vec![(BITSWAP_PROTOCOL, request_response::ProtocolSupport::Full)],
            request_response::Config::default(),
        );

        KotobaBehaviour { gossipsub, kademlia, identify, ping, bitswap }
    }

    #[test]
    fn behaviour_constructs_with_all_five_protocols() {
        let b = make_behaviour();
        // Touch every field so a removed/renamed protocol fails to compile here.
        let _ = &b.gossipsub;
        let _ = &b.kademlia;
        let _ = &b.identify;
        let _ = &b.ping;
        let _ = &b.bitswap;
    }

    /// `swarm.rs` routes inbound events by matching `KotobaBehaviourEvent::{Gossipsub,
    /// Kademlia, Identify, Ping, Bitswap}` — variants generated by the
    /// `#[derive(NetworkBehaviour)]` macro from the struct field names. This exhaustive
    /// match is a compile-time guard: if the derive ever renames, drops, or adds a
    /// variant (e.g. after a libp2p upgrade), this fails to build, surfacing the drift
    /// before the swarm's event dispatch silently stops routing a protocol.
    #[test]
    fn behaviour_event_variants_match_swarm_routing() {
        fn _exhaustive(ev: &KotobaBehaviourEvent) {
            match ev {
                KotobaBehaviourEvent::Gossipsub(_) => {}
                KotobaBehaviourEvent::Kademlia(_) => {}
                KotobaBehaviourEvent::Identify(_) => {}
                KotobaBehaviourEvent::Ping(_) => {}
                KotobaBehaviourEvent::Bitswap(_) => {}
            }
        }
        // Reference the guard so it is type-checked as part of this test.
        let _ = _exhaustive;
    }
}

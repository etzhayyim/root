#!/usr/bin/env node
/**
 * CLI tool to generate Zod validators from AT Protocol Lexicon JSON files.
 *
 * Usage:
 *   node src/cli.ts [lexicon-root] [output-dir]
 *
 * Example:
 *   node src/cli.ts 00-contracts/lexicons/com/etzhayyim 70-tools/lexicon-to-zod/generated
 *
 * Output: One .ts file per actor directory, with all lexicons pre-built into
 * a validator map that can be imported and used by XRPC adapters.
 */

import { readdir, readFile, writeFile, mkdir } from "node:fs/promises";
import { dirname, join } from "node:path";
import type { LexiconDoc } from "./types.js";

const LEX_ROOT = process.argv[2] ?? "00-contracts/lexicons/com/etzhayyim";
const OUT_DIR = process.argv[3] ?? "70-tools/lexicon-to-zod/generated";

async function main() {
  try {
    const entries = await readdir(LEX_ROOT, { withFileTypes: true });
    await mkdir(OUT_DIR, { recursive: true });

    for (const ent of entries) {
      if (!ent.isDirectory()) continue;

      const lexicons = await collectLexicons(join(LEX_ROOT, ent.name));
      if (lexicons.length === 0) continue;

      const tsSource = emitValidatorModule(ent.name, lexicons);
      const outPath = join(OUT_DIR, `${ent.name}.validators.ts`);

      await writeFile(outPath, tsSource);
      console.log(`✓ ${ent.name}: ${lexicons.length} lexicons → ${outPath}`);
    }
  } catch (err) {
    console.error("CLI error:", err);
    process.exit(1);
  }
}

/**
 * Recursively collect all Lexicon JSON files from a directory tree.
 */
async function collectLexicons(dir: string): Promise<LexiconDoc[]> {
  const out: LexiconDoc[] = [];
  const stack = [dir];

  while (stack.length) {
    const cur = stack.pop()!;

    try {
      const entries = await readdir(cur, { withFileTypes: true });

      for (const e of entries) {
        const p = join(cur, e.name);

        if (e.isDirectory()) {
          stack.push(p);
        } else if (e.name.endsWith(".json")) {
          try {
            const content = await readFile(p, "utf8");
            const j = JSON.parse(content) as unknown;

            if (isLexiconDoc(j)) {
              out.push(j);
            }
          } catch {
            // Skip invalid JSON or non-lexicon files
          }
        }
      }
    } catch {
      // Skip unreadable directories
    }
  }

  return out;
}

/**
 * Type guard for LexiconDoc
 */
function isLexiconDoc(v: unknown): v is LexiconDoc {
  return (
    typeof v === "object" &&
    v !== null &&
    (v as Record<string, unknown>).lexicon === 1 &&
    typeof (v as Record<string, unknown>).id === "string" &&
    typeof (v as Record<string, unknown>).defs === "object"
  );
}

/**
 * Emit a TypeScript module that exports a pre-built validator map
 * for all lexicons in a given actor directory.
 */
function emitValidatorModule(actor: string, lexicons: LexiconDoc[]): string {
  const embedded = JSON.stringify(lexicons, null, 2);
  const camelizedActor = camelize(actor);

  return `// Auto-generated by @etzhayyim/lexicon-to-zod. Do not edit.
// Source: ${LEX_ROOT}/${actor}/

import { buildValidatorMap } from "@etzhayyim/lexicon-to-zod";
import type { LexiconDoc } from "@etzhayyim/lexicon-to-zod";

const LEXICONS: LexiconDoc[] = ${embedded};

export const ${camelizedActor}Validators = buildValidatorMap(LEXICONS);
`;
}

/**
 * Convert kebab-case to camelCase for export names.
 * @example "open-banking" → "openBanking"
 */
function camelize(s: string): string {
  return s.replace(/-([a-z])/g, (_, c) => c.toUpperCase());
}

main();

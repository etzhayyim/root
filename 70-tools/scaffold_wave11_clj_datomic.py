def render(tmpl, **kw):
    out = tmpl
    for k, v in kw.items():
        out = out.replace("__" + k + "__", str(v))
    return out


def kebab(name):
    out = []
    for i, ch in enumerate(name):
        if ch.isupper() and i > 0:
            out.append("-")
        out.append(ch.lower())
    return "".join(out)


def _cast_form(t, expr):
    return {"integer": f"(as-long {expr})", "float": f"(as-double {expr})",
            "boolean": f"(as-bool {expr})"}.get(t, expr)


def clj_program_bundle(adir, handle):
    parts = []
    for rel in (f"schema/{handle}.kotoba", f"src/{handle}/actor.cljc", "deps.edn"):
        p = os.path.join(adir, rel)
        body = open(p, "rb").read() if os.path.exists(p) else b""
        parts.append(f"--- {rel} ({len(body)}) ---\n".encode("utf-8"))
        parts.append(body)
        parts.append(b"\n")
    return b"".join(parts)



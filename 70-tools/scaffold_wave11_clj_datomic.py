def gen_clj(handle, id_prefix, blurb, model):
    vt = {"string": ":db.type/string", "integer": ":db.type/long",
          "float": ":db.type/double", "boolean": ":db.type/boolean",
          "datetime": ":db.type/instant"}
    sl = []
    for ent, fields in model.items():
        sl.append(f"   ;; {ent}")
        sl.append(f"   {{:db/ident :{handle}.{ent}/id :db/valueType :db.type/string "
                  ":db/cardinality :db.cardinality/one :db/unique :db.unique/identity}")
        for f, t in fields.items():
            sl.append(f"   {{:db/ident :{handle}.{ent}/{f} :db/valueType {vt[t]} "
                      ":db/cardinality :db.cardinality/one}")
        for f in ("createdAt", "updatedAt"):
            sl.append(f"   {{:db/ident :{handle}.{ent}/{f} :db/valueType :db.type/instant "
                      ":db/cardinality :db.cardinality/one}")
    schema_block = "\n".join(sl).lstrip()
    entities_block = " ".join(f'"{e}"' for e in model)

    blocks = [render(HEADER, HANDLE=handle, BLURB=blurb,
                     SCHEMA=schema_block, ENTITIES=entities_block)]
    routes = []
    for ent, fields in model.items():
        plural = _pluralize(ent).lower()
        prefix = f"{id_prefix}_{ent[:3].lower()}"
        required = "[" + " ".join(f'"{r}"' for r in _required_fields(fields)) + "]"
        assign = "\n".join(
            f"           :{handle}.{ent}/{f} {_cast_form(t, f'(get data :{f})')}"
            for f, t in fields.items())
        updates = "\n".join(
            f"                   (cond-> (contains? data :{f}) "
            f"(conj [:db/add id :{handle}.{ent}/{f} {_cast_form(t, f'(get data :{f})')}]))"
            for f, t in fields.items())
        allowed = "[" + " ".join(f":{handle}.{ent}/{f}" for f in fields) + "]"
        refs = w11._refs(model, fields)
        expand = "".join(
            f"\n         (and want (contains? want :{f}) (get rec :{handle}.{ent}/{f}))"
            f"\n         (assoc :{f}-obj (-pull port (get rec :{handle}.{ent}/{f})))"
            for f in refs)
        blocks.append(render(ENTITY_TMPL, ENT=ent, EKEBAB=kebab(ent),
                             PKEBAB=kebab(_pluralize(ent)), PREFIX=prefix, HANDLE=handle,
                             REQUIRED=required, ASSIGN=assign, UPDATES=updates,
                             ALLOWED=allowed, EXPAND=expand))
        routes.append(f'{{:method "POST" :path "/v1/{plural}" :op :create :entity "{ent}"}}')
        routes.append(f'{{:method "GET" :path "/v1/{plural}" :op :list :entity "{ent}"}}')
        routes.append(f'{{:method "GET" :path "/v1/{plural}/:id" :op :get :entity "{ent}"}}')
        routes.append(f'{{:method "PATCH" :path "/v1/{plural}/:id" :op :update :entity "{ent}"}}')
        routes.append(f'{{:method "DELETE" :path "/v1/{plural}/:id" :op :delete :entity "{ent}"}}')
    handlers = "\n   ".join(
        f'"{_pluralize(ent).lower()}" {{:create create-{kebab(ent)} :list list-{kebab(_pluralize(ent))} '
        f':get get-{kebab(ent)} :update update-{kebab(ent)} :delete delete-{kebab(ent)}}}'
        for ent in model)
    blocks.append(render(TAIL, ROUTES="\n   ".join(routes), HANDLERS=handlers, HANDLE=handle))
    return "".join(blocks)


def _sample(handle, ent, model, overrides=None):
    """A create-input map literal from an entity's required fields (+ overrides)."""
    req = _required_fields(model[ent])
    vals = {r: '"x"' for r in req}
    vals.update(overrides or {})
    return "{" + " ".join(f":{k} {v}" for k, v in vals.items()) + "}"


def _expand_test(handle, model):
    """A relational expand test for the first *Id ref found, else an arity fallback."""
    for child, fields in model.items():
        refs = w11._refs(model, fields)
        if refs:
            field, parent = next(iter(refs.items()))
            return render(
                '(deftest expand-inlines-relation\n'
                '  (testing "?expand inlines the referenced __PARENT__ on a __CHILD__"\n'
                '    (let [port   (a/in-memory-datom)\n'
                '          parent (a/create-__PKEBAB__ port __PSAMPLE__)\n'
                '          child  (a/create-__CKEBAB__ port (assoc __CSAMPLE__ :__FIELD__ (:db/id parent)))\n'
                '          got    (a/get-__CKEBAB__ port (:db/id child) {:expand #{:__FIELD__}})]\n'
                '      (is (= (:db/id parent) (:db/id (:__FIELD__-obj got)))\n'
                '          "expand resolves the relation to the parent entity"))))\n',
                PARENT=parent, CHILD=child, PKEBAB=kebab(parent), CKEBAB=kebab(child),
                FIELD=field, PSAMPLE=_sample(handle, parent, model),
                CSAMPLE=_sample(handle, child, model))
    e0 = next(iter(model))
    return render(
        '(deftest expand-arity-ok\n'
        '  (is (nil? (a/get-__E0KEBAB__ (a/in-memory-datom) "missing" {:expand #{}}))\n'
        '      "get with :expand opts returns nil for an absent id"))\n',
        E0KEBAB=kebab(e0))


def gen_clj_test(handle, model):
    ents = list(model.keys())
    e0 = ents[0]
    fields0 = model[e0]
    req0 = _required_fields(fields0)
    # the update/filter assertions check round-tripped string values → pick a string field
    upd_field = next((f for f, t in fields0.items() if t == "string"), req0[0])
    sample = _sample(handle, e0, model, {upd_field: '"x"'})
    sample2 = _sample(handle, e0, model, {upd_field: '"y"'})
    samples = "{" + "\n   ".join(
        f'"{_pluralize(ent).lower()}" {_sample(handle, ent, model)}' for ent in model) + "}"
    return render(TEST_TMPL, HANDLE=handle, SAMPLES=samples,
                  ENTITIES_VEC="[" + " ".join(f'"{e}"' for e in ents) + "]",
                  ENT0=e0, E0KEBAB=kebab(e0), P0KEBAB=kebab(_pluralize(e0)),
                  COLL0=_pluralize(e0).lower(),
                  SAMPLE=sample, SAMPLE2=sample2,
                  UPDKEY=f':{upd_field} "updated"', UPDVAL='"updated"',
                  UPDATTR=f":{handle}.{e0}/{upd_field}",
                  FILTERATTR=f":{handle}.{e0}/{upd_field}", FILTERVAL='"x"',
                  EXPANDTEST=_expand_test(handle, model))



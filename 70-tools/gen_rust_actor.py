#!/usr/bin/env python3
"""
Per-actor Rust→WASM build for the browser-local (raw single-block CID) tier.

For each requested actor, writes `wasm-rs/src/actor_meta.rs` (the actor's handle
+ entity list, so the module bytes — and thus the raw CID — are actor-specific),
builds the compact `wasm32-unknown-unknown` module, validates it, and computes
its raw CIDv1 (`bafkrei…`, matching the apex Worker's isRawCidV1 / browser-local
tier). Records every built component in
`00-contracts/schemas/cleanroom-built-actors.json` — the manifest of *actually
built* WASM (vs the source-bundle CID stand-in in the registration seed).

Default cohort: the curated-override marquees. `--per-category N` widens it.

Requires the rustup stable toolchain (has wasm32-unknown-unknown std) +
wasm-tools. Usage:
    python3 70-tools/gen_rust_actor.py stripe github openai
    python3 70-tools/gen_rust_actor.py --per-category 1
"""
import os
import re
import sys
import json
import subprocess
import importlib.util

TOOLS_DIR = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(TOOLS_DIR)
CRATE = os.path.join(ROOT, "60-apps", "cleanroom-browser-runtime", "wasm-rs")
META = os.path.join(CRATE, "src", "actor_meta.rs")
TARGET = "/tmp/cractor-target"
HOME = os.path.expanduser("~")
TC = os.path.join(HOME, ".rustup", "toolchains", "stable-aarch64-apple-darwin", "bin")

_spec = importlib.util.spec_from_file_location(
    "deepen_actors", os.path.join(TOOLS_DIR, "deepen_actors.py"))
deepen = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(deepen)
_rspec = importlib.util.spec_from_file_location(
    "register_cleanroom_actors", os.path.join(TOOLS_DIR, "register_cleanroom_actors.py"))
reg = importlib.util.module_from_spec(_rspec)
_rspec.loader.exec_module(reg)


def model_for(platform):
    cats = deepen.parse_platform_categories()
    return (deepen.PLATFORM_OVERRIDES.get(platform)
            or deepen.CATEGORY_MODELS.get(cats.get(platform))
            or deepen.GENERIC_MODEL)


def build_one(platform):
    handle = f"{platform}-compat"
    entities = list(model_for(platform).keys())
    ents = ", ".join(f'"{e}"' for e in entities)
    with open(META, "w") as f:
        f.write("// generated by gen_rust_actor.py — do not edit\n")
        f.write(f'pub const HANDLE: &str = "{handle}";\n')
        f.write(f"pub const ENTITIES: &[&str] = &[{ents}];\n")
    env = dict(os.environ)
    env["RUSTC"] = os.path.join(TC, "rustc")
    env["PATH"] = TC + os.pathsep + env["PATH"]
    env["CARGO_TARGET_DIR"] = TARGET
    r = subprocess.run(
        [os.path.join(TC, "cargo"), "build", "--release",
         "--target", "wasm32-unknown-unknown"],
        cwd=CRATE, env=env, capture_output=True, text=True)
    if r.returncode != 0:
        return {"handle": handle, "error": r.stderr.strip().splitlines()[-1] if r.stderr else "build failed"}
    wasm = os.path.join(TARGET, "wasm32-unknown-unknown", "release", "cleanroom_actor_raw.wasm")
    data = open(wasm, "rb").read()
    v = subprocess.run(["wasm-tools", "validate", wasm], capture_output=True, text=True)
    cid = reg.cid_v1_raw(data)
    return {
        "handle": handle, "platform": platform,
        "bytes": len(data), "wasmCid": cid,
        "rawSingleBlock": bool(reg.RAW_CID_RE.match(cid)),
        "valid": v.returncode == 0,
        "tier": "browser-local",
        "entities": entities,
    }


def main(argv):
    if argv and argv[0] == "--per-category":
        depth = int(argv[1]) if len(argv) > 1 and argv[1].isdigit() else 1
        cats = deepen.parse_platform_categories()
        by = {}
        for p, k in cats.items():
            by.setdefault(k, []).append(p)
        cohort = []
        for k, ps in by.items():
            cohort += sorted(ps)[:depth]
        cohort = sorted(set(cohort) | set(deepen.PLATFORM_OVERRIDES))
    else:
        cohort = argv or sorted(deepen.PLATFORM_OVERRIDES.keys())

    built, errs = [], []
    for p in cohort:
        if not os.path.isdir(os.path.join(ROOT, "20-actors", f"{p}-compat")):
            continue
        res = build_one(p)
        if res.get("error"):
            errs.append(res)
            print(f"  ✘ {p}: {res['error']}")
        else:
            built.append(res)
            print(f"  ✔ {res['handle']:<28} {res['bytes']:>6}B  {res['wasmCid']}")

    out = {
        "schemaVersion": "1.0",
        "kind": "built-wasm-actors",
        "tier": "browser-local (raw single-block CIDv1)",
        "tooling": {"rustc": "stable wasm32-unknown-unknown", "validator": "wasm-tools"},
        "adr": ["260607", "2606014500", "2606014600"],
        "count": len(built),
        "actors": built,
    }
    path = os.path.join(ROOT, "00-contracts", "schemas", "cleanroom-built-actors.json")
    with open(path, "w") as f:
        json.dump(out, f, indent=2, ensure_ascii=False)
        f.write("\n")
    print(f"\nBuilt {len(built)} actors → {os.path.relpath(path, ROOT)} ({len(errs)} errors)")
    # restore default meta so the committed crate builds standalone
    with open(META, "w") as f:
        f.write("// Default actor identity (overwritten per-actor by gen_rust_actor.py at build).\n")
        f.write('pub const HANDLE: &str = "cleanroom-actor-raw";\n')
        f.write('pub const ENTITIES: &[&str] = &["Resource"];\n')
    return 0 if not errs else 1


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))

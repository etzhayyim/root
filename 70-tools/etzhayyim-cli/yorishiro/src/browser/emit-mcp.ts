// browser/emit-mcp.ts — L3 emitter (TS MCP server, playwright Node).
//
// The emitted server exposes one tool per browser-only op. Each tool
// launches a headless Chromium via playwright (Node), replays the
// step sequence, harvests the extract selectors, and returns the result.
//
// Heavy dependency: playwright requires a browser binary
// (`pnpm exec playwright install chromium` after install).

import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

import type { BrowserKamiManifest, BrowserOp, BrowserStep } from "./types.js";

export interface EmitArgs {
  repoRoot: string;
  name: string;
  purposes: readonly string[];
  manifest: BrowserKamiManifest;
}

export function emitBrowserMcp(args: EmitArgs): { packageDir: string; files: string[] } {
  const dir = join(args.repoRoot, "40-engine/kotoba/crates/kotoba-kotodama/mcp", `yorishiro-${args.name}-mcp`);
  mkdirSync(join(dir, "src"), { recursive: true });
  const files: string[] = [];
  const w = (rel: string, body: string) => {
    const p = join(dir, rel);
    writeFileSync(p, body, "utf-8");
    files.push(p);
  };

  w("package.json", renderPackage(args));
  w("tsconfig.json", renderTsconfig());
  w("README.md", renderReadme(args));
  w("src/index.ts", renderIndex(args));
  w("src/cli.ts", renderCli(args));
  w("src/server.ts", renderServer(args));
  w("src/tools.ts", renderTools(args));
  w("src/handle.ts", renderHandle(args));

  return { packageDir: dir, files };
}


function renderTsconfig(): string {
  return JSON.stringify(
    {
      compilerOptions: {
        target: "ES2022",
        module: "ESNext",
        moduleResolution: "Bundler",
        lib: ["ES2022"],
        strict: true,
        esModuleInterop: true,
        skipLibCheck: true,
        resolveJsonModule: true,
        isolatedModules: true,
        noEmit: true,
        types: ["node"],
      },
      include: ["src/**/*.ts"],
    },
    null,
    2,
  ) + "\n";
}

function renderReadme(args: EmitArgs): string {
  const ops = args.manifest.ops
    .map((o) => `| \`${snake(o.name)}\` | ${(o.summary || o.description || o.name).slice(0, 100)} |`)
    .join("\n");
  return `# @etzhayyim/yorishiro-${args.name}-mcp

MCP server exposing the **${args.name}** yorishiro (browser-only; base URL: \`${args.manifest.kami.base_url}\`) as tools.

Per ADR-2605211900. Generated by \`@etzhayyim/yorishiro\` in browser-only mode.

## Tools

| Tool | Purpose |
|---|---|
${ops}

## Runtime requirement

\`\`\`bash
pnpm install
pnpm exec playwright install chromium
\`\`\`

A Chromium browser is launched per request (no persistent context).
`;
}

function renderIndex(args: EmitArgs): string {
  const P = pascal(args.name);
  return `export { createYorishiro${P}McpServer } from "./server.js";
export type { McpServerConfig } from "./server.js";
export { tools, findTool } from "./tools.js";
export type { ToolDefinition, ${P}Handle } from "./tools.js";
export { createDefault${P}Handle } from "./handle.js";
`;
}

function renderCli(args: EmitArgs): string {
  const P = pascal(args.name);
  return `#!/usr/bin/env node
import { StdioServerTransport } from "@modelcontextprotocol/sdk/server/stdio.js";
import { createDefault${P}Handle } from "./handle.js";
import { createYorishiro${P}McpServer } from "./server.js";

async function main(): Promise<void> {
  const handle = createDefault${P}Handle({});
  const server = createYorishiro${P}McpServer({ handle });
  const transport = new StdioServerTransport();
  console.error("[yorishiro-${args.name}-mcp] stdio; base=${args.manifest.kami.base_url}");
  await server.connect(transport);
}

main().catch((err) => {
  console.error("[yorishiro-${args.name}-mcp] fatal:", err);
  process.exit(1);
});
`;
}

function renderServer(args: EmitArgs): string {
  const P = pascal(args.name);
  return `import { Server } from "@modelcontextprotocol/sdk/server/index.js";
import {
  CallToolRequestSchema,
  ListToolsRequestSchema,
} from "@modelcontextprotocol/sdk/types.js";
import { findTool, tools, type ${P}Handle } from "./tools.js";

export interface McpServerConfig {
  handle: ${P}Handle;
  name?: string;
  version?: string;
}

export function createYorishiro${P}McpServer(config: McpServerConfig): Server {
  const server = new Server(
    { name: config.name ?? "etzhayyim-yorishiro-${args.name}", version: config.version ?? "0.1.0" },
    { capabilities: { tools: {} } },
  );

  server.setRequestHandler(ListToolsRequestSchema, async () => ({
    tools: tools.map((t) => ({ name: t.name, title: t.title, description: t.description, inputSchema: t.jsonSchema })),
  }));

  server.setRequestHandler(CallToolRequestSchema, async (req) => {
    const tool = findTool(req.params.name);
    if (!tool) return { isError: true, content: [{ type: "text", text: \`Unknown tool: \${req.params.name}\` }] };
    const parsed = tool.inputSchema.safeParse(req.params.arguments ?? {});
    if (!parsed.success) return { isError: true, content: [{ type: "text", text: \`InvalidInput: \${parsed.error.toString()}\` }] };
    try {
      const out = await tool.invoke(config.handle, parsed.data);
      return { content: [{ type: "text", text: JSON.stringify(out) }] };
    } catch (err) {
      return { isError: true, content: [{ type: "text", text: \`InvokeError: \${(err as Error).message}\` }] };
    }
  });
  return server;
}
`;
}

function renderTools(args: EmitArgs): string {
  const P = pascal(args.name);

  const handleSig = args.manifest.ops
    .map((op) => `  ${snake(op.name)}(input: ${P}${pascal(op.name)}Input): Promise<${P}${pascal(op.name)}Output>;`)
    .join("\n");

  const schemas = args.manifest.ops
    .map((op) => {
      const required = new Set<string>();
      for (const s of op.steps as BrowserStep[]) {
        if (s.kind === "fill" || s.kind === "select") required.add(s.value_input_key);
      }
      const props = Array.from(required)
        .map((k) => `    ${quoteKey(k)}: z.string(),`)
        .join("\n");
      const inputType = `${P}${pascal(op.name)}Input`;
      const outputType = `${P}${pascal(op.name)}Output`;
      const extractKeys = (op.extract ?? []).map((e) => `  ${quoteKey(e.output_key)}?: ${e.multiple ? "string[]" : "string"};`).join("\n");
      return `// ── ${op.name} ─────────────────────────────────────────────────────────
export const ${snake(op.name)}InputSchema = z.object({
${props || "  // (no input fields — pure-extract op)"}
});
export type ${inputType} = z.infer<typeof ${snake(op.name)}InputSchema>;

export interface ${outputType} {
  ok: boolean;
  error?: string;
${extractKeys}
}
`;
    })
    .join("\n");

  const toolEntries = args.manifest.ops
    .map(
      (op) => `  {
    name: ${JSON.stringify(snake(op.name))},
    title: ${JSON.stringify(op.summary || op.name)},
    description: ${JSON.stringify(op.description || op.summary || op.name)},
    inputSchema: ${snake(op.name)}InputSchema,
    jsonSchema: zodToJsonSchemaShim(${snake(op.name)}InputSchema),
    invoke: async (handle, input) => handle.${snake(op.name)}(input as ${P}${pascal(op.name)}Input),
  },`,
    )
    .join("\n");

  return `import { z, type ZodObject } from "zod";

export interface ${P}Handle {
${handleSig}
}

${schemas}

export interface ToolDefinition {
  name: string;
  title: string;
  description: string;
  inputSchema: ZodObject<Record<string, z.ZodTypeAny>>;
  jsonSchema: unknown;
  invoke: (handle: ${P}Handle, input: unknown) => Promise<unknown>;
}

function zodToJsonSchemaShim(schema: ZodObject<Record<string, z.ZodTypeAny>>): unknown {
  const shape = (schema as unknown as { shape: Record<string, z.ZodTypeAny> }).shape;
  const props: Record<string, unknown> = {};
  const required: string[] = [];
  for (const [k, v] of Object.entries(shape)) {
    const def = (v as unknown as { _def: { typeName?: string } })._def;
    const t = (def?.typeName ?? "").replace(/^Zod/, "").toLowerCase();
    props[k] = { type: t === "boolean" ? "boolean" : t === "number" || t === "bigint" ? "number" : "string" };
    if (!(v as unknown as { isOptional?: () => boolean }).isOptional?.()) required.push(k);
  }
  return { type: "object", properties: props, required };
}

export const tools: ToolDefinition[] = [
${toolEntries}
];

export function findTool(name: string): ToolDefinition | undefined {
  return tools.find((t) => t.name === name);
}
`;
}

function renderHandle(args: EmitArgs): string {
  const P = pascal(args.name);

  const methods = args.manifest.ops
    .map((op) => {
      const opSnake = snake(op.name);
      const steps = (op.steps as BrowserStep[]).map((s) => renderStepTs(s)).join("\n");
      const extracts = (op.extract ?? [])
        .map((e) => {
          const sel = JSON.stringify(e.selector);
          const key = JSON.stringify(e.output_key);
          // 6-space indent — same scope as the step calls above.
          if (e.multiple) return `      out[${key}] = await page.locator(${sel}).allTextContents();`;
          if (e.attribute) return `      out[${key}] = (await page.locator(${sel}).first().getAttribute(${JSON.stringify(e.attribute)})) ?? undefined;`;
          return `      out[${key}] = (await page.locator(${sel}).first().textContent()) ?? undefined;`;
        })
        .join("\n");
      return `  async ${opSnake}(input) {
    const out: Record<string, unknown> = { ok: false };
    let browser;
    try {
      browser = await chromium.launch({ headless: true });
      const ctx = await browser.newContext();
      const page = await ctx.newPage();
${steps}
${extracts || "      // (no extract entries — op runs for side effects only)"}
      out.ok = true;
    } catch (err) {
      out.error = (err as Error).message;
    } finally {
      try { await browser?.close(); } catch { /* noop */ }
    }
    return out as ${P}${pascal(op.name)}Output;
  },`;
    })
    .join("\n");

  return `import { chromium } from "playwright";
import type { ${P}Handle, ${args.manifest.ops.map((o) => `${P}${pascal(o.name)}Output`).join(", ")} } from "./tools.js";

export interface DefaultHandleOptions {
  baseUrl?: string;
}

export function createDefault${P}Handle(_opts: DefaultHandleOptions): ${P}Handle {
  const handle: ${P}Handle = {
${methods}
  };
  return handle;
}
`;
}

function renderStepTs(s: BrowserStep): string {
  switch (s.kind) {
    case "goto":
      return `      await page.goto(${JSON.stringify(s.url_template)});`;
    case "wait_for":
      return `      await page.waitForSelector(${JSON.stringify(s.selector)}, { timeout: ${s.timeout_ms ?? 5000} });`;
    case "fill":
      return `      await page.fill(${JSON.stringify(s.selector)}, String((input as Record<string, unknown>)[${JSON.stringify(s.value_input_key)}] ?? ""));`;
    case "click":
      return `      await page.click(${JSON.stringify(s.selector)});`;
    case "select":
      return `      await page.selectOption(${JSON.stringify(s.selector)}, String((input as Record<string, unknown>)[${JSON.stringify(s.value_input_key)}] ?? ""));`;
    case "sleep_ms":
      return `      await page.waitForTimeout(${s.ms});`;
    case "scroll_to":
      return `      await page.locator(${JSON.stringify(s.selector)}).first().scrollIntoViewIfNeeded();`;
    default:
      return `      // unknown step kind`;
  }
}

function pascal(s: string): string {
  return s.split(/[-_]/).filter(Boolean).map((p) => p[0]!.toUpperCase() + p.slice(1)).join("");
}
function snake(s: string): string {
  return s.replace(/([a-z0-9])([A-Z])/g, "$1_$2").replace(/[-]/g, "_").toLowerCase();
}
function quoteKey(k: string): string {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(k) ? k : JSON.stringify(k);
}

// emit/mcp-server.ts — L3 emitter. Produces a yorishiro-<name>-mcp package
// mirroring 40-engine/kotoba/crates/kotoba-kotodama/mcp/unispsc-isic-mcp/ (stdio + Streamable
// HTTP transport, zod 4 input schemas, handler delegation to a typed
// kami handle).

import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

import type { JsonSchema, NormalizedOp } from "../openapi/parse.js";

export interface EmitMcpArgs {
  repoRoot: string;
  name: string;
  kami: string;
  baseUrl: string;
  transport: string;
  purposes: readonly string[];
  ops: readonly NormalizedOp[];
}

export interface EmittedMcp {
  packageDir: string;
  files: string[];
}

export function emitMcpServer(args: EmitMcpArgs): EmittedMcp {
  const dir = join(args.repoRoot, "40-engine/kotoba/crates/kotoba-kotodama/mcp", `yorishiro-${args.name}-mcp`);
  mkdirSync(join(dir, "src"), { recursive: true });

  const files: string[] = [];
  const w = (rel: string, body: string) => {
    const p = join(dir, rel);
    writeFileSync(p, body, "utf-8");
    files.push(p);
  };

  w("package.json", renderPackageJson(args));
  w("tsconfig.json", renderTsconfig());
  w("README.md", renderReadme(args));
  w("src/index.ts", renderIndex(args));
  w("src/cli.ts", renderCli(args));
  w("src/server.ts", renderServer(args));
  w("src/tools.ts", renderTools(args));
  w("src/handle.ts", renderHandle(args));

  return { packageDir: dir, files };
}


;; robotics-coverage — cross-actor chain verifier + map.
;;
;; The 4 GAP actors hand off to downstream actors (niyaku→kuramori→todoke,
;; soma→tatekata, madomori→tatekata, kudamori→mizuho). This tool reads every
;; actor's handoff.clj, extracts the `:from-actor`/`:to-actor` endpoints it
;; references, and FAILS (exit 1) if any referenced actor is not a real actor
;; flat west actor checkout — drift/typo protection for the logistics chain.
;; It also emits CHAIN.md, the system-level map of the whole robotics wave.
;;
;; Run: bb 70-tools/robotics-coverage/ecosystem.clj
;; Per ADR-2606142000 (Clojure-first GAP-actor wave).
(ns robotics-coverage.ecosystem
  (:require [clojure.string :as str]
            [clojure.java.io :as io]))

(def wave-actors ["kuramori" "soma" "madomori" "kudamori"])

(defn- slurp* [p] (when (.exists (io/file p)) (slurp p)))

(defn actor-exists?
  "True iff `name` is a real flat west actor checkout."
  [name]
  (.isDirectory (io/file (str "orgs/etzhayyim/com-etzhayyim-" name))))

(defn edges-of
  "Extract directed handoff edges from one actor's handoff.clj as [from to] pairs.
   Pairs :from-actor/:to-actor WITHIN the same builder map (in either textual
   order, not crossing a map-close `}`) so a file with several builders yields one
   edge per builder rather than a cartesian product."
  [actor]
  (let [src (slurp* (str "orgs/etzhayyim/com-etzhayyim-" actor "/methods/handoff.clj"))]
    (when src
      (let [fwd (map (fn [[_ f t]] [f t])
                     (re-seq #":from-actor\s+\"([^\"]+)\"[^}]*?:to-actor\s+\"([^\"]+)\"" src))
            rev (map (fn [[_ t f]] [f t])
                     (re-seq #":to-actor\s+\"([^\"]+)\"[^}]*?:from-actor\s+\"([^\"]+)\"" src))]
        (vec (distinct (filter (fn [[f t]] (not= f t)) (concat fwd rev))))))))

(defn -main [& _]
  (let [edges (distinct (mapcat edges-of wave-actors))
        referenced (set (mapcat identity edges))
        dangling (remove actor-exists? referenced)
        chain-md
        (str "# robotics-coverage — cross-actor chain map\n\n"
             "Generated by `70-tools/robotics-coverage/ecosystem.clj`. Every edge is a "
             "`:handoff/*` 縁 a GAP actor emits to a downstream actor; the verifier fails "
             "if any endpoint is not a real flat west actor checkout.\n\n"
             "## Edges\n\n"
             "| from | → | to | actors real? |\n|---|---|---|---|\n"
             (str/join "\n"
               (for [[f t] (sort edges)]
                 (format "| %s | → | %s | %s |" f t
                         (if (and (actor-exists? f) (actor-exists? t)) "✓" "✗ DANGLING"))))
             "\n\n"
             (format "**Chain**: %d edges across %d referenced actors; %d dangling.\n"
                     (count edges) (count referenced) (count dangling)))]
    (spit "70-tools/robotics-coverage/CHAIN.md" chain-md)
    (println "robotics-coverage chain → 70-tools/robotics-coverage/CHAIN.md")
    (doseq [[f t] (sort edges)]
      (println (format "  %-10s → %-10s %s" f t
                       (if (and (actor-exists? f) (actor-exists? t)) "✓" "✗ DANGLING"))))
    (when (seq dangling)
      (println "DANGLING actor references (not a flat west checkout):" (vec dangling)))
    (System/exit (if (seq dangling) 1 0))))

(apply -main *command-line-args*)

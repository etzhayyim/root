#!/usr/bin/env node
// Emit per-project defence-handlers.ts modules from defence-catalog.tsv.
//
// Phase 2 of the BPMN→CF Worker migration (90-docs/260425-bpmn-to-cf-worker-migration-design.md).
// Reads the catalog, groups by project, and writes
// `60-apps/etzhayyim-project-{project}/worker/src/defence-handlers.ts`
// for each project. The file exports one async function per NSID plus a
// `defenceRoutes` map (`Record<NSID, handler>`). The project's existing
// `app.ts` can `import { defenceRoutes }` and merge into its existing
// switch — no rewrite of unrelated handlers required.
//
// Projects without a worker directory get a minimal scaffold (skipped here
// for visibility — see TODO at end of file).

import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const repoRoot = path.resolve(__dirname, "..", "..", "..");
const catalogPath = path.join(__dirname, "defence-catalog.tsv");

const tsv = readFileSync(catalogPath, "utf8");
const lines = tsv.trim().split("\n");
const header = lines[0].split("\t");
const idx = (k) => header.indexOf(k);

const entries = lines.slice(1).map((line) => {
  const cols = line.split("\t");
  return {
    project: cols[idx("project")],
    proc: cols[idx("proc")],
    nsidNs: cols[idx("nsidNs")],
    bpmnId: cols[idx("bpmnId")],
    jpName: cols[idx("jpName")],
    actionName: cols[idx("actionName")],
    subjectField: cols[idx("subjectField")],
    severity: cols[idx("severity")],
  };
});

// Group by project
const byProject = new Map();
for (const e of entries) {
  const arr = byProject.get(e.project) ?? [];
  arr.push(e);
  byProject.set(e.project, arr);
}

let written = 0;
let skipped = 0;
const summary = [];

for (const [project, procs] of byProject) {
  const projDir = path.join(repoRoot, "60-apps", `etzhayyim-project-${project}`, "worker");
  if (!existsSync(projDir)) {
    skipped++;
    summary.push({ project, status: "skipped (no worker dir)", count: procs.length });
    continue;
  }

  const srcDir = path.join(projDir, "src");
  if (!existsSync(srcDir)) mkdirSync(srcDir, { recursive: true });

  const lines = [
    `// Defence cluster handlers — generated by gen-defence-cfworker.mjs.`,
    `// Source: 70-tools/scripts/contract/defence-catalog.tsv`,
    `// Catalog wave 1-5 (105 NSIDs). This file holds the ${procs.length} handler${procs.length === 1 ? "" : "s"} owned by ${project}.`,
    `//`,
    `// Wire into app.ts with:`,
    `//   import { defenceRoutes } from "./defence-handlers";`,
    `//   const handler = defenceRoutes[nsid]; if (handler) return handler(env, body);`,
    `//`,
    `// All handlers write a single row to vertex_open_defence_event via Hyperdrive,`,
    `// then return { ok: true, vertexId, severity } as JSON. PDS routing should`,
    `// prefer this Worker over the legacy BPMN binding (see migration doc).`,
    `import { Pool } from "pg";`,
    ``,
    `export interface DefenceEnv {`,
    `  HYPERDRIVE: { connectionString: string };`,
    `  PRIMARY_DID?: string;`,
    `  APP_HANDLE?: string;`,
    `}`,
    ``,
    `let _pool: Pool | null = null;`,
    `function pool(env: DefenceEnv): Pool {`,
    `  if (_pool) return _pool;`,
    `  _pool = new Pool({`,
    `    connectionString: env.HYPERDRIVE.connectionString,`,
    `    max: 5,`,
    `    idleTimeoutMillis: 30_000,`,
    `    connectionTimeoutMillis: 10_000,`,
    `  });`,
    `  return _pool;`,
    `}`,
    ``,
    `function nanoid(len = 12): string {`,
    `  const a = "abcdefghijklmnopqrstuvwxyz0123456789";`,
    `  const b = crypto.getRandomValues(new Uint8Array(len));`,
    `  let o = ""; for (let i = 0; i < len; i++) o += a[b[i] % a.length]; return o;`,
    `}`,
    ``,
    `async function insertDefenceEvent(env: DefenceEnv, params: {`,
    `  vertexId: string; project: string; nsid: string; bpmnProcessId: string;`,
    `  subjectVid: string | null; actionClass: string; severity: string; callerDid: string;`,
    `}) {`,
    `  const now = new Date().toISOString();`,
    `  await pool(env).query(`,
    `    \`INSERT INTO vertex_open_defence_event`,
    `       (vertex_id, owner_did, bpmn_process_id, nsid, project, subject_vid,`,
    `        action_class, severity, detected_at, created_at,`,
    `        sensitivity_ord, org_id, user_id, actor_id)`,
    `     VALUES ($1::varchar, $2::varchar, $3::varchar, $4::varchar, $5::varchar, $6::varchar,`,
    `             $7::varchar, $8::varchar, $9::varchar, $10::varchar,`,
    `             1, $11::varchar, $11::varchar, $12::varchar)`,
    `     ON CONFLICT DO NOTHING\`,`,
    `    [`,
    `      params.vertexId,`,
    `      params.callerDid,`,
    `      params.bpmnProcessId,`,
    `      params.nsid,`,
    `      params.project,`,
    `      params.subjectVid,`,
    `      params.actionClass,`,
    `      params.severity,`,
    `      now,`,
    `      now,`,
    `      params.callerDid,`,
    `      \`open-defence.\${params.project}\`,`,
    `    ],`,
    `  );`,
    `}`,
    ``,
  ];

  // Per-NSID handler
  for (const e of procs) {
    const nsid = `com.etzhayyim.apps.${e.nsidNs}.${e.proc}`;
    const handlerName = `handle_${e.proc}`;
    lines.push(
      `// ${nsid} — ${e.jpName}`,
      `export async function ${handlerName}(env: DefenceEnv, body: any): Promise<Response> {`,
      `  const callerDid = body?.callerDid ?? env.PRIMARY_DID ?? "did:web:anon";`,
      `  const subjectVid = body?.${e.subjectField} ?? null;`,
      `  const vertexId = body?.vertexId ?? \`at://\${callerDid}/${nsid}/\${nanoid(12)}\`;`,
      `  try {`,
      `    await insertDefenceEvent(env, {`,
      `      vertexId,`,
      `      project: "${e.project}",`,
      `      nsid: "${nsid}",`,
      `      bpmnProcessId: "${e.bpmnId}",`,
      `      subjectVid,`,
      `      actionClass: "${e.actionName}",`,
      `      severity: "${e.severity}",`,
      `      callerDid,`,
      `    });`,
      `    return new Response(JSON.stringify({ ok: true, vertexId, severity: "${e.severity}" }), {`,
      `      status: 200, headers: { "content-type": "application/json" },`,
      `    });`,
      `  } catch (e: any) {`,
      `    return new Response(JSON.stringify({ ok: false, error: String(e?.message ?? e) }), {`,
      `      status: 500, headers: { "content-type": "application/json" },`,
      `    });`,
      `  }`,
      `}`,
      ``,
    );
  }

  // Routes map for app.ts merge
  lines.push(
    `export const defenceRoutes: Record<string, (env: DefenceEnv, body: any) => Promise<Response>> = {`,
    ...procs.map(
      (e) => `  "com.etzhayyim.apps.${e.nsidNs}.${e.proc}": handle_${e.proc},`,
    ),
    `};`,
    ``,
  );

  const outPath = path.join(srcDir, "defence-handlers.ts");
  writeFileSync(outPath, lines.join("\n"));
  written++;
  summary.push({ project, status: "written", count: procs.length, path: path.relative(repoRoot, outPath) });
}

console.log(JSON.stringify({ written, skipped, total: byProject.size, projects: summary }, null, 2));

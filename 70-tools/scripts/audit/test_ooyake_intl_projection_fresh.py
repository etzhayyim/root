"""Fail-closed FRESHNESS invariant for the ooyake (公) ↔ toritsugi (取次) projection.

`20-actors/ooyake/registry/gov-units.intl-procedures.seed.edn` is AUTO-GENERATED by
`20-actors/ooyake/scripts/gen_intl_procedures.py` from the toritsugi registry. If a
maintainer edits the toritsugi procedures but forgets to re-run the generator, the
committed atlas projection drifts silently — new procedures never appear in the
atlas, removed ones linger as ghosts. This suite catches that drift WITHOUT
mutating the committed file: it recomputes the expected projection in-memory (via
the generator's own pure helpers) and asserts the committed file matches.

Invariants:
  1. The set of toritsugi procedureIds projected into the committed atlas file
     EXACTLY equals the set the generator would project today (no missing/ghost).
  2. Every committed projection row's owner-unit equals the owner the generator
     would assign (country-level gov.<iso>, or the documented override e.g.
     eu-wide -> gov.eu) — owner-unit drift fails.

R0-safe: test-only, deterministic, network-free. Imports only the generator's
pure helpers; never calls main() (so it never writes to disk).
"""

from __future__ import annotations

import os
import sys
from pathlib import Path

_REPO = Path(__file__).resolve().parents[3]
_OOYAKE_SCRIPTS = _REPO / "20-actors" / "ooyake" / "scripts"
_RECONCILE = _REPO / "20-actors" / "ooyake" / "cells" / "reconcile"
_INTL = _REPO / "20-actors" / "ooyake" / "registry" / "gov-units.intl-procedures.seed.edn"
_TORITSUGI_ROOT = Path(os.environ.get("ETZHAYYIM_TORITSUGI_ROOT", _REPO.parent / "com-etzhayyim-toritsugi"))
_TORITSUGI = _TORITSUGI_ROOT / "registry" / "procedures.seed.edn"

sys.path.insert(0, str(_RECONCILE))
sys.path.insert(0, str(_OOYAKE_SCRIPTS))
import gen_intl_procedures as gen  # noqa: E402
from cell import parse_edn  # noqa: E402


def _committed_rows() -> list[dict]:
    return parse_edn(_INTL.read_text()).get(":procedures", [])


def _expected_projection() -> dict[str, str]:
    """toritsugi procedureId -> expected owner-unit, per the generator's rules."""
    units = gen._atlas_units()
    tor = parse_edn(_TORITSUGI.read_text())["procedures"]
    out = {}
    for p in tor:
        iso = p["jurisdiction"]
        if iso == "jpn":
            continue  # hand-authored elsewhere
        owner = gen._owner_for(iso, units)
        if owner:
            out[p["procedureId"]] = owner
    return out


def test_projection_is_fresh_no_missing_or_ghost():
    expected = _expected_projection()
    committed = {
        r.get(":gov.procedure/toritsugi-ref")
        for r in _committed_rows()
        if r.get(":gov.procedure/toritsugi-ref")
    }
    missing = set(expected) - committed   # toritsugi added, generator not re-run
    ghost = committed - set(expected)     # toritsugi removed, atlas still has it
    assert not missing and not ghost, (
        "atlas intl projection is STALE — re-run "
        "`python3 20-actors/ooyake/scripts/gen_intl_procedures.py`.\n"
        f"missing (in toritsugi, not projected): {sorted(missing)}\n"
        f"ghost (projected, not in toritsugi): {sorted(ghost)}"
    )


def test_projection_owner_units_match_generator():
    expected = _expected_projection()
    drift = []
    for r in _committed_rows():
        ref = r.get(":gov.procedure/toritsugi-ref")
        owner = r.get(":gov.procedure/owner-unit")
        if ref in expected and owner != expected[ref]:
            drift.append((ref, owner, expected[ref]))
    assert not drift, (
        "owner-unit drift vs generator (ref, committed, expected) — re-run the "
        f"generator: {drift}"
    )


if __name__ == "__main__":
    import pytest

    raise SystemExit(pytest.main([__file__, "-v"]))

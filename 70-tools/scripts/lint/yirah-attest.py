#!/usr/bin/env python3
"""yirah-attest — yir'ah invariant-bundle attestation scanner (ADR-2606112200 D4).

知識は神の畏れから始まる (箴言1:7). ADR-2606112200 D4 canonizes five epistemic
invariants as the engineered form of yir'ah, plus D3 NEVER-a-throne:

  non-adjudicating · distribution-not-point · no-score-of-soul · map-not-target
  · append-only · never-a-throne

This scanner reads flat west actor wire manifests (gates + purpose + lineage
text) and reports, per actor, which invariants are DECLARED. Absence is not a
violation — a manufacturing actor may have nothing to forecast — so the output
is an evolution WORKLIST (which actors could adopt which declarations), never a
verdict. The scanner itself honors what it measures: it emits counts + a
declared-matrix, no per-actor score, no ranking.

Pure stdlib. Usage:
    python3 yirah-attest.py [--repo ROOT] [--out REPORT.md] [--json WORKLIST.json]
"""
from __future__ import annotations
import json
import pathlib
import re
import sys

# invariant -> declaration patterns (case-insensitive, matched over manifest text)
INVARIANTS = {
    "non-adjudicating": [
        r"non-adjudicat", r"never\s+a?\s*verdict", r"no\s+verdict", r"裁定しない",
        r"非裁定", r"adjudicat\w*\s+(is\s+)?(not|never|prohibited|unrepresentable)",
    ],
    "distribution-not-point": [
        r"distribution[- ]only", r"distribution[- ]not[- ]point", r"no[- ]forecast",
        r"never\s+forecasts?", r"band\s+not\s+point", r"point[- ]asserted.*false",
        r"skill[- ]honest", r"非終末論",
    ],
    "no-score-of-soul": [
        r"no[- ]score", r"score[- ]of[- ]soul", r"never\s+an?\s+\w*\s*(ranking|score)",
        r"no\s+(per-person|per-work|popularity|engagement)\s+(score|ranking|metric)",
        r"魂の点数化", r"no\s+retention\s+metric", r"discriminatory[- ]scoring",
    ],
    "map-not-target": [
        r"map[- ]not[- ]target", r"never\s+a?\s*target[- ]?list", r"not\s+a\s+target",
        r"標的", r"resilience[- ]map,?\s+never", r"never\s+a\s+targeting",
        r"no[- ]doxxing", r"person[- ]excluded", r"no[- ]person[- ]tracking",
    ],
    "append-only": [
        r"append[- ]only", r"no\s+right\s+to\s+erasure", r"永久記憶", r":add[- ]only",
        r"erase\s+is\s+not", r"tamper[- ]evident",
    ],
    "never-a-throne": [
        r"never[- ]a[- ]throne", r"玉座", r"aggregate[- ](only|first)",
        r"own[- ]did[- ]only", r"no\s+central", r"panopticon", r"keyless",
        r"no[- ]server[- ]key", r"no\s+platform[- ]held",
    ],
}

SKIP_DIR_SUFFIXES = ("-compat",)  # API-facade actors: thin mirrors of external specs


def scan_manifest(path: pathlib.Path) -> dict:
    text = path.read_text(encoding="utf-8", errors="replace")
    declared = {}
    for inv, pats in INVARIANTS.items():
        declared[inv] = any(re.search(p, text, re.IGNORECASE) for p in pats)
    return declared


def scan_repo(root: pathlib.Path) -> dict:
    actors = {}
    for mf in sorted(root.glob("orgs/etzhayyim/com-etzhayyim-*/wire/manifest.jsonld")):
        name = mf.parent.parent.name.removeprefix("com-etzhayyim-")
        if name.endswith(SKIP_DIR_SUFFIXES) or name.startswith("_"):
            continue
        actors[name] = scan_manifest(mf)
    return actors


def render(actors: dict) -> str:
    invs = list(INVARIANTS)
    n = len(actors)
    counts = {i: sum(1 for a in actors.values() if a[i]) for i in invs}
    L = ["---",
         "id: yirah-attest-snapshot",
         'title: "yir\'ah invariant-bundle attestation snapshot (ADR-2606112200 D4)"',
         "status: active",
         "doc_type: reference",
         "topic: yirah-attest",
         "authoritative: false",
         "last_verified: 2026-06-11",
         "---",
         "",
         "# yir'ah attestation snapshot — GENERATED by 70-tools/scripts/lint/yirah-attest.py",
         "",
         "Declared ≠ conforming, absent ≠ violating (a manufacturing actor may have",
         "nothing to forecast). This is the **evolution worklist** for the shinka loop:",
         "each row's unchecked cells are candidate declarations for that actor's next",
         "iteration — adopted only where the invariant is meaningful for its scope.",
         "No per-actor score is computed (the scanner honors no-score-of-soul).",
         "",
         f"**Actors scanned**: {n} (manifest-bearing, non-compat)",
         "",
         "| invariant | declared | coverage |",
         "|---|---|---|"]
    for i in invs:
        L.append(f"| {i} | {counts[i]}/{n} | {'█' * round(10 * counts[i] / max(n, 1))} |")
    L += ["", "## Declared-matrix (✓ = declared in manifest text)", "",
          "| actor | " + " | ".join(invs) + " |",
          "|---|" + "---|" * len(invs)]
    for name in sorted(actors):
        row = " | ".join("✓" if actors[name][i] else "·" for i in invs)
        L.append(f"| {name} | {row} |")
    L += ["", "## Worklist (actors declaring fewest bundle invariants first — count, not rank of worth)", ""]
    by_gap = sorted(actors, key=lambda a: (sum(actors[a].values()), a))
    for name in by_gap[:15]:
        missing = [i for i in invs if not actors[name][i]]
        L.append(f"- **{name}** — undeclared: {', '.join(missing)}")
    L.append("")
    return "\n".join(L)


def main(argv):
    root = pathlib.Path(argv[argv.index("--repo") + 1]) if "--repo" in argv \
        else pathlib.Path(__file__).resolve().parents[3]
    actors = scan_repo(root)
    if not actors:
        print("no actor manifests found", file=sys.stderr)
        return 1
    report = render(actors)
    out = pathlib.Path(argv[argv.index("--out") + 1]) if "--out" in argv \
        else root / "90-docs" / "yirah-attest-snapshot.md"
    out.write_text(report, encoding="utf-8")
    if "--json" in argv:
        jp = pathlib.Path(argv[argv.index("--json") + 1])
        jp.write_text(json.dumps(actors, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    invs = list(INVARIANTS)
    n = len(actors)
    for i in invs:
        c = sum(1 for a in actors.values() if a[i])
        print(f"  {i:<24} {c}/{n}")
    print(f"yirah-attest → {out} ({n} actors)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))

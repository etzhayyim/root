#!/usr/bin/env node
// Fold `90-docs/baien/multimodal-models.jsonl` (produced by
// `baien-mx-train` commit_node, ADR-2605232500) into a TypeScript
// module that the canonical llm-model-registry imports.
//
// Sibling of gen-distilled-entries.mjs — same two-phase ship pattern.
//
// Output: `40-engine/kotoba/crates/kotoba-kotodama/sdk/kotodama-host-sdk/src/llm-model-registry-multimodal.ts`
//
// One-time wiring (done by reviewer):
//   - in `llm-model-registry.ts`, import + spread:
//       import { MULTIMODAL_MODEL_REGISTRY } from "./llm-model-registry-multimodal.js";
//       export const MODEL_REGISTRY = {
//         ...MULTIMODAL_MODEL_REGISTRY,
//         ...DISTILLED_MODEL_REGISTRY,
//         /* existing entries */
//       };
//
// Run from repo root:
//   node 70-tools/scripts/llm-registry/gen-multimodal-entries.mjs

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = join(__dirname, "..", "..", "..");

const MANIFEST = join(REPO_ROOT, "90-docs", "baien", "multimodal-models.jsonl");
const OUT = join(
  REPO_ROOT,
  "20-actors", "kotodama", "sdk", "kotodama-host-sdk", "src",
  "llm-model-registry-multimodal.ts",
);

function readManifest(path) {
  if (!existsSync(path)) return [];
  return readFileSync(path, "utf8")
    .split("\n")
    .filter((l) => l.trim().length > 0)
    .map((l, i) => {
      try {
        return JSON.parse(l);
      } catch (e) {
        console.error(`[gen-multimodal] line ${i + 1} parse error:`, e.message);
        return null;
      }
    })
    .filter(Boolean);
}

function pickLatestPerModelId(entries) {
  const byId = new Map();
  for (const e of entries) {
    const prev = byId.get(e.model_id);
    if (!prev || (e.ts ?? "") > (prev.ts ?? "")) byId.set(e.model_id, e);
  }
  return [...byId.values()].sort((a, b) => a.model_id.localeCompare(b.model_id));
}

function entryToTs(e) {
  const lines = [];
  lines.push(`  // ${e.kind} phase=${e.phase ?? "?"} iter=${e.iter ?? "?"} — image-encoder ${e.imageEncoder ?? "?"}`);
  lines.push(`  // base:      ${e.huggingfaceModel}`);
  lines.push(`  // projector: ${e.projectorPath}`);
  lines.push(`  // dataset:   ${e.trainJsonl ?? "?"} (sha256 ${e.datasetHash?.slice(0, 12) ?? "?"})`);
  lines.push(`  // eval:      visual=${e.visualMicrobenchPassRate ?? "n/a"} text_dpp=${e.textMicrobenchDeltaPp ?? "n/a"} loss=${e.finalLoss ?? "n/a"}`);
  lines.push(`  // decision:  ${e.decision ?? "?"} — review before flipping available=true`);
  lines.push(`  "${e.model_id}": {`);
  lines.push(`    cfModel: "huggingface:${e.huggingfaceModel}",`);
  lines.push(`    huggingfaceModel: ${JSON.stringify(e.huggingfaceModel)},`);
  lines.push(`    maxTokens: 2048,`);
  lines.push(`    contextWindow: 4096,`);
  lines.push(`    useCases: ${JSON.stringify(e.useCases ?? ["edge", "image"])},`);
  lines.push(`    available: ${e.available === true ? "true" : "false"},`);
  lines.push(`  },`);
  return lines.join("\n");
}

function main() {
  const raw = readManifest(MANIFEST);
  if (raw.length === 0) {
    console.error(`[gen-multimodal] no entries at ${MANIFEST} — nothing to do`);
    process.exit(0);
  }
  const entries = pickLatestPerModelId(raw);

  const header = [
    "// AUTO-GENERATED by 70-tools/scripts/llm-registry/gen-multimodal-entries.mjs",
    "// Source manifest: 90-docs/baien/multimodal-models.jsonl",
    "// Do not edit by hand — re-run the codegen to refresh.",
    "// Per ADR-2605232500 (Move 1 image graft) + ADR-2605231300 §commit_node pattern.",
    "",
    'import type { ModelDef } from "./llm-model-types.js";',
    "",
    "export const MULTIMODAL_MODEL_REGISTRY: Record<string, ModelDef> = {",
  ].join("\n");

  const body = entries.map(entryToTs).join("\n\n");

  const footer = [
    "};",
    "",
    "/** Per-entry provenance (image encoder, projector path, eval scores). */",
    "export const MULTIMODAL_MODEL_PROVENANCE: Record<string, {",
    "  imageEncoder: string;",
    "  projectorPath: string;",
    "  datasetHash: string | null;",
    "  nTrainRows: number | null;",
    "  phase: string | null;",
    "  finalLoss: number | null;",
    "  visualMicrobenchPassRate: number | null;",
    "  textMicrobenchDeltaPp: number | null;",
    "  iter: number | null;",
    "  ts: string;",
    "}> = {",
    ...entries.map((e) =>
      `  "${e.model_id}": {`
      + ` imageEncoder: ${JSON.stringify(e.imageEncoder ?? "")},`
      + ` projectorPath: ${JSON.stringify(e.projectorPath ?? "")},`
      + ` datasetHash: ${JSON.stringify(e.datasetHash ?? null)},`
      + ` nTrainRows: ${e.nTrainRows ?? null},`
      + ` phase: ${JSON.stringify(e.phase ?? null)},`
      + ` finalLoss: ${e.finalLoss ?? null},`
      + ` visualMicrobenchPassRate: ${e.visualMicrobenchPassRate ?? null},`
      + ` textMicrobenchDeltaPp: ${e.textMicrobenchDeltaPp ?? null},`
      + ` iter: ${e.iter ?? null},`
      + ` ts: ${JSON.stringify(e.ts)} },`
    ),
    "};",
    "",
  ].join("\n");

  const ts = `${header}\n${body}\n${footer}`;
  writeFileSync(OUT, ts, "utf8");
  console.error(`[gen-multimodal] wrote ${entries.length} entries → ${OUT}`);
  for (const e of entries) {
    console.error(`  - ${e.model_id} (available=${e.available === true}, phase=${e.phase})`);
  }
}

main();

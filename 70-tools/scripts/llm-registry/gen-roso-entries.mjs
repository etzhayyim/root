#!/usr/bin/env node
// Fold `90-docs/baien/roso-models.jsonl` (produced by roso-distill
// commit_node, ADR-2605242000) into a TypeScript module that the canonical
// llm-model-registry imports.
//
// Sibling of gen-distilled-entries.mjs + gen-multimodal-entries.mjs — same
// 2-phase ship pattern (Python manifest → reviewer-gated TS module).
//
// Output: `40-engine/kotoba/crates/kotoba-kotodama/sdk/kotodama-host-sdk/src/llm-model-registry-roso.ts`
//
// One-time wiring (done by reviewer):
//   - in `llm-model-registry.ts`, import + spread:
//       import { ROSO_MODEL_REGISTRY } from "./llm-model-registry-roso.js";
//       export const MODEL_REGISTRY = {
//         ...ROSO_MODEL_REGISTRY,
//         ...MULTIMODAL_MODEL_REGISTRY,
//         ...DISTILLED_MODEL_REGISTRY,
//         /* existing entries */
//       };
//
// Run from repo root:
//   node 70-tools/scripts/llm-registry/gen-roso-entries.mjs

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = join(__dirname, "..", "..", "..");

const MANIFEST = join(REPO_ROOT, "90-docs", "baien", "roso-models.jsonl");
const OUT = join(
  REPO_ROOT,
  "20-actors", "kotodama", "sdk", "kotodama-host-sdk", "src",
  "llm-model-registry-roso.ts",
);

function readManifest(path) {
  if (!existsSync(path)) return [];
  return readFileSync(path, "utf8")
    .split("\n")
    .filter((l) => l.trim().length > 0)
    .map((l, i) => {
      try {
        return JSON.parse(l);
      } catch (e) {
        console.error(`[gen-roso] line ${i + 1} parse error:`, e.message);
        return null;
      }
    })
    .filter(Boolean);
}

function pickLatestPerModelId(entries) {
  const byId = new Map();
  for (const e of entries) {
    const prev = byId.get(e.model_id);
    if (!prev || (e.ts ?? "") > (prev.ts ?? "")) byId.set(e.model_id, e);
  }
  return [...byId.values()].sort((a, b) => a.model_id.localeCompare(b.model_id));
}

function entryToTs(e) {
  const lines = [];
  lines.push(`  // ${e.kind} from ${e.base_model} (${e.quant_method}, phase ${e.phase})`);
  lines.push(`  // packed: ${e.packedGB ?? "?"} GB | RAM @4k: ${e.ram4kGB ?? "?"} GB | RAM @16k: ${e.ram16kGB ?? "?"} GB`);
  lines.push(`  // edge-invariant pass: ${e.edgeInvariantPassed === true}`);
  lines.push(`  // recovery: ${e.recoveryDatasets?.join(", ") || "(phase A, no recovery)"}`);
  lines.push(`  // quantized weights: ${e.quantizedPath}`);
  lines.push(`  // decision: ${e.decision ?? "?"} — review before flipping available=true`);
  lines.push(`  "${e.model_id}": {`);
  lines.push(`    cfModel: "huggingface:${e.base_model}",`);
  lines.push(`    huggingfaceModel: ${JSON.stringify(e.base_model)},`);
  lines.push(`    maxTokens: 4096,`);
  lines.push(`    contextWindow: 16384,`);
  lines.push(`    useCases: ${JSON.stringify(e.useCases ?? ["edge", "browser", "cpu"])},`);
  lines.push(`    available: ${e.available === true ? "true" : "false"},`);
  lines.push(`  },`);
  return lines.join("\n");
}

function main() {
  const raw = readManifest(MANIFEST);
  if (raw.length === 0) {
    console.error(`[gen-roso] no entries at ${MANIFEST} — nothing to do`);
    process.exit(0);
  }
  const entries = pickLatestPerModelId(raw);

  const header = [
    "// AUTO-GENERATED by 70-tools/scripts/llm-registry/gen-roso-entries.mjs",
    "// Source manifest: 90-docs/baien/roso-models.jsonl",
    "// Do not edit by hand — re-run the codegen to refresh.",
    "// Per ADR-2605242000 (Bonsai-pattern 1-bit siblings) + ADR-2605241900 (edge invariant).",
    "",
    'import type { ModelDef } from "./llm-model-types.js";',
    "",
    "export const ROSO_MODEL_REGISTRY: Record<string, ModelDef> = {",
  ].join("\n");

  const body = entries.map(entryToTs).join("\n\n");

  const footer = [
    "};",
    "",
    "/** Per-entry provenance (base, quant_method, attestation, recovery). */",
    "export const ROSO_MODEL_PROVENANCE: Record<string, {",
    "  baseModel: string;",
    "  quantMethod: string;",
    "  phase: string;",
    "  quantizedPath: string | null;",
    "  recoveryDatasets: string[];",
    "  recoveryFinalLoss: number | null;",
    "  packedGB: number | null;",
    "  ram4kGB: number | null;",
    "  ram16kGB: number | null;",
    "  edgeInvariantPassed: boolean;",
    "  iter: number;",
    "  ts: string;",
    "}> = {",
    ...entries.map((e) =>
      `  "${e.model_id}": {`
      + ` baseModel: ${JSON.stringify(e.base_model)},`
      + ` quantMethod: ${JSON.stringify(e.quant_method)},`
      + ` phase: ${JSON.stringify(e.phase ?? "A")},`
      + ` quantizedPath: ${JSON.stringify(e.quantizedPath ?? null)},`
      + ` recoveryDatasets: ${JSON.stringify(e.recoveryDatasets ?? [])},`
      + ` recoveryFinalLoss: ${e.recoveryFinalLoss ?? null},`
      + ` packedGB: ${e.packedGB ?? null},`
      + ` ram4kGB: ${e.ram4kGB ?? null},`
      + ` ram16kGB: ${e.ram16kGB ?? null},`
      + ` edgeInvariantPassed: ${e.edgeInvariantPassed === true},`
      + ` iter: ${e.iter ?? 0},`
      + ` ts: ${JSON.stringify(e.ts)} },`
    ),
    "};",
    "",
  ].join("\n");

  const ts = `${header}\n${body}\n${footer}`;
  writeFileSync(OUT, ts, "utf8");
  console.error(`[gen-roso] wrote ${entries.length} entries → ${OUT}`);
  for (const e of entries) {
    console.error(`  - ${e.model_id} (available=${e.available === true}, phase=${e.phase}, pass=${e.edgeInvariantPassed})`);
  }
}

main();

#!/usr/bin/env node
// Fold `90-docs/baien/distilled-models.jsonl` (produced by
// `baien-distill` commit_node) into a TypeScript module that the
// canonical llm-model-registry imports.
//
// Two-phase by design:
//   1. Python loop appends a JSONL line on commit.
//   2. This codegen turns it into reviewable TS — the operator can
//      eyeball the diff, flip `available: true`, and PR it before any
//      runtime starts routing requests to the new adapter.
//
// Output: `40-engine/kotoba/crates/kotoba-kotodama/sdk/kotodama-host-sdk/src/llm-model-registry-distilled.ts`
//
// One-time wiring (done by reviewer):
//   - in `llm-model-registry.ts`, import + spread:
//       import { DISTILLED_MODEL_REGISTRY } from "./llm-model-registry-distilled.js";
//       export const MODEL_REGISTRY = { ...DISTILLED_MODEL_REGISTRY, /* existing entries */ };
//
// Run from repo root:
//   node 70-tools/scripts/llm-registry/gen-distilled-entries.mjs

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = join(__dirname, "..", "..", "..");

const MANIFEST = join(REPO_ROOT, "90-docs", "baien", "distilled-models.jsonl");
const OUT = join(
  REPO_ROOT,
  "20-actors", "kotodama", "sdk", "kotodama-host-sdk", "src",
  "llm-model-registry-distilled.ts",
);

function readManifest(path) {
  if (!existsSync(path)) return [];
  return readFileSync(path, "utf8")
    .split("\n")
    .filter((l) => l.trim().length > 0)
    .map((l, i) => {
      try {
        return JSON.parse(l);
      } catch (e) {
        console.error(`[gen-distilled] line ${i + 1} parse error:`, e.message);
        return null;
      }
    })
    .filter(Boolean);
}

function pickLatestPerModelId(entries) {
  // If a model_id is appended twice (re-run, recovery), keep the latest.
  const byId = new Map();
  for (const e of entries) {
    const prev = byId.get(e.model_id);
    if (!prev || (e.ts ?? "") > (prev.ts ?? "")) byId.set(e.model_id, e);
  }
  return [...byId.values()].sort((a, b) => a.model_id.localeCompare(b.model_id));
}

function entryToTs(e) {
  const lines = [];
  lines.push(`  // ${e.kind} iter ${e.iter} — teacher ${e.teacher_model ?? "n/a"}`);
  lines.push(`  // license: ${e.teacher_license ?? "?"} — review before flipping available=true`);
  lines.push(`  // adapter:  ${e.adapterPath}`);
  lines.push(`  // merged:   ${e.mergedPath}`);
  lines.push(`  "${e.model_id}": {`);
  lines.push(`    cfModel: "huggingface:${e.huggingfaceModel}",`);
  lines.push(`    huggingfaceModel: ${JSON.stringify(e.huggingfaceModel)},`);
  lines.push(`    maxTokens: 2048,`);
  lines.push(`    contextWindow: 4096,`);
  lines.push(`    useCases: ${JSON.stringify(e.useCases ?? ["edge"])},`);
  lines.push(`    available: ${e.available === true ? "true" : "false"},`);
  lines.push(`  },`);
  return lines.join("\n");
}

function main() {
  const raw = readManifest(MANIFEST);
  if (raw.length === 0) {
    console.error(`[gen-distilled] no entries at ${MANIFEST} — nothing to do`);
    process.exit(0);
  }
  const entries = pickLatestPerModelId(raw);

  const header = [
    "// AUTO-GENERATED by 70-tools/scripts/llm-registry/gen-distilled-entries.mjs",
    "// Source manifest: 90-docs/baien/distilled-models.jsonl",
    "// Do not edit by hand — re-run the codegen to refresh.",
    "// Per ADR-2605231300 §6 (commit_node) + ADR-2605092350 (baien).",
    "",
    'import type { ModelDef } from "./llm-model-types.js";',
    "",
    "export const DISTILLED_MODEL_REGISTRY: Record<string, ModelDef> = {",
  ].join("\n");

  const body = entries.map(entryToTs).join("\n\n");

  const footer = [
    "};",
    "",
    "/** Provenance per distilled entry (for audit / license tracking). */",
    "export const DISTILLED_MODEL_PROVENANCE: Record<string, {",
    "  teacherModel: string | null;",
    "  teacherLicense: string | null;",
    "  iter: number;",
    "  adapterPath: string;",
    "  mergedPath: string;",
    "  ts: string;",
    "}> = {",
    ...entries.map((e) =>
      `  "${e.model_id}": {`
      + ` teacherModel: ${JSON.stringify(e.teacher_model ?? null)},`
      + ` teacherLicense: ${JSON.stringify(e.teacher_license ?? null)},`
      + ` iter: ${e.iter},`
      + ` adapterPath: ${JSON.stringify(e.adapterPath)},`
      + ` mergedPath: ${JSON.stringify(e.mergedPath)},`
      + ` ts: ${JSON.stringify(e.ts)} },`
    ),
    "};",
    "",
  ].join("\n");

  const ts = `${header}\n${body}\n${footer}`;
  writeFileSync(OUT, ts, "utf8");
  console.error(
    `[gen-distilled] wrote ${entries.length} entries → ${OUT}`
  );
  for (const e of entries) {
    console.error(`  - ${e.model_id} (available=${e.available === true})`);
  }
}

main();

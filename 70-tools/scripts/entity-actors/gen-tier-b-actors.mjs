#!/usr/bin/env node
// AUTOGENERATOR for Tier-B actor registry entries (ADR-2606042330 follow-up).
//
// Scans 20-actors/<a>/manifest.jsonld for `tier == "Tier-B"` actors NOT already
// hand-authored in infra-actors.ts, and emits
//   50-infra/etzhayyim-did-web/src/registry/tier-b-actors.gen.ts
// as a Record<string, InfraActorEntry> merged into INFRA_ACTORS. This makes every
// designed Tier-B actor resolve `did:web:etzhayyim.com:actor:<handle>` and appear
// in /search — the named-actor counterpart to the entity-mirror registries.
//
// Node stdlib only. Regenerate:
//   node 70-tools/scripts/entity-actors/gen-tier-b-actors.mjs
//
import { readFileSync, writeFileSync, existsSync, readdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..", "..", "..");
const ACTORS = join(ROOT, "20-actors");
const INFRA = join(ROOT, "50-infra/etzhayyim-did-web/src/registry/infra-actors.ts");
const OUT = join(ROOT, "50-infra/etzhayyim-did-web/src/registry/tier-b-actors.gen.ts");
const GENERATED_AT = "2026-06-04T00:00:00+00:00";

// Hand-authored handles already in INFRA_ACTORS — never override these.
const infraSrc = readFileSync(INFRA, "utf8");
const HAND = new Set(
  [...infraSrc.matchAll(/^ {2}"?([a-z][a-z0-9-]*)"?:\s*\{/gm)].map((m) => m[1]),
);

// Split a displayName like "早苗 — Field-Agriculture Robotics" into {glyph, label}.
function splitDisplay(dn) {
  if (!dn) return { glyph: undefined, label: dn };
  const parts = dn.split(/\s+[—–-]\s+/);
  const head = parts[0].trim();
  // glyph = leading CJK run of the head segment
  const m = head.match(/^[　-鿿豈-﫿々〆〤ヶ]+/);
  return { glyph: m ? m[0] : undefined, label: dn };
}

// Pull ADR ids out of the manifest `adr` field (object or array of
// "etzhayyim:adr:NNN" / "NNN").
function adrIds(adr) {
  const vals = Array.isArray(adr)
    ? adr
    : adr && typeof adr === "object"
      ? Object.values(adr)
      : adr
        ? [adr]
        : [];
  const ids = [];
  for (const v of vals) {
    const s = String(v);
    const m = s.match(/(\d{8,12})/);
    if (m) ids.push(m[1]);
  }
  return [...new Set(ids)];
}

function jsEsc(s) {
  return JSON.stringify(String(s ?? ""));
}

const entries = [];
for (const a of readdirSync(ACTORS).sort()) {
  const mf = join(ACTORS, a, "manifest.jsonld");
  if (!existsSync(mf)) continue;
  let m;
  try {
    m = JSON.parse(readFileSync(mf, "utf8"));
  } catch {
    continue;
  }
  if (m.tier !== "Tier-B") continue; // actor's own self-declaration
  const handle = (m.name || a).toLowerCase();
  if (HAND.has(handle)) continue; // hand-authored wins
  if (!/^[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?$/.test(handle)) continue;
  const { glyph, label } = splitDisplay(m.displayName);
  const adrs = adrIds(m.adr);
  const desc = (m.purpose || label || handle).replace(/\s+/g, " ").trim();
  entries.push({
    handle,
    glyph,
    displayName: label || handle,
    description: desc,
    primaryLexicon:
      typeof m.primaryLexicon === "string" ? m.primaryLexicon : undefined,
    adrs,
  });
}

entries.sort((a, b) => a.handle.localeCompare(b.handle));

const body = entries
  .map((e) => {
    const lines = [`  ${jsEsc(e.handle)}: {`];
    lines.push(`    description: ${jsEsc(e.description)},`);
    if (e.glyph) lines.push(`    glyph: ${jsEsc(e.glyph)},`);
    lines.push(`    displayName: ${jsEsc(e.displayName)},`);
    if (e.primaryLexicon)
      lines.push(`    primaryLexicon: ${jsEsc(e.primaryLexicon)},`);
    lines.push(`    adrs: [${e.adrs.map(jsEsc).join(", ")}],`);
    // Every Tier-B actor advertises the shared PDS endpoint (same shape as the
    // hand-authored named actors). State is kotoba-native; this is the AAT face.
    lines.push(`    service: [`);
    lines.push(`      {`);
    lines.push(
      `        id: "did:web:etzhayyim.com:actor:${e.handle}#atproto_pds",`,
    );
    lines.push(`        type: "AtprotoPersonalDataServer",`);
    lines.push(`        serviceEndpoint: "https://pds.etzhayyim.com",`);
    lines.push(`      },`);
    lines.push(`    ],`);
    lines.push(`  },`);
    return lines.join("\n");
  })
  .join("\n");

const out = `// AUTOGENERATED — do not edit.
// Source: 20-actors/<handle>/manifest.jsonld (tier == "Tier-B").
// Regenerate: node 70-tools/scripts/entity-actors/gen-tier-b-actors.mjs
// ADR-2606042330 — register every designed Tier-B actor so its DID resolves and
// it appears in /search (the named-actor counterpart to the entity mirrors).
//
// Merged into INFRA_ACTORS (infra-actors.ts). Hand-authored entries win on a
// handle clash. State is kotoba-native; verificationMethod stays empty
// (no-server-key, ADR-2605231525) — the DID trust root is did:web TLS.

import type { InfraActorEntry } from "./infra-actors";

export const TIER_B_GENERATED_AT = ${jsEsc(GENERATED_AT)};
export const TIER_B_TOTAL_COUNT = ${entries.length};

export const TIER_B_ACTORS: Readonly<Record<string, InfraActorEntry>> = {
${body}
};
`;

writeFileSync(OUT, out);
console.log(
  `tier-b-actors.gen.ts: ${entries.length} Tier-B actors registered (${OUT.replace(ROOT + "/", "")})`,
);
for (const e of entries) console.log(`  ${e.glyph ?? "  "} ${e.handle}`);

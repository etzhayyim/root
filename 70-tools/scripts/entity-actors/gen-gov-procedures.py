#!/usr/bin/env python3
"""gen-gov-procedures.py — compile ooyake :gov.procedure records into a TS module
the apex Worker serves: government procedures published FINELY BY ADMINISTRATIVE
UNIT (per the owning gov entity-actor handle).

Reads every `orgs/etzhayyim/com-etzhayyim-ooyake/registry/gov-units*.edn` (which now carries the
JP hand-authored + the auto-projected worldwide toritsugi procedures), groups
each `:gov.procedure` under its owner gov-unit's entity-actor handle
(gov.<id> -> gov-<id>, the same transform as gen-entity-handles.mjs), and emits

    50-infra/etzhayyim-did-web/src/registry/gov-procedures.gen.ts

The Worker imports it to serve `/.well-known/gov-procedures.json` (full index)
and `/actor/<gov-handle>/procedures.json` (one administrative unit's procedures),
and to surface a procedure count on each gov entity-actor's profile.

Charter posture (mirror, ADR-2606021600 / 2606042330): this is an OBSERVATIONAL
catalog of where/how a public procedure is done — never the government, never an
official channel, never filing on anyone's behalf (that is toritsugi, gated).
Every row carries its sourcing + verification-status; all are
`:representative` / `:unverified-seed` today (G5 — never counted as authoritative
coverage). Re-run after ooyake procedure changes:

    python3 70-tools/scripts/entity-actors/gen-gov-procedures.py
"""
from __future__ import annotations

import glob
import json
import re
import sys
from pathlib import Path

_REPO = Path(__file__).resolve().parents[3]
_REG = _REPO / "20-actors" / "ooyake" / "registry"
_OUT = _REPO / "50-infra" / "etzhayyim-did-web" / "src" / "registry" / "gov-procedures.gen.ts"

sys.path.insert(0, str(_REPO / "20-actors" / "ooyake" / "cells" / "reconcile"))
from cell import parse_edn  # noqa: E402

# Fixed stamp (Date.now() unavailable / non-deterministic; keep generation pure).
_GENERATED_AT = "2026-06-05T00:00:00+00:00"


def _to_handle(unit_id: str) -> str:
    """gov.<id> -> gov-<id>: same transform as gen-entity-handles.mjs toHandle()."""
    s = unit_id.lower()
    s = re.sub(r"[._\s/]+", "-", s)
    s = re.sub(r"[^a-z0-9-]", "-", s)
    s = re.sub(r"-+", "-", s).strip("-")
    if len(s) > 63:
        s = s[:63].rstrip("-")
    return s


def _collect() -> list[dict]:
    procs = []
    for f in sorted(glob.glob(str(_REG / "gov-units*.edn"))):
        for p in parse_edn(open(f, encoding="utf-8").read()).get(":procedures", []):
            pid = p.get(":gov.procedure/id")
            owner = p.get(":gov.procedure/owner-unit")
            if not pid or not owner:
                continue
            procs.append({
                "id": pid,
                "title": p.get(":gov.procedure/title-en") or p.get(":gov.procedure/title-local") or pid,
                "titleLocal": p.get(":gov.procedure/title-local") or "",
                "ownerUnit": owner,
                "ownerHandle": _to_handle(owner),
                "jurisdiction": p.get(":gov.procedure/jurisdiction") or "",
                "authority": p.get(":gov.procedure/owner-authority") or "",
                "channel": p.get(":gov.procedure/channel") or [],
                "requiredDocs": p.get(":gov.procedure/required-docs") or [],
                "legalBasis": p.get(":gov.procedure/legal-basis") or "",
                "toritsugiRef": p.get(":gov.procedure/toritsugi-ref") or "",
                "provenance": p.get(":gov.procedure/provenance") or "",
                "sourcing": (p.get(":gov.procedure/sourcing") or ":representative").lstrip(":"),
                "verificationStatus": (p.get(":gov.procedure/verification-status") or ":unverified-seed").lstrip(":"),
            })
    procs.sort(key=lambda x: (x["ownerHandle"], x["id"]))
    return procs


def main() -> int:
    procs = _collect()
    by_owner: dict[str, list[dict]] = {}
    for p in procs:
        by_owner.setdefault(p["ownerHandle"], []).append(p)
    owners = sorted(by_owner)
    jurisdictions = sorted({p["jurisdiction"] for p in procs if p["jurisdiction"]})

    def js(o) -> str:
        return json.dumps(o, ensure_ascii=False)

    lines = [
        "// AUTOGENERATED — do not edit.",
        "// Source: ooyake :gov.procedure records (orgs/etzhayyim/com-etzhayyim-ooyake/registry/gov-units*.edn).",
        "// Regenerate: python3 70-tools/scripts/entity-actors/gen-gov-procedures.py",
        "// ADR-2606021600 (gov atlas) + 2606042330 (entity-as-actor mirror).",
        "//",
        "// Government procedures published FINELY BY ADMINISTRATIVE UNIT: each entry is",
        "// grouped under its owning gov entity-actor handle (did:web:etzhayyim.com:actor:",
        "// gov-<...>). OBSERVATIONAL MIRROR — where/how a public procedure is done; never",
        "// the government, never an official channel, never filing on anyone's behalf",
        "// (that is toritsugi, gated). All rows :representative / :unverified-seed (G5).",
        "",
        "export interface GovProcedure {",
        "  readonly id: string;",
        "  readonly title: string;",
        "  readonly titleLocal: string;",
        "  readonly ownerUnit: string;",
        "  readonly ownerHandle: string;",
        "  readonly jurisdiction: string;",
        "  readonly authority: string;",
        "  readonly channel: readonly string[];",
        "  readonly requiredDocs: readonly string[];",
        "  readonly legalBasis: string;",
        "  readonly toritsugiRef: string;",
        "  readonly provenance: string;",
        "  readonly sourcing: string;",
        "  readonly verificationStatus: string;",
        "}",
        "",
        f"export const GOV_PROCEDURES_TOTAL = {len(procs)};",
        f"export const GOV_PROCEDURES_OWNER_COUNT = {len(owners)};",
        f"export const GOV_PROCEDURES_JURISDICTION_COUNT = {len(jurisdictions)};",
        f"export const GOV_PROCEDURES_GENERATED_AT = {js(_GENERATED_AT)};",
        "",
        "// ownerHandle (gov entity-actor) → that administrative unit's procedures.",
        "export const GOV_PROCEDURES_BY_OWNER: ReadonlyMap<string, readonly GovProcedure[]> = new Map([",
    ]
    for h in owners:
        lines.append(f"  [{js(h)}, {js(by_owner[h])}],")
    lines.append("]);")
    lines.append("")
    lines.append("// Flat list (all administrative units), stable-ordered.")
    lines.append(f"export const GOV_PROCEDURE_LIST: readonly GovProcedure[] = {js(procs)};")
    lines.append("")
    _OUT.write_text("\n".join(lines), encoding="utf-8")

    print(f"wrote {_OUT.relative_to(_REPO)}")
    print(f"  procedures={len(procs)} ownerUnits={len(owners)} jurisdictions={len(jurisdictions)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

#!/usr/bin/env bash
# fleet-heartbeat — beat every locally-runnable actor's autonomous loop once.
#
# Runs each actor's `autorun.py` (the charter-permitted autonomous form: offline observe →
# analyze → persist a content-addressed transaction to the LOCAL append-only kotoba Datom
# log; ADR-2605312345). FAIL-OPEN per actor: one actor's failure never stops the fleet.
#
# DISCIPLINE (unchanged from each actor's gates):
#   - No live external I/O here — live ingest/posting stays per-actor operator/Council-gated
#     (e.g. KANJO_OPERATOR_GATE for EDGAR fetch). This script only beats the OFFLINE loops.
#   - Narration cells route Murakumo-only (ADR-2605215000) and degrade gracefully when the
#     fleet endpoint is down; this script never substitutes another LLM.
#
# LOG SEGMENTATION: each beat re-reads the whole local Datom log (head + chain verify), so an
# unbounded log makes the beat O(n) — kanjo (+~40k datoms/cycle) hit 33MB/8s within hours. When
# an actor's log exceeds LOG_ROTATE_MB the runner SEGMENTS it: the log is moved into archives/
# (a new chain segment starts at the next beat). This is segmentation, NOT erasure — the local
# heartbeat log is a deterministic, regenerable runtime artifact (each actor's .gitignore marks
# it "regenerated by autorun.py"; the canonical state is the committed seed/merged graphs), and
# the last KEEP_ARCHIVES segments are retained per actor.
#
# Usage:
#   70-tools/scripts/fleet-heartbeat/heartbeat.sh             # 1 cycle per actor
#   CYCLES=3 70-tools/scripts/fleet-heartbeat/heartbeat.sh    # N cycles per actor
#   ACTORS="shionome kanjo" 70-tools/scripts/fleet-heartbeat/heartbeat.sh   # subset
#   LOG_ROTATE_MB=8 KEEP_ARCHIVES=5 …/heartbeat.sh            # tune segmentation
set -uo pipefail

ROOT="$(cd "$(dirname "$0")/../../.." && pwd)"
HERE="$(cd "$(dirname "$0")" && pwd)"
CYCLES="${CYCLES:-1}"
LOG_ROTATE_MB="${LOG_ROTATE_MB:-16}"
KEEP_ARCHIVES="${KEEP_ARCHIVES:-3}"
# actor → autorun dir (relative to repo root). tadori is case-anchored (needs TADORI_CASE_ID)
# so it is opt-in via ACTORS rather than part of the default beat.
DEFAULT_ACTORS="shionome kanjo kabuto kosatsu keizu danjo tsumugi watari watatsuna sukashi ipaddress yabai"
ACTORS="${ACTORS:-$DEFAULT_ACTORS}"

# segment an actor's local Datom log when it exceeds the size threshold (see header)
rotate_log() {  # $1 = actor
  local log
  log=$(find "$ROOT/orgs/etzhayyim/com-etzhayyim-$1" -name "*.datoms.kotoba.edn" -not -path "*/archives/*" 2>/dev/null | head -1)
  [ -n "$log" ] && [ -f "$log" ] || return 0
  local sz_mb=$(( $(stat -f%z "$log" 2>/dev/null || stat -c%s "$log") / 1048576 ))
  [ "$sz_mb" -lt "$LOG_ROTATE_MB" ] && return 0
  mkdir -p "$HERE/archives"
  local seg="$HERE/archives/$1.$(date -u +%Y%m%dT%H%M%SZ).kotoba.edn"
  mv "$log" "$seg"
  echo "↻ $1: log segmented at ${sz_mb}MB → archives/$(basename "$seg") (fresh chain next beat)"
  # prune to the newest KEEP_ARCHIVES segments for this actor
  ls -t "$HERE/archives/$1."*.kotoba.edn 2>/dev/null | tail -n +"$((KEEP_ARCHIVES + 1))" | while read -r old; do
    rm -f "$old"
  done
}

# plain counters/strings (macOS ships bash 3.2 — empty arrays trip `set -u`)
ok_n=0; fail_n=0; failed=""
start_ts=$(date +%s)

for actor in $ACTORS; do
  dir="$ROOT/orgs/etzhayyim/com-etzhayyim-$actor/methods"
  [ -f "$dir/autorun.py" ] || dir="$ROOT/orgs/etzhayyim/com-etzhayyim-$actor/kotoba"
  if [ ! -f "$dir/autorun.py" ]; then
    echo "· $actor: no autorun.py — skipped"
    continue
  fi
  rotate_log "$actor"
  line=$(cd "$dir" && timeout 300 python3 autorun.py --cycles "$CYCLES" 2>&1 | grep -E "♥|log:" | tail -2)
  if [ -n "$line" ]; then
    echo "♥ $actor:"
    echo "$line" | sed 's/^/    /'
    ok_n=$((ok_n + 1))
  else
    echo "✗ $actor: heartbeat FAILED (no cycle output)"
    fail_n=$((fail_n + 1)); failed="$failed $actor"
  fi
done

echo
echo "── fleet-heartbeat: $ok_n beating · $fail_n failed · $(( $(date +%s) - start_ts ))s ──"
[ "$fail_n" -gt 0 ] && { echo "failed:$failed"; exit 1; }
exit 0

const NS_BY_PREFIX: ReadonlyMap<string, EntityNamespace> = new Map(
  ENTITY_NAMESPACES.map((n) => [n.ns, n]),
);

export const ENTITY_TOTAL_COUNT = ENTITY_NAMESPACES.reduce(
  (a, n) => a + n.count,
  0,
);

/** Resolve the namespace for a handle by its prefix (the segment before the
 *  first hyphen), then confirm shape. Cheap pre-filter before the Map lookup. */
function namespaceOf(handle: string): EntityNamespace | null {
  const dash = handle.indexOf("-");
  if (dash <= 0) return null;
  const ns = NS_BY_PREFIX.get(handle.slice(0, dash));
  if (!ns) return null;
  return ns.shape.test(handle) ? ns : null;
}

/** True iff `handle` is a registered entity-actor (namespace shape + membership).
 *  Used by the apex Worker's isKnownHandle to admit entity DIDs. */
export function isEntityHandle(handle: string): boolean {
  const ns = namespaceOf(handle);
  return ns ? ns.entities.has(handle) : false;
}

/** True iff `handle` MATCHES an entity namespace shape (even if not registered).
 *  Used to gate the getProfile/search short-circuit so member handles are never
 *  hijacked, and to return a registry-shaped 404 for unknown entity handles. */
export function isEntityHandleShape(handle: string): boolean {
  return namespaceOf(handle) !== null;
}

/** The mandatory observation-only mirror disclaimer (G1). Every entity-actor
 *  description opens with this — by construction, not convention. */
function mirrorDisclaimer(name: string, kindLabel: string): string {
  return (
    `Observational mirror — etzhayyim's public-fact record of ${name} ` +
    `(a ${kindLabel}). This is NOT ${name} itself and NOT an official channel ` +
    `(no impersonation; keyless, verificationMethod empty). A civic ` +
    `accountability / resilience presence, never a target-list.`
  );
}

/** Build the keyless mirror ActorRecord for a registered entity handle.
 *  Returns null if the handle is not a registered entity-actor. */
export function entityActorRecord(handle: string): ActorRecord | null {
  const ns = namespaceOf(handle);
  if (!ns) return null;
  const name = ns.entities.get(handle);
  if (name === undefined) return null;

  const did = `did:web:etzhayyim.com:actor:${handle}`;
  // service[]:
  //  - #atproto_pds: a kagami mirror IS a registered ATProto actor so it can
  //    POST its own observational mirror content AS the mirror (映す — ADR-2606232100
  //    + 2606211752 四鏡則). This is NOT impersonation: posts come from the mirror's
  //    own `did:web:etzhayyim.com:actor:<entity>` (whose profile opens with the
  //    mirrorDisclaimer "NOT <entity> itself, no impersonation"), never as the real
  //    entity. Keyless still holds — vm stays []; writes are member/operator-on-behalf
  //    + CACAO leash (no-server-key, ADR-2606072802), exactly like the named kagami
  //    lineage (tsumugi/danjo/kanae) that already post their observations.
  //  - #mirror-source-*: the owning KG actor(s) that render/maintain the mirror;
  //    there is NO per-entity server.
  const service: ActorServiceEntry[] = [
    {
      id: `${did}#atproto_pds`,
      type: "AtprotoPersonalDataServer",
      serviceEndpoint: "https://pds.aozora.app",
    },
    ...ns.owners.map((owner) => ({
      id: `${did}#mirror-source-${owner}`,
      type: "EtzhayyimMirrorSource",
      serviceEndpoint: `https://etzhayyim.com/actor/${owner}/did.json`,
    })),
  ] as ActorServiceEntry[];

  return {
    handle,
    did,
    kind: "entity-mirror",
    status: "r0",
    glyph: ns.glyph,
    displayNameEn: name,
    description: mirrorDisclaimer(name, ns.kindLabel),
    performerType: ns.performerType, // organization | system — never person (G3)
    uiType: "appview",
    primarySchema: ns.primarySchema,
    adr: ns.adr,
    service,
    vm: [], // no-server-key (G5): mirror of on-chain ERC725, never server-minted
    source: "compiled",
  };
}

export interface EntitySearchPage {
  /** the records for this page (≤ limit) */
  readonly records: ActorRecord[];
  /** offset to resume from for the next page, or null at end of results.
   *  Stringify for the searchActors `cursor` field. */
  readonly nextOffset: number | null;
  /** total number of matches across all namespaces (for `totalActors`) */
  readonly total: number;
}

/** searchActors over the entity registries with OFFSET pagination. Case-
 *  insensitive substring match on handle OR displayName, optionally restricted
 *  to namespaces. A single forward scan yields both the page window
 *  [offset, offset+limit) AND the full match `total` (so the UI can render the
 *  real count + page through all ~8,888 via the cursor). Self-contained (no
 *  firehose / no PDS) — the charter-clean way to make society scale visible on
 *  `/search` without outward publication (G8). The global ordering is stable
 *  (namespace order × each Map's sorted insertion order), so the offset cursor
 *  is consistent across requests. */
export function searchEntityActors(
  query: string,
  limit = 25,
  offset = 0,
  nsFilter?: readonly string[],
): EntitySearchPage {
  const q = query.trim().toLowerCase();
  const records: ActorRecord[] = [];
  const spaces = nsFilter?.length
    ? ENTITY_NAMESPACES.filter((n) => nsFilter.includes(n.ns))
    : ENTITY_NAMESPACES;
  let total = 0; // count of ALL matches (for totalActors)
  for (const ns of spaces) {
    for (const [handle, name] of ns.entities) {
      if (!q || handle.includes(q) || name.toLowerCase().includes(q)) {
        // window: collect only matches whose match-index ∈ [offset, offset+limit)
        if (total >= offset && records.length < limit) {
          const rec = entityActorRecord(handle);
          if (rec) records.push(rec);
        }
        total++;
      }
    }
  }
  const consumed = offset + records.length;
  return { records, nextOffset: consumed < total ? consumed : null, total };
}

/** Per-namespace summary for the `/actors` index + `/.well-known/actors.json`
 *  (so the page honestly reports society scale instead of a silent 12). */
export function entityNamespaceSummary(): Array<{
  ns: string;
  glyph: string;
  kindLabel: string;
  count: number;
  owners: readonly string[];
}> {
  return ENTITY_NAMESPACES.map((n) => ({
    ns: n.ns,
    glyph: n.glyph,
    kindLabel: n.kindLabel,
    count: n.count,
    owners: n.owners,
  }));
}

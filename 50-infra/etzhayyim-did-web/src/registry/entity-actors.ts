/**
 * Entity-as-actor mirror registry (ADR-2606042330).
 *
 * Generalizes the UNSPSC `1 entity = 1 actor` precedent (ADR-2605171300) to the
 * public/power entities datafied by the knowledge-graph actors (ooyake / kabuto
 * / tsumugi / kanjo / watatsuna / watari). Every such entity resolves a
 * **keyless mirror-actor** — `did:web:etzhayyim.com:actor:<ns>-<...>` with
 * `verificationMethod: []` — whose profile is etzhayyim's public-fact record of
 * the entity, NOT the entity itself (no impersonation, G1).
 *
 * Charter invariants enforced HERE by construction:
 *   - G1 mirror-only: every record is `isMirror`, description opens with the
 *     observation-only disclaimer, server holds no key (vm: []).
 *   - G2 public/power-only: namespaces are gov-units / public companies / cables
 *     / landing stations / craft-as-system — never a natural person.
 *   - G3 person-excluded: performerType ∈ {organization, system}; never person.
 *   - G5 no-server-key: vm: [] (mirror of on-chain ERC725, never server-minted).
 *
 * The per-namespace `entity-handles.<ns>.gen.ts` registries are AUTOGENERATED
 * from seed EDN by 70-tools/scripts/entity-actors/gen-entity-handles.mjs.
 */

